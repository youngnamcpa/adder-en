def 이상해(실, 매출):
    """매출 비 · 금액이 둘 다 전후 두 해(자기 빼고)의 중앙값의 0.5~2배 밖인 해 — 이상치 · 재분류 후보."""
    낸 = []
    해 = sorted(실)
    for i, c in enumerate(해):
        이웃 = [x for x in 해[max(0, i - 2):i] + 해[i + 1:i + 3]]
        if len(이웃) < 2:
            continue
        m금 = statistics.median([실[x] for x in 이웃])
        비들 = [실[x] / 매출[x] for x in 이웃 if 매출.get(x)]
        if not m금 or not 비들 or not 매출.get(c):
            continue
        m비 = statistics.median(비들)
        r금, r비 = 실[c] / m금, (실[c] / 매출[c]) / m비 if m비 else None
        if r비 is not None and not (0.5 <= r금 <= 2.0) and not (0.5 <= r비 <= 2.0):
            낸.append((c, r금, r비))
    return 낸


