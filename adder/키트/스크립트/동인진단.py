    물 = sorted([x for x in 판 if _물리(x["동인"]) and _자리(k, x["동인"], 지표Q)[1] is not None], key=lambda x: x["표본밖오차"])
    # 물리 동인을 매출액보다 앞세우는 것(상대 20% 안이면 물리)은 공통 창이 다섯 해 이상이고 그 동인의 탄력성 하한이 0 위일 때만 —
    # 짧은 창에서는 우연한 맞춤이 많아 물리 동인이 매출액을 20% 넘게 이겨야 한다
