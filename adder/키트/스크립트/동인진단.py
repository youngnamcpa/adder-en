def 국면범위(국면, 값):
    """국면 이름마다 **모든 구간을 합쳐** 최저 · 최고(S6-01 — 종전에는 같은 이름의 둘째 구간이 첫째를 덮어써 지난 저점 · 정점 관측이 사라졌다).
    → ({이름: [최저, 최고]}, {이름: [기간 …]})."""
    범, 구 = {}, {}
    for y in 국면 or []:
        if not isinstance(y, dict):
            continue
        이름 = y.get("이름", "?")
        xs = [(c, 값[c]) for c in y.get("기간", []) if c in 값 and isinstance(값[c], (int, float))]
        if not xs:
            continue
        a, b = 범.get(이름, [float("inf"), float("-inf")])
        범[이름] = [min(a, min(v for _, v in xs)), max(b, max(v for _, v in xs))]
        구.setdefault(이름, []).extend(c for c, _ in xs)
    return {k: [round(a, 6), round(b, 6)] for k, (a, b) in 범.items()}, 구


def _중앙(xs):
    xs = sorted(xs)
    n = len(xs)
    return (xs[n // 2] if n % 2 else (xs[n // 2 - 1] + xs[n // 2]) / 2.0) if xs else None


