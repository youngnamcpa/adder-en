def 성격확인목록(항목):
    """S4-C9 — 성격 판정은 사람이 확정한다. 도구의 판정은 초안이다 — 원가 노드마다 초안 판정과 함께, 사람이 멈춤에서 반드시 볼 것
    (자료가 성격 사전을 뒤집은 노드 · 분리 필요 · 판정 보류 · 확인 불가)을 앞에 둔 목록. 본선이 멈춤 통지에 그대로 싣는다."""
    낸 = []
    for x in 항목:
        판 = x.get("판정")
        if not ("%s" % x.get("노드", "")).startswith("원가줄"):
            continue
        if not isinstance(판, dict):
            낸.append({"노드": x["노드"], "초안": "%s" % 판, "볼것": "판정 보류 — %s" % (x.get("까닭") or "")[:80]})
            continue
        성 = 판.get("성격판정") or {}
        성.setdefault("확정", "초안 — 사람 확정 전")
        사 = (성.get("사전") or {}).get("판정")
        볼 = []
        if 성.get("판정") == "분리 필요":
            볼.append("분리 필요")
        if 사 not in (None, "모름") and 성.get("적용") and 사 != 성.get("적용"):
            볼.append("자료가 성격 사전(%s)을 %s 로 뒤집었다" % (사, 성.get("적용")))
        if 판.get("근거강도") == "추정":
            볼.append("근거 추정")
        낸.append({"노드": x["노드"], "초안": 성.get("판정"), "적용": 성.get("적용"), "볼것": " · ".join(볼)})
    return sorted(낸, key=lambda y: (not y["볼것"], y["노드"]))


