def 늦춤몫(j):
    """늦춤 꼴의 j 번째 걸음이 남은 격차를 메우는 몫 — 0.2 · 0.3 · 0.4 · 0.5 … (0.1 씩 · 0.9 까지). 가운데 해 앞(j = 연차)과
    가운데 해 뒤(j = 연차 − 가운데 해)에 같은 몫을 쓴다(다모다란 갱신 판 — N = 10 이면 누적 분율 0.0667 · 0.1467 · 0.2213 · 0.2773 · 0.3333 ·
    0.4667 · 0.6267 · 0.7760 · 0.8880 · 1)."""
    return 늦춤분율[j - 1] if j - 1 < len(늦춤분율) else min(0.9, 늦춤분율[-1] + 0.1 * (j - len(늦춤분율)))


def 경로수준(R0, RN, N, 경로):
    """연차 1 … N 의 단위 매출(목록 — 끝 = RN)."""
    경로 = 경로 or {}
    분 = 경로.get("분율")
    if isinstance(분, list) and 분:
        if len(분) != N or not all(_수(x) for x in 분) or abs(분[-1] - 1.0) > 1e-9:
            raise 짓기오류("경로.분율 은 해마다 누적 분율 %d 개이고 끝이 1 이어야 합니다 — %r" % (N, 분))
        return [R0 + (RN - R0) * f for f in 분]
    꼴 = _글(경로.get("꼴")) or "직선"
    if 꼴 == "직선":
        return [R0 + (RN - R0) * k / N for k in range(1, N + 1)]
    if 꼴 == "램프업":
        return [R0 + (RN - R0) * (3 * (k / N) ** 2 - 2 * (k / N) ** 3) for k in range(1, N + 1)]
    if 꼴 == "늦춤":
        가 = int(math.ceil(N / 2.0))
        R가 = R0 + (RN - R0) / 3.0
        낸, 앞 = [], R0
        for k in range(1, N + 1):
            if k < 가:
                앞 = 앞 + (R가 - 앞) * 늦춤몫(k)                 # 가운데 해까지 남은 격차의 0.2 · 0.3 · 0.4 · 0.5 …
            elif k == 가:
                앞 = R가
            elif k < N:
                앞 = 앞 + (RN - 앞) * 늦춤몫(k - 가)             # 도착까지 남은 격차의 0.2 · 0.3 · 0.4 · 0.5 … (2026-10-25 Y3-2 — 뒤쪽도 같은 꼴)
            else:
                앞 = RN
            낸.append(앞)
        return 낸
    raise 짓기오류("경로.꼴 은 직선 · 늦춤 · 램프업 가운데 하나입니다 — %r" % 꼴)


