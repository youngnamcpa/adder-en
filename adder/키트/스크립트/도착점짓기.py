def _표(기록):
    줄 = ["도착점짓기 — %s · 도착연도 FY%s · 예측 %d 해 · %s" % (기록["형식"], 기록["도착연도"], 기록["예측연수"], 기록["국가"])]
    for x in 기록["대조"]:
        if not _수(x["차"]):
            차 = "–"
        elif x.get("차단위") == "배":
            차 = "%.3f배" % x["차"]
        elif x.get("차단위") == "%p":
            차 = "%+.2f%%p" % (x["차"] * 100)
        else:
            차 = "%+.4f%%" % (x["차"] * 100)
        줄.append("  %-6s %-60s 목표 %-14s 엔진 %-14s 차 %s" % (x["판정"], x["항목"][:60], _숫(x["목표"]), _숫(x["엔진"]), 차))
    재 = 기록.get("재투자갈래") or {}
    if 재.get("열"):
        줄.append("  재투자 갈래(기준) — 열: CAPEX − D&A + 순운전자본 증가 = 재투자(목표)")
        for r in 재["열"]:
            줄.append("    %-8s %14s − %14s + %14s = %14s(%s)" % (r["열"], _숫(r["CAPEX"]), _숫(r["D&A"]), _숫(r["순운전자본증가"]), _숫(r["재투자"]),
                                                            _숫(r["목표재투자"])))
    for 이름, 키 in (("거절", "거절"), ("모델 밖 가치", "모델밖가치"), ("옮길 수 없음", "옮길수없음")):
        for x in 기록.get(키) or []:
            줄.append("  [%s] %s — %s" % (이름, x.get("무엇") or x.get("이름") or x.get("자리"), (x.get("까닭") or "")[:160]))
    for x in (기록.get("처음") or {}).get("바꾼것") or []:
        줄.append("  · 바꾼 것 — " + x[:200])
    for x in 기록.get("글") or []:
        줄.append("  · " + x[:200])
    return "\n".join(줄)


