def 영구베타역산(g, 목표, de):
    """영구기간 WACC 가 `목표` 가 되는 `WACC.영구기간.베타u` — 엔진 `wacc계산` 을 그대로 쓰는 이분법(허용 1e-7).
    무위험이자율 · 시장위험프리미엄 · D/E(`de` — 엔진이 낸 영구기간 D/E) · 타인자본비용 · 한계세율 · 현금비중 · 부채베타는 WACC.영구기간 그대로 둔다.
    βU 가 0 이어도 목표보다 높거나 βU 를 키워도 닿지 않으면 None(옮길 수 없다). → (βU 또는 None, 그 βU 의 WACC, βU = 0 의 WACC)."""
    from 엔진.wacc import wacc계산                         # noqa: PLC0415
    h = copy.deepcopy(g)
    w = h["WACC"]["영구기간"]

    def f(b):
        w["베타u"] = b
        return wacc계산(h, de, 1.0)["영구기간"]["WACC"]          # 총차입금 ÷ 시가총액 = de(목표 D/E 를 적었으면 엔진이 그 값을 쓴다)
    lo, hi = 0.0, 1.0
    f0 = f(lo)
    if f0 > 목표 + 1e-12:
        return None, f0, f0
    while f(hi) < 목표 and hi < 1e3:
        hi *= 2.0
    if f(hi) < 목표:
        return None, f(hi), f0
    for _ in range(200):
        mid = (lo + hi) / 2.0
        if f(mid) < 목표:
            lo = mid
        else:
            hi = mid
        if hi - lo < 1e-15:
            break
    b = (lo + hi) / 2.0
    v = f(b)
