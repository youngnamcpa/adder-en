def _가정해시(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def 입력읽기(가정경로, 지정=None):
    p = 지정 or os.path.join(os.path.dirname(os.path.abspath(가정경로)), 가격성립파일)
    if not os.path.isfile(p):
        if 지정:
            raise 입력틀림("가격 성립 입력 파일이 없다: %s" % 지정)
        return None, None
    with io.open(p, encoding="utf-8") as f:
        d = json.load(f)
    if not isinstance(d, dict):
        raise 입력틀림("가격 성립 입력의 최상위가 객체가 아니다: %s" % p)
    return d.get("공시밖"), p


def 쓰기(낸, 가정경로, 낼=None):
    p = 낼 or os.path.join(os.path.dirname(os.path.abspath(가정경로)), "_raw", 산출이름)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with io.open(p, "w", encoding="utf-8", newline="\n") as f:
        json.dump(낸, f, ensure_ascii=False, indent=1)
    return p


