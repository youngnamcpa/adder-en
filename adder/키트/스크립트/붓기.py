def _준이름(가정):
    """가정이 준 이름을 **이름 칸 열쇠**로 모은다 → {블록: {열쇠: 이름}}. 겹친 열쇠는 보고에 적는다.

    원가 이름의 열쇠 셋(「원가항목1」·「원가1」·행 번호 「80」)은 같은 이름 칸을 가리킨다(`이름열쇠별칭`) —
    여럿을 줬으면 앞의 것(행 번호 → 원가항목N → 원가N)을 쓰고, 글이 서로 다르면 「이름 겹침」으로 알린다."""
    M = (가정.get("메타") or {})
    준 = collections.OrderedDict()
    for 블록 in 이름블록:
        d = M.get(블록)
        if not isinstance(d, dict):
            continue
        글 = collections.OrderedDict((k, ("%s" % v).strip()) for k, v in d.items()
                                    if not _주석키(k) and v is not None and ("%s" % v).strip())
        낸, 쓴 = collections.OrderedDict(), set()
        for 열쇠, 받는 in 이름열쇠별칭.get(블록, {}).items():
            있는 = [(k, 글[k]) for k in 받는 if k in 글]
            쓴.update(받는)
            if not 있는:
                continue
            낸[열쇠] = 있는[0][1]
            if len({v for _k, v in 있는}) > 1:
                _판.보고.append("이름 겹침 — 메타.%s 의 %s 이 같은 이름 칸(%s)을 가리키는데 글이 서로 다릅니다 — 「%s」의 것을 썼습니다"
                              "(차례: 행 번호 → 원가항목N → 원가N. 레터.py 는 「원가1」·「원가2」를 읽습니다 — 열쇠를 하나만 두십시오)"
                              % (블록, " · ".join("「%s」" % k for k, _v in 있는), 열쇠, 있는[0][0]))
        for k, v in 글.items():
            if k not in 쓴:
                낸[k] = v
        if 낸:
            준[블록] = 낸
    return 준


_re제품군 = re.compile(r"^제품군(\d)$")


def _구분뗀(말, 이):
    """구분 이름(이) 뒤에 이어 쓸 명칭이 이미 그 구분 이름 + 띄어쓰기로 시작하면 앞의 구분 이름을 뗀 말(`레터.구분뗀말` 과 같은 규칙)."""
    if 이 and 말.startswith(이) and 말[len(이):len(이) + 1].isspace() and 말[len(이):].strip():
        return 말[len(이):].strip()
    return 말


def _물량단가말(가정):
    """매출 구분 s → (판매량 증가율 줄의 낱말, 판매단가 변동률 줄의 낱말) — 레터1부.매출명칭인가 · _증가율절 과 같은 규칙(W4 · 2026-10-23).
    판매량명칭이 매출 그 자체(「매출」 · 「매출액」 · 「영업수익」 · 구분 이름에 든 말)면 그 구분의 판매량 증가율 줄은 매출 증가율이다.
    판매량명칭 · 판매단가명칭을 주지 않은 구분은 넣지 않는다(줄 이름 그대로)."""
    M = 가정.get("메타") or {}
    스, 물, 단 = (M.get(k) if isinstance(M.get(k), dict) else {} for k in ("스트림이름", "물량이름", "단가이름"))
    낸 = {}
    for 열쇠 in set(물) | set(단):
        m = _re제품군.match("%s" % 열쇠)
        if not m:
            continue
        이 = ("%s" % (스.get(열쇠) or "")).strip()
        # 이름 칸은 「<구분 이름> 판매량 증가율」 이다 — 명칭이 이미 구분 이름으로 시작하면 앞의 구분 이름을 뗀다(`레터.구분뗀말` 과 같은 규칙 ·
        # 「<구분> <구분> 매출 증가율」 겹침을 막는다)
        명 = _구분뗀(("%s" % (물.get(열쇠) or "")).strip(), 이)
        단명 = _구분뗀(("%s" % (단.get(열쇠) or "")).strip(), 이)
        매명 = bool(명) and (명 in ("매출", "매출액", "영업수익") or bool(이 and 명 in 이))
        # 판매량명칭이 구분 이름에 든 말이면(「영업수익」 구분의 「영업수익」) 「영업수익 증가율」 — 그 밖의 매출명칭은 「<구분> 매출 증가율」
        물말 = (("증가율" if (이 and 명 in 이) else "매출 증가율") if 매명 else ("%s 증가율" % 명 if 명 else None))
        단말 = ("%s 변동률" % (단명[:-2].strip() if 단명.endswith("지수") and len(단명) > 2 else 단명)) if 단명 else None
        낸[int(m.group(1))] = (물말, 단말)
    return 낸


