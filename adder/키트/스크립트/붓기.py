def _이름쓰기(장, 칸번호, 글, 틀=None, 방식=None):
    """이름 칸에 글을 쓴다 → "바꿈" · "그대로"(이미 그 글이다) · "틀다름"(그 칸의 지금 글이 틀과 안 맞아 안 썼다) ·
    None(못 썼다 — 이 배치에 없는 자리 · 병합 칸 · 수식 칸).

    글이 None 이면 쓸 것이 없다는 뜻이다(덧붙일 이름이 줄 이름에 이미 들어 있다) — 쓸 수 있는 칸이면 "그대로".
    **틀을 주면 그 칸의 지금 글이 틀에서 나올 수 있는 글일 때만 쓴다**(자리표시가 든 스캐폴드의 글 · 이름이 이미 든 글).
    스캐폴드의 줄 이름을 고쳤는데 지도의 틀이 옛 글이면 지금 글이 틀과 안 맞는다 — 틀대로 덮으면 고친 줄 이름이 되돌아간다."""
    칸 = 장.칸(칸번호)
    if 칸 is None or 좌표.병합딸린칸(칸):
        return None
