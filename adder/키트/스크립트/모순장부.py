def 병합(기존, 새):
    """사람이 적은 상태·처리·승격·독자는 보존한다. ID 가 같으면 값만 갱신.
    옛 순번 M-09(M-09-01…)는 **대상·칸이 같은 새 해시 ID 로 사람 칸을 옮기고** 옛 줄을 지운다."""
    표 = {it["ID"]: it for it in (기존 or {}).get("항목") or []}
    결과 = []
    for it in 새:
        옛 = 표.pop(it["ID"], None)
        if 옛 is None and it["ID"].startswith("M-06-") and not _옛M06.match(it["ID"]):
            for ID in sorted(k for k in 표 if _옛M06.match(k)):
                if (표[ID].get("충돌") or "") == (it.get("충돌") or ""):
                    옛 = 표.pop(ID)
                    it["옛ID"] = ID
                    break
        if 옛 is None and it["ID"].startswith("M-09-") and not _옛M09.match(it["ID"]):
            나대상, 나칸 = _정규(it.get("대상")), it.get("칸") or ""
            for ID in sorted(k for k in 표 if _옛M09.match(k)):
                옛대상, 옛칸 = _옛대상칸(표[ID])
                if _정규(옛대상) == 나대상 and 옛칸 == 나칸:
                    옛 = 표.pop(ID)
                    it["옛ID"] = ID
                    break
        if 옛:
            for k in ("상태", "처리", "승격", "중요도", "옛ID"):
                if 옛.get(k):
                    it[k] = 옛[k]
            # 독자 — 사람이 적은 것(자동 표시가 없는 것)은 보존, 자동이면 새로 만든 문장으로 갈음
            if 옛.get("독자") and not 옛.get("독자_자동"):
                it["독자"] = 옛["독자"]
                it.pop("독자_자동", None)
        결과.append(it)
    # X-계열(사람 등록)과 사라진 M 은 보존 — 단 옛 순번 M-09 가 새 ID 로 옮겨지지 못했고 이미 해소면 버린다
    # M-10(신호)은 예외 — 신호가 더는 서지 않고 사람이 손대지 않은(빈 상태 · 미해결) 줄은 닫을 것이 없으니 버린다(부분해결 등 사람이 적은 줄은 남긴다)
    for ID, 옛 in 표.items():
        if ID.startswith("M-10-") and (옛.get("상태") or "미해결").strip() == "미해결":
            continue
        # 조건이 풀리면 사라지는 자동 항목(M-07 — 외부 제약이 가정에 없다)은 새 판에 없으면 풀린 것이다 — 미해결로 남기면 ㉟ 가 늘 오류였다(2026-10-23 실측 NAVER · MO)
        if ID in 조건자동해소 and (옛.get("상태") or "미해결").strip() != "해소":
            결과.append(dict(옛, 상태="해소", 처리=((옛.get("처리") or "") + " [자동 해소 — 새 판에서 조건이 서지 않는다]").strip()))
            continue
        if ID.startswith("X-") or 옛.get("상태") != "해소":
            결과.append(옛)
    return 결과


