class 원천열(object):
    """13번 원천을 기간 축의 열로 읽는다 — 최근 실적 열(기준일 열 = 재무기준일 열 — 누계 실적 열이 있으면 그 열)과 직전 실적 열,
    최근 열의 기간(년). 축을 못 지으면 `까닭` 에 글이 있고 값은 모두 None 이다(열을 위치로 짐작하지 않는다)."""

    def __init__(self, 가정):
        self.원 = 가정.get("원천") or {}
        self.까닭 = None
        try:
            from 기간축 import 기간축                        # noqa: PLC0415
            축 = 기간축(가정)
            self.최근 = 축.ID[축.기준일]
            self.직전 = 축.ID[축.실적[-2]] if len(축.실적) > 1 else None
            self.년 = 축.열[축.기준일].년
            self.예측 = [축.ID[i] for i in 축.예측]
        except Exception as e:                                # noqa: BLE001 — 기간축오류 · 평가기준일 없음 · 옛 꼴(v12)
            self.까닭 = "%s" % e
            self.최근 = self.직전 = self.년 = None
            self.예측 = []

    def 값(self, 번호, 열=None):
        열 = 열 or self.최근
        v = self.원.get(str(번호))
        return _n(v.get(열)) if (열 and isinstance(v, dict)) else None

    def 합(self, 번호들, 열=None):
        """계정들의 합 — 값이 하나도 없으면 None(합계를 0 으로 지어내지 않는다)."""
        값들 = [self.값(r, 열) for r in 번호들]
        return sum(x for x in 값들 if x is not None) if any(x is not None for x in 값들) else None


def _매출닿는행(가정):
    """선언한 매출 구분의 판매량을 정하는 줄(엔진 매출.py 의 번호) — 증가율 경로 A-030 · 038 … · 기타 A-070 /
    수준 경로 · 직접 A-6s0 / 수준 경로 · 능력 그 구분 라인의 생산능력(기간 평균) A-(668 + 2j) · 가동률 A-(273 + 25(s−1)) ·
    수율 A-(277 + 25(s−1)) / 수준 경로 · 저량 유입 A-(570 + s) · 유출률 A-(575 + s) · 전환율 A-(580 + s) / 점유율 대조를 세웠으면
    시장 규모 A-(281 + 25(s−1)). 수준 경로의 기타(6)는 판매량이 없다."""
    낸 = []
    for x in ((가정.get("구조") or {}).get("매출구분") or []):
        s = x.get("번호") if isinstance(x, dict) else None
        if not isinstance(s, int):
            continue
        if (x.get("경로") or "증가율") != "수준":
            낸.append(_ID(12, 70 if s == 6 else 30 + 8 * (s - 1)))
        elif s < 6 and x.get("판매량산정") == "능력":
            낸 += [_ID(12, 668 + 2 * j["번호"]) for j in (x.get("라인") or []) if isinstance(j, dict) and isinstance(j.get("번호"), int)]
            낸 += [_ID(12, 273 + 25 * (s - 1)), _ID(12, 277 + 25 * (s - 1))]
        elif s < 6 and x.get("판매량산정") == "저량":           # S2-04 — 저량 굴림: 유입 A-(570 + s) · 유출률 A-(575 + s) (· 전환율 A-(580 + s))
            낸 += [_ID(12, 570 + s), _ID(12, 575 + s)] + ([_ID(12, 580 + s)] if x.get("판매량꼴") == "저량" else [])
        elif s < 6:
            낸.append(_ID(12, 600 + 10 * s))
        if s < 6 and x.get("점유율대조") == "예":
            낸.append(_ID(12, 281 + 25 * (s - 1)))
    return 낸 or [_ID(12, 30)]


