def 미해결인가(it):
    """**규칙 — 「해소」가 아니면 미해결이다.** 「부분해결」·「미해결」·빈 상태 모두.
    부분해결은 「방향은 설명되나 금액 bridge 가 없다」(스킬)이므로 닿는 행을 「확인완료」로 올릴 수 없다는
    점에서 미해결과 같다. 승격 여부는 셈을 가르지 않는다 — critical 의 「승격 없음」 셈만 가른다."""
    return (it.get("상태") or "").strip() != "해소"


def 요약(항목):
    q = {"critical_미해결": 0, "high_미해결": 0, "medium_미해결": 0, "해소": 0, "승격없는_critical": 0,
         "부분해결": 0, "전체": len(항목), "상태별": {},
         "규칙": "해소가 아니면 미해결(부분해결 포함) · 승격은 critical 의 승격없음 셈만 가른다"}
    for it in 항목:
        상 = (it.get("상태") or "").strip() or "(빈 상태)"
        q["상태별"][상] = q["상태별"].get(상, 0) + 1
        if not 미해결인가(it):
            q["해소"] += 1
            continue
        if (it.get("상태") or "").strip() == "부분해결":
            q["부분해결"] += 1
        중 = it.get("중요도")
        if 중 == "critical":
            q["critical_미해결"] += 1
            if not (it.get("승격") or "").strip():
                q["승격없는_critical"] += 1
        elif 중 == "high":
            q["high_미해결"] += 1
        else:
            q["medium_미해결"] += 1
    return q


