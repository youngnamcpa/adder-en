# 1.1.4 — 신호 글은 저자층이다(도구 내부 말 · 표 번호 · 사람에게 시키는 꼬리 · 「이(가)」 꼴 조사). 부록 H 의 자동 독자 문장으로 옮길 때 다듬는다
# (회차 다섯이 「유사기업 βU 에서 …」(⑬ 용어) · 「표 1600 + j 의 어느 줄로 …」(⑱ 없는 상호참조) · 「엔진 기본 폭」(내부어)을 사람 문장으로 고쳤다)
_독자바꿈 = ((r"유사기업 후보", "Peer group 후보"), (r"유사기업", "Peer group"), (r"\s*—\s*[^—.]*?(?:표|시트) \d{3,4}\s*\+\s*\w+[^—.]*?(?:정한다|본다|옮긴다)", ""),
          (r"(?:표|시트) \d{3,4}\s*\+\s*\w+", "입력 표"), (r"엔진 기본 폭", "기본 폭"), (r"엔진(?=\s|이|가|은|는|의|으로|로)", "계산"),
          (r"\{[^{}]*['\"][^{}]*\}", ""), (r"\s*—\s*[^—]*?사람이 (?:정한다|본다|원문으로 본다)\.?", ""), (r"[.]?\s*[^.—]*?사람이 (?:정한다|본다|원문으로 본다)\.?$", ""),
          (r"\s{2,}", " "))


def 독자다듬기(글):
    """신호에서 온 자동 독자 문장 → 레터 부록 H 에 실을 꼴. 사실(대상 · 값 · 문턱)은 그대로 두고 도구 말 · 지시 꼬리를 걷고 조사를 고른다."""
    g = "%s" % (글 or "")
    for 패, 새 in _독자바꿈:
        g = re.sub(패, 새, g)

    def 조사(m):                                          # 「1.250 가」 · 「이(가)」 꼴 — 앞 말의 받침으로 고른다
        앞, 있, 없 = m.group(1), m.group(2), m.group(3)
        끝 = 앞[-1]
        받 = ((ord(끝) - 0xAC00) % 28 != 0) if "가" <= 끝 <= "힣" else (끝 in "0136")
        return "%s %s" % (앞, 있 if 받 else 없) if m.group(0)[len(앞)] == " " else "%s%s" % (앞, 있 if 받 else 없)
    g = re.sub(r"(\S+?)\s?(이|은|을)\((가|는|를)\)", lambda m: 조사(m), g)
    g = re.sub(r"(\d[\d.,]*) (가|이) (?=\S)", lambda m: "%s%s " % (m.group(1), "이" if m.group(1)[-1] in "0136" else "가"), g)
    g = g.strip(" —")
    if g and not g.endswith("."):
        g += "."
    return g


def 독자사실(글):
    """신호 글(「사실 — 저자가 할 일」 꼴)에서 저자에게 시키는 꼬리(「… 근거 칸에 적는다」)를 떼고 사실만 남긴다 → 「…다.」 로 끝나는 글.
    레터 부록 H 는 독자 문장을 싣는다 — 독자에게 나가는 글이 저자에게 일을 시키면 자리가 틀렸다. 일은 처리 칸(저자층)에 있다."""
    g = ("%s" % (글 or "")).strip()
    while True:
        m = re.search(r"(?:\s—\s|\.\s+)((?:(?!\s—\s|\.\s).)*?적는다)\.?\s*$", g)     # 마지막 마디만(앞 마디의 사실은 남긴다)
        if not m:
            break
        g = g[:m.start()].rstrip(" —.")
    if g and not g.endswith((".", "다")):
        g += "."
    elif g.endswith("다"):
        g += "."
    return g


def _값(s):
    """숫자로 읽히면 숫자, 아니면 문자열 그대로. 빈 값은 None."""
    if s is None or (isinstance(s, str) and not s.strip()):
        return None
    if _수인가(s):
        return s
    t = str(s).replace(",", "").strip()
    if re.fullmatch(r"[-+]?\d+(\.\d+)?", t):
        return float(t)
    return str(s)


