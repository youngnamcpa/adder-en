def _주(x, 단위=""):
    """주당 금액 — 원 · 엔(또는 100 이상)은 정수, 그 밖의 통화는 소수 둘째 자리(1.1.11 — 7.03달러가 「7달러」로 나가 본문과 어긋났다)."""
