def _이다(글):
    """마지막 한글 음절에 받침이 있으면 「이다」, 없으면 「다」(숫자로 끝나면 「이다」)."""
    끝 = (글 or "").strip()[-1:]
    if "가" <= 끝 <= "힣":
        return 글 + ("이다" if (ord(끝) - 0xAC00) % 28 else "다")
    return 글 + ("다" if 끝 == "%" else "이다")


