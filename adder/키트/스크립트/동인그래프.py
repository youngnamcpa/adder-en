def 짓기(가정, 가정경로=None, 축들=None, 엔진=True):
    """(산출, 까닭) — 까닭이 있으면 입력오류."""
    try:
        p = 판(가정)
    except Exception as e:                           # noqa: BLE001
        return None, "기간 축 · 구조를 세우지 못했다 — %s" % e
    if p.구조오류:
        return None, "구조 오류 %d건 — %s" % (len(p.구조오류), " / ".join(p.구조오류[:3]))
    이름표, 종류표 = {}, {}
    try:
        import 거친바퀴                              # noqa: PLC0415
        이름표, 종류표 = 거친바퀴.줄표(가정경로)
    except Exception:                                # noqa: BLE001
        pass
    G = 그래프(p, 이름표, 종류표).짓기()
    신호 = []
    까닭 = 값채우기(G, 가정) if 엔진 else "엔진을 돌리지 않았다(--엔진없이)"
    if 까닭:
        신호.append({"출처": 출처이름, "종류": "엔진 미계산", "대상": "계산 노드 값", "값": "", "문턱": "", "글": 까닭, "등급": "참고"})
    민 = 민감도붙이기(G, 가정경로)
    단위 = 단위검사(G)
    전파, 전파신호 = 전파대조(G, 축들)
    신호 += 단위 + 전파신호
    체인 = [G.체인(아) for 아 in sorted((a for a, n in G.노드.items() if n["종류"] in ("가정", "거시")), key=lambda a: int(a[2:]))]
    안읽는 = [c["노드"] for c in 체인 if not c["읽힘"]]
    try:
        지문 = 구조모듈.구조지문(가정)
    except Exception:                                # noqa: BLE001
        지문 = None
    낸 = {"형식": 형식, "만든날": datetime.datetime.now().strftime("%Y-%m-%d %H:%M"), "가정": os.path.basename(가정경로) if 가정경로 else None,
         "구조지문": 지문, "묶음": (가정.get("구조") or {}).get("묶음"),
         "요약": {"노드": len(G.노드), "가정노드": sum(1 for n in G.노드.values() if n["종류"] in ("가정", "거시")),
                "계산노드": sum(1 for n in G.노드.values() if n["종류"] == "계산"), "엣지": len(G.엣지),
                "엣지종류": sorted({e["엣지"] for e in G.엣지 if e["엣지"]}), "되돌아오는엣지": [e["이름"] for e in G.엣지 if e["성격"] == "닫힌 식"],
                "민감도붙인칸": 민, "안읽는가정칸": 안읽는},
         "노드": list(G.노드.values()), "엣지": G.엣지, "단위검사": 단위, "전파": 전파, "설명체인": 체인, "신호": 신호}
    return 낸, ""


def 쓰기(낸, 가정경로, 낼=None):
    p = 낼 or os.path.join(os.path.dirname(os.path.abspath(가정경로)), "_raw", "동인그래프.json")
    os.makedirs(os.path.dirname(p) or ".", exist_ok=True)
    with io.open(p, "w", encoding="utf-8") as f:
        json.dump(낸, f, ensure_ascii=False, indent=1, default=str)
    return p


