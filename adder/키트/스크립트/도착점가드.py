def _연별(줄, 속):
    """{기간 id: 값} → {회계연도: 합}(영구기간 열 뺌). 한 회계연도에 실적 · 예측 열이 섞이면 더한다(기저율.경로 와 같다)."""
    낸 = {}
    for 열, v in (줄 or {}).items():
        p = 속.get(열) or {}
        if p.get("구분") == "영구기간" or not _수(v):
            continue
        y = p.get("회계연도")
        if y is None:
            continue
        낸[int(y)] = 낸.get(int(y), 0.0) + float(v)
    return 낸


def 앞해경로(R, u, 문):
    """엔진 매출 구분 줄(4번 46 + 구분)의 기준 해 → 기준 + 앞해수 CAGR. → (값 또는 None, 글)."""
    s = u.get("구분")
    if not (_수(s) and 1 <= int(s) <= 6):
        return None, "구분 번호가 없어 엔진 경로를 못 짚는다"
    줄 = ((R or {}).get("4.Sales") or {}).get("%d" % (46 + int(s)))
    if not 줄:
        return None, "엔진에 매출 구분 %s 의 매출액 줄(4번 %d)이 없다" % (s, 46 + int(s))
    연 = _연별(줄, R["기간"]["속성"])
    y0 = u.get("기준연도")
    k = int(문["앞해수"])
    if y0 is None or y0 not in 연 or (y0 + k) not in 연:
        return None, "엔진 경로에 기준 해 %s 또는 %s 해가 없다" % (y0, (y0 + k) if y0 else "—")
    a, b = 연[y0], 연[y0 + k]
    if not (a > 0 and b > 0):
        return None, "엔진 경로의 기준 해 또는 끝 해 매출이 0 이하"
    return (b / a) ** (1.0 / k) - 1, "엔진 4번 %d · %d → %d" % (46 + int(s), y0, y0 + k)


def 한계ROIC(R, b, 문):
    """예측기간 한계 ROIC 와 대조. R 이 None 이면 재료 없음."""
    낸 = {"식": "Δ세후영업이익(2번 19 · 첫 연간 열 → 끝 연간 열) ÷ 순재투자 합(2번 21 − 20 + 22 · 첫 연간 열 ~ 끝 열 앞 — 한 해 늦춤)"}
    if not R:
        낸.update({"판정": "재료 없음", "경보": False})
        return 낸
    속, 열 = R["기간"]["속성"], R["기간"]["열"]
    D = R["2.DCF"]
    연간 = [c for c in 열 if (속.get(c) or {}).get("구분") not in ("실적", "영구기간") and abs(((속.get(c) or {}).get("년") or 0) - 1.0) < 1e-9]
    안 = b.get("안정") or {}
    안정 = float(안["ROIC"]) if _수(안.get("ROIC")) else R["요약"].get("영구ROIC")
    자본 = float(안["자본비용"]) if _수(안.get("자본비용")) else (R.get("WACC") or {}).get("영구기간", {}).get("WACC")
    예W = (R.get("WACC") or {}).get("예측기간", {}).get("WACC")
    낸.update({"안정ROIC": 안정, "안정ROIC출처": "도착점.안정.ROIC" if _수(안.get("ROIC")) else "엔진 영구 ROIC(2번 48)",
              "안정근거": 안.get("근거"), "자본비용": 자본,
              "자본비용출처": "도착점.안정.자본비용" if _수(안.get("자본비용")) else "엔진 영구기간 WACC(2번 46)",
              "예측기간WACC": 예W, "엔진증분ROIC": R["요약"].get("증분ROIC"), "연간열": 연간,
              "엔진예측연수": round(sum(((속.get(c) or {}).get("년") or 0) for c in 열 if (속.get(c) or {}).get("구분") not in ("실적", "영구기간")), 2),
              # 연차 = 예측 열의 개수 — 평가기준일이 기중이면 잔여 기간 열이 연차 1 을 맡는다(도착점짓기 `연차표` 와 같은 셈 · Y3-2)
              "엔진예측연차": sum(1 for c in 열 if (속.get(c) or {}).get("구분") not in ("실적", "영구기간"))})
    if len(연간) < 2:
        낸.update({"판정": "재료 없음", "까닭": "예측기간 연간 열이 둘 미만", "경보": False})
        return 낸

    # 연구개발비 자본화를 켠 판은 조정 세후영업이익(2번 116) · 조정 재투자(2번 117)로 잰다 — 엔진 증분 ROIC · 다모다란 Diagnostics 와 같은 잣대(Y3-2)
    자본화 = isinstance(D.get("116"), dict) and isinstance(D.get("117"), dict) and any(v is not None for v in D["116"].values())
    낸["잣대"] = "조정(연구개발비 자본화 — 2번 116 · 117)" if 자본화 else "보고(2번 19 · 21 − 20 + 22)"

    def _이익(c):
        return (D["116"].get(c) if 자본화 else D["19"].get(c)) or 0.0

    def _재투자(c):
        if 자본화:
            return D["117"].get(c) or 0.0
        return (D["21"].get(c) or 0.0) - (D["20"].get(c) or 0.0) + (D["22"].get(c) or 0.0)

    def 구간(a, z):
        Δ = _이익(z) - _이익(a)
        i0, i1 = 열.index(a), 열.index(z)
        재 = sum(_재투자(c) for c in 열[i0:i1])
        return {"처음": a, "끝": z, "Δ세후영업이익": Δ, "순재투자": 재, "한계ROIC": (Δ / 재) if 재 > 0 else None}

    전 = 구간(연간[0], 연간[-1])
    낸["전체"] = 전
    if len(연간) >= 7:
        낸["앞"] = 구간(연간[0], 연간[4])
        낸["뒤"] = 구간(연간[4], 연간[-1])
    배 = float(문["한계ROIC배"])
    걸 = []
    참 = []
    r = 전["한계ROIC"]
    if r is None:
        if 전["Δ세후영업이익"] > 0:
            걸.append("순재투자 합이 0 이하인데 세후영업이익이 %s 늘어난다 — 재투자 없이 사는 성장" % _금(전["Δ세후영업이익"]))
        else:
            참.append("순재투자 합이 0 이하 — 한계 ROIC 를 잴 수 없다")
    else:
        if _수(예W) and r < 예W * float(문["한계ROIC자본비용"]):
            걸.append("한계 ROIC %s 가 예측기간 WACC %s 보다 낮다 — 예측기간 성장이 자본비용보다 낮은 수익률로 산 성장이다" % (_퍼(r), _퍼(예W)))
        if _수(안정) and 안정 > 0:
            if r > 안정 * 배:
                걸.append("한계 ROIC %s 가 안정 ROIC %s 의 %.1f배를 넘는다 — 두 구간 회전율 · 목표 마진 · 안정 ROIC 가운데 하나가 서사와 어긋난다" % (_퍼(r), _퍼(안정), 배))
            elif r < 안정 / 배:
                참.append("한계 ROIC %s 가 안정 ROIC %s 의 %.1f분의 1 아래 — 예측기간 재투자가 영구기간보다 크게 비싸다" % (_퍼(r), _퍼(안정), 배))
    if _수(안정) and _수(자본):
        if 안정 < 자본:
            참.append("안정 ROIC %s 가 영구기간 자본비용 %s 보다 낮다 — 영구 성장이 가치를 깎는다" % (_퍼(안정), _퍼(자본)))
        elif 안정 > 자본 * float(문["안정ROIC자본비용배"]):
            글 = "안정 ROIC %s 가 영구기간 자본비용 %s 의 %.1f배를 넘는다 — 초과수익이 영구히 남는 까닭" % (_퍼(안정), _퍼(자본), float(문["안정ROIC자본비용배"]))
            if (안.get("근거") or "").strip():
                참.append(글 + "은 안정.근거 에 적혀 있다")
            else:
                걸.append(글 + "이 안정.근거 에 없다")
