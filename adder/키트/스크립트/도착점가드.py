def _퍼(x, 자리=1):
    return "—" if not _수(x) else ("%." + "%d" % 자리+ "f%%") % (x * 100)


def _금(x):
    return "—" if not _수(x) else "{:,.0f}".format(x)


def _이다(글):
    끝 = (글 or "").strip()[-1:]
    if "가" <= 끝 <= "힣":
        return 글 + ("이다" if (ord(끝) - 0xAC00) % 28 else "다")
    return 글 + ("다" if 끝 == "%" else "이다")


def _대표집단(항):
    """근거 범위 표에 실을 집단 — 같은 규모 → 산업 3 · 2자리 → 전체 가운데 관측이 찬 첫 집단."""
    xs = [x for x in (항 or {}).get("집단별") or [] if x.get("판정") != "표본 부족"]
    for 머 in ("같은 규모", None):
        for x in xs:
            if 머 is None or x["집단"].startswith(머):
                return x
    return None


