def _집단판정(값, 표본, 최소, 위, 아래=None):
    """정렬된 표본에서 값의 자리 → {관측수 · q10~q90 · 최대 · 최소 · 백분위 · 이상비중 · 판정}."""
    import 기저율 as 기                                          # noqa: PLC0415
    g = sorted(표본)
    낸 = {"관측수": len(g)}
    for q in (0.10, 0.25, 0.50, 0.75, 0.90):
        낸["q%02d" % round(q * 100)] = 기.분위(g, q)
    낸["최대"] = g[-1] if g else None
    낸["최소"] = g[0] if g else None
    if len(g) < 최소:
        낸.update({"백분위": None, "이상비중": None, "판정": "표본 부족"})
        return 낸
    아래수 = sum(1 for v in g if v < 값)
    낸["백분위"] = round(아래수 / len(g), 4)
    낸["이상비중"] = round(sum(1 for v in g if v >= 값) / len(g), 4)
    if 값 > g[-1]:
        판 = "0건"
    elif 낸["백분위"] >= 위:
        판 = "위 꼬리"
    elif 아래 is not None and 낸["백분위"] <= 아래:
        판 = "아래 꼬리"
    else:
        판 = ""
    낸["판정"] = 판
    return 낸


def 성장자리(P, 값, 연수, 기준원, 문):
    """내재 연평균 성장률을 같은 길이(패널 한도 안) CAGR 창에 댄다. → {창(년) · 요청창 · 창축소 · 집단별[] · 판정 · 경보 · 걸린집단[]}."""
    import 기저율 as 기                                          # noqa: PLC0415
    설 = P["설정"]
    해 = P.get("연도") or []
    폭 = (max(해) - min(해)) if 해 else 0
    k = min(int(연수), int(문["성장창최대"]), 폭)
    if k < 1:
        return {"판정": "재료 없음", "까닭": "패널 해가 하나뿐이다", "경보": False}
    W = [w for w in 기.cagr창(P["넓은"], k, 설) if w["고유번호"] != P.get("고유번호")]
    if 설["자료_제외"].get("창_양끝_같은구분", True):
        W = [w for w in W if w["같은구분"]]
    대 = _대상(P, 기준원)
    집 = 기.집단들(대, 설)
    낸 = {"창(년)": k, "요청창": int(연수), "창축소": k < int(연수), "규모구간": 대["규모구간"], "집단별": []}
    하한 = 설["자료_제외"].get("기준연도_매출_하한_원")
    if _수(기준원) and _수(하한) and 기준원 < 하한:
        낸["메모"] = "기준 매출이 패널 창 시작 매출 하한(%s) 아래다 — 패널에는 그보다 큰 회사의 창만 있다" % _금(하한)
    for 이름, f in 집:
        x = _집단판정(값, [w["CAGR"] for w in W if f(w)], int(문["최소관측"]), float(문["성장분위상한"]), float(문["성장하한분위"]))
        x["집단"] = 이름
        낸["집단별"].append(x)
    잰 = [x for x in 낸["집단별"] if x["판정"] != "표본 부족"]
    위 = [x for x in 잰 if x["판정"] in ("위 꼬리", "0건")]
    필요 = min(int(문["경보집단수"]), len(잰)) if 잰 else 0
    낸["걸린집단"] = [x["집단"] for x in 위]
    if not 잰:
        낸.update({"판정": "표본 부족", "경보": False})
    elif 위 and len(위) >= 필요:
        낸.update({"판정": "위 꼬리", "경보": True})
    elif 위:
        낸.update({"판정": "위 꼬리(한 집단)", "경보": False})
    elif any(x["판정"] == "아래 꼬리" for x in 잰):
        낸.update({"판정": "아래 꼬리", "경보": False})
    else:
        낸.update({"판정": "", "경보": False})
    return 낸


