def 점유율자리(u, 문):
    """출처마다 내재 점유율. → {출처별[] · 경보글[] · 참고글[] · 경보 · 판정}."""
    상 = float(문["점유율상한"])
    도 = u["도착매출"]
    줄, 걸, 참 = [], [], []
    for m in u["시장"]:
        x = {"차례": m["차례"], "출처": m["출처"], "종류": m["종류"], "채택": m["채택"], "연도": m["연도"], "시장규모": m["값"],
             "원값": m["원값"], "단위": m["단위"], "옮김": m["옮김"]}
        if not _수(도):
            x.update({"점유율": None, "판정": "도착 매출 없음"})
        elif not (_수(m["값"]) and m["값"] > 0):
            x.update({"점유율": None, "판정": "잴 수 없음 — " + (m["옮김"] or "시장 규모 0 이하")})
        else:
            x["점유율"] = 도 / m["값"]
            x["판정"] = "100% 초과" if x["점유율"] > 상 else ""
            if _수(m["연도"]) and _수(u.get("도착연도")) and int(m["연도"]) != int(u["도착연도"]):
                x["판정"] = (x["판정"] + " · " if x["판정"] else "") + "시장 규모 연도 %d ≠ 도착연도 %d" % (int(m["연도"]), int(u["도착연도"]))
        줄.append(x)
    회사제시 = lambda x: "회사 제시" in ("%s" % (x.get("종류") or ""))        # noqa: E731
    for x in 줄:
        if not _수(x.get("점유율")):
            continue
        if x["점유율"] > 상:
            (걸 if x["채택"] else 참).append("시장 규모 %s 대비 내재 점유율 %s — %d%% 를 넘는다%s" % (
                x["출처"] or "(출처 미기재)", _퍼(x["점유율"]), round(상 * 100), "" if x["채택"] else "(채택하지 않은 출처)"))
    비교 = [x for x in 줄 if _수(x.get("점유율")) and x["점유율"] > 0 and not 회사제시(x)]
    갈림 = None
    if len(비교) >= 2:
        갈림 = max(x["점유율"] for x in 비교) / min(x["점유율"] for x in 비교)
        if 갈림 >= float(문["점유율갈림배"]):
            걸.append("시장 규모 출처마다 내재 점유율이 %.1f배 갈린다(%s) — 도착점이 출처 고르기에 매달린다" % (
                갈림, " · ".join("%s %s" % (x["출처"] or "—", _퍼(x["점유율"])) for x in 비교)))
    if any(x["채택"] and 회사제시(x) for x in 줄):
        걸.append("채택한 시장 규모가 「회사 제시」 다 — 회사가 제시한 시장 규모는 걸러 적고 채택하지 않는 것이 기본이다")
    if u["시장"] and not any(x["채택"] for x in 줄):
        참.append("채택한 시장 규모가 없다 — 점유율의 분모가 정해지지 않았다")
    if not u["시장"] and u["종류"] == "사업단위":
        참.append("시장 규모 출처가 하나도 없다 — 내재 점유율을 잴 수 없다")
    채 = [x for x in 줄 if x["채택"] and _수(x.get("점유율"))]
    if 채 and _수(u.get("점유율")) and abs(채[0]["점유율"] - u["점유율"]) > 0.005:
        참.append("적은 점유율 %s 와 도착 매출이 함의하는 점유율 %s 가 다르다" % (_퍼(u["점유율"]), _퍼(채[0]["점유율"])))
    return {"출처별": 줄, "갈림배": 갈림, "경보글": 걸, "참고글": 참, "경보": bool(걸), "판정": "경보" if 걸 else ("참고" if 참 else "")}


def 선례자리(u, 문):
    최소 = int(문["선례최소"])
    유효 = [s for s in u["선례"] if ("%s" % (s.get("이름") or "")).strip() and ("%s" % (s.get("출처") or "")).strip()]
    빠짐 = [s.get("이름") or "(이름 없음)" for s in u["선례"] if s not in 유효]
    n = len(유효)
    강도 = "범위" if n >= 최소 else ("유추" if n >= 1 else "선례 없음")
    낸 = {"꼴": u.get("경로꼴"), "선례수": n, "선례": [{"이름": s.get("이름"), "곡선": s.get("곡선"), "출처": s.get("출처")} for s in 유효],
          "출처없어뺌": 빠짐, "근거강도": 강도, "경보": n < 최소}
    낸["판정"] = "유추" if n < 최소 else ""
    return 낸


