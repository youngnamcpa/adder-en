def 단위풀기(단위):
    """「백만원」 · 「십억달러」 · 「USD bn」 → (통화, 배). 통화 낱말을 뺀 나머지가 배수 표에 없으면 None(「대만달러」 같은 다른 통화를 달러로 읽지 않는다)."""
    t = ("%s" % (단위 or "")).replace(" ", "").strip()
    if not t:
        return None
    for 낱, 통 in _통화낱말:
        if 낱 in t:
            남 = t.replace(낱, "", 1)
            if 남 in _배수:
                return 통, _배수[남]
            if 남.lower() in _영배수:
                return 통, _영배수[남.lower()]
            return None
    return None


def 환산(값, 단위, 메타):
    """값(단위) → 가정 금액단위의 값. → (값 또는 None, 글). 단위가 비거나 금액단위와 같으면 그대로. 통화가 다르면 환율로 옮기지 않는다."""
    if not _수(값):
        return None, "값 없음"
    금 = ("%s" % (메타.get("금액단위") or "")).strip()
    if not 단위 or ("%s" % 단위).strip() == 금:
        return float(값), ("" if 단위 else "단위 미기재 — 금액단위(%s)로 읽음" % (금 or "—"))
    풀 = 단위풀기(단위)
    통 = ("%s" % (메타.get("표시통화") or "")).strip().upper()
    배 = 메타.get("환산배율") if _수(메타.get("환산배율")) else None
    if not 풀 or 통 not in ("KRW", "USD") or not 배:
        return None, "단위 %s 를 금액단위 %s 로 옮길 수 없다(모르는 단위 · 표시통화 %s · 환산배율 %s)" % (단위, 금 or "—", 통 or "—", 배)
    if 풀[0] != 통:
        return None, "통화가 다르다(%s · 표시통화 %s) — 환율로 옮기지 않는다" % (풀[0], 통)
    return float(값) * 풀[1] / float(배), "%s → %s" % (단위, 금)


