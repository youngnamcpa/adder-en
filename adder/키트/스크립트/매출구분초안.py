def 원천초안(Q들, 대응):
    """본선이 정한 「지표:구분」 대응 → 13번 원천 초안 {번호: {기간: 값}}. 저량은 기말(555+s)과 기간 평균(550+s — 앞 기말과의 평균 ·
    구조 칸 `판매량꼴 = 저량` 과 함께 — S2R1-01), 잔고 지표는 기말 잔고(600+s — 판매량산정 = 저량, S2-04)."""
    초 = {}
    for 쌍 in 대응 or []:
        if ":" not in 쌍:
            raise ValueError("--대응 은 「지표:구분」 꼴입니다: %s" % 쌍)
        이름, s = [y.strip() for y in 쌍.rsplit(":", 1)]
        s = int(s)
        if not 1 <= s <= 5:
            raise ValueError("--대응 의 구분은 1~5 입니다: %s" % 쌍)
        x = (next((q for q in Q들 if q.get("원천", "").endswith("." + 이름) or q.get("이름") == 이름), None)
             or next((q for q in Q들 if 이름 and (이름 in ("%s" % q.get("이름") or "") or 이름 in q.get("원천", ""))), None))
        if x is None:
            raise ValueError("--대응 의 지표를 Q 후보에서 못 찾았습니다: %s" % 이름)
        if not x.get("쓸수있나"):
            raise ValueError("--대응 의 지표 「%s」는 Q 로 못 씁니다 — %s" % (이름, x.get("까닭")))
        값 = dict(sorted((x.get("값") or {}).items()))
        if (x.get("원천") or "").split(".")[-1] in 잔고지표:
            초[str(600 + s)] = {c: v for c, v in 값.items() if c.startswith("FY")}
            continue
        if x.get("꼴") == "저량":
            초[str(555 + s)] = 값
            열 = [c for c in 값 if c.startswith("FY")]
            초[str(550 + s)] = {c: (값[a] + 값[c]) / 2.0 for a, c in zip(열, 열[1:])}
        else:
            초[str(550 + s)] = {c: v for c, v in 값.items() if c.startswith("FY")}
        fy = [c for c in 값 if c.startswith("FY")]
        if fy:
            # S2R2-03 — 저량 꼴의 기준 기간 판매량은 기간 평균(550+s 의 직전 회계연도)이다. 엔진은 기간 평균 판매량(550+s · 예측 6s0)과 견주므로
            #   기말 값을 넣으면 첫 예측 열부터 그 구분 매출이 기말 ÷ 평균만큼 꺾인다(가입자 연 30% 증가면 약 12%)
            if x.get("꼴") == "저량" and fy[-1] in 초[str(550 + s)]:
                초[str(586 + s)] = {"기준기간": 초[str(550 + s)][fy[-1]],
                                    "메모": "직전 회계연도(%s)의 기간 평균 저량 = (앞 기말 + 기말) ÷ 2 — 기준 기간이 누계면 (앞 기말 + 기준일 기말) ÷ 2. "
                                          "다르면 본선이 고친다" % fy[-1]}
            elif x.get("꼴") == "저량":
                초[str(586 + s)] = {"기준기간": None, "메모": "기간 평균을 낼 앞 기말이 없다(%s 한 해) — 본선이 (앞 기말 + 기말) ÷ 2 를 적는다" % fy[-1]}
            else:
                초[str(586 + s)] = {"기준기간": 값[fy[-1]], "메모": "직전 회계연도(%s) — 기준기간이 다르면 본선이 고친다" % fy[-1]}
    return 초


def 상태공간복원(상태):
    """`_raw/상태공간.json` → [{매출구분, 번호, 판정, 빈도, 관측수, 대리변수}] — 없거나 꼴이 다르면 None."""
