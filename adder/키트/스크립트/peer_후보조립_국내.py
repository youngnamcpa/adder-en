def 슬롯읽기(글들):
    """「이름:비중:키워드,키워드」 목록 → [(이름, 비중, 키워드글)] — 비중은 합이 1 이 되게 나눈다."""
    낸 = []
    for g in 글들 or []:
        조 = g.split(":", 2)
        if len(조) < 2:
            raise SystemExit("--슬롯 꼴은 「이름:비중:경로②키워드」 입니다: %r" % g)
        낸.append((조[0].strip(), float(조[1]), 조[2].strip() if len(조) > 2 else ""))
    합 = sum(x[1] for x in 낸) or 1.0
    return [(n, w / 합, k) for n, w, k in 낸]


def 나누기(총, 비중들):
    """총 자리를 비중대로 — 내림한 뒤 남는 자리는 나머지가 큰 슬롯부터(같으면 비중이 큰 슬롯)."""
    몫 = [int(총 * w + 1e-9) for w in 비중들]
    for i in sorted(range(len(비중들)), key=lambda i: (-(총 * 비중들[i] - 몫[i]), -비중들[i]))[:총 - sum(몫)]:
        몫[i] += 1
    return 몫


