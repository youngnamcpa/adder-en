# ────────────────────────────────────────────────────────────── 읽기

def _설명키(k):
    return ("%s" % k).startswith(("_", "("))


def 월번호(글, 자리):
    """"YYYY-MM" → 연 × 12 + (월 − 1)."""
    m = re.match(r"^\s*(\d{4})-(\d{1,2})\s*$", "%s" % (글,))
    if not m or not 1 <= int(m.group(2)) <= 12:
        raise 일정오류("%s 「%s」 — 월은 \"YYYY-MM\" 로 적습니다" % (자리, 글))
    return int(m.group(1)) * 12 + int(m.group(2)) - 1


def 월글(t):
    return "%04d-%02d" % (t // 12, t % 12 + 1)


def _수(v, 자리, 정수=False, 최소=None):
    if isinstance(v, bool) or not isinstance(v, (int, float)) or v != v or abs(v) == float("inf"):
        raise 일정오류("%s 「%s」 — 숫자를 적습니다" % (자리, v))
    if 정수:
        if int(v) != v:
            raise 일정오류("%s 가 %s 입니다 — 정수(개월 · 횟수 · 번호)를 적습니다" % (자리, v))
        v = int(v)
    if 최소 is not None and v < 최소:
        raise 일정오류("%s 가 %s 입니다 — %s 이상이어야 합니다" % (자리, v, 최소))
    return v


def _풀기(o, 시, 자리):
    """{"비관", "기준", "낙관"} 겹을 그 시나리오의 값으로 풀고 설명 키를 걷는다."""
    if isinstance(o, dict):
        키 = [k for k in o if not _설명키(k)]
        if 키 and all(k in 시나리오목록 for k in 키):
            빠진 = [s for s in 시나리오목록 if s not in o]
            if 빠진:
                raise 일정오류("%s — 시나리오 값에 %s 이 없습니다(비관 · 기준 · 낙관 셋을 다 적습니다)"
                              % (자리, " · ".join(빠진)))
            return _풀기(o[시], 시, 자리)
        return {k: _풀기(o[k], 시, "%s.%s" % (자리, k)) for k in 키}
    if isinstance(o, list):
        return [_풀기(x, 시, 자리) for x in o]
    return o


def _키검사(v, 받는, 자리):
    모르는 = [k for k in v if k not in 받는]
    if 모르는:
        raise 일정오류("%s — 모르는 키 %s (받는 키: %s)" % (자리, " · ".join(모르는), " · ".join(받는)))
    빠진 = [k for k in 받는 if k not in v]
    if 빠진:
        raise 일정오류("%s — %s 이 없습니다" % (자리, " · ".join(빠진)))


def _자리들(묶음, 이름, 상한):
    """`일정.라인` · `일정.프로젝트` → [(번호, 날것)] 번호 차례."""
    if 묶음 is None:
        return []
    if not isinstance(묶음, dict):
        raise 일정오류("일정.%s 이 객체가 아닙니다 — {번호: {꼴: …}}" % 이름)
    out = []
    for k, v in 묶음.items():
        if _설명키(k):
            continue
        if not re.match(r"^\d+$", "%s" % k) or not 1 <= int(k) <= 상한:
            raise 일정오류("일정.%s 의 키 「%s」 — 번호는 1~%d 입니다" % (이름, k, 상한))
        if not isinstance(v, dict):
            raise 일정오류("일정.%s.%s 이 객체가 아닙니다" % (이름, k))
        out.append((int(k), v))
    번호 = [j for j, _ in out]
    if len(set(번호)) != len(번호):
        raise 일정오류("일정.%s 의 번호가 겹칩니다" % 이름)
    return sorted(out, key=lambda x: x[0])


def _선언(가정):
    """`구조` 가 선언한 라인 · 프로젝트의 {번호: 이름}. `구조` 가 없으면 (None, None) — 견주지 않는다."""
    구조 = 가정.get("구조")
    if not isinstance(구조, dict):
        return None, None
    라인, 프로젝트 = {}, {}
    for 구분 in 구조.get("매출구분") or []:
        for x in (구분.get("라인") or []) if isinstance(구분, dict) else []:
            if isinstance(x, dict) and "번호" in x:
                라인[x["번호"]] = x.get("이름")
    투자 = 구조.get("투자") if isinstance(구조.get("투자"), dict) else {}
    for x in 투자.get("프로젝트") or []:
        if isinstance(x, dict) and "번호" in x:
            프로젝트[x["번호"]] = x.get("이름")
    return 라인, 프로젝트


def 열의달(축):
    """예측 열과 기준일 열의 {기간 ID: (첫 달, 달 수)}. 달 단위로 떨어지지 않는 열이 있으면 일정오류."""
    out = {}
    for i in [축.기준일] + list(축.예측):
        c = 축.열[i]
        if c.시작일.day != 1 or (c.종료일 + timedelta(days=1)).day != 1 or int(c.개월) != c.개월:
            raise 일정오류("%s 열(%s ~ %s)이 달 단위로 떨어지지 않습니다 — 월 단위 일정을 펼 수 없습니다. "
                          "열별 값을 가정에 직접 적고 산정 근거를 채우십시오" % (c.ID, c.시작일, c.종료일))
        out[c.ID] = (c.시작일.year * 12 + c.시작일.month - 1, int(c.개월))
    return out


