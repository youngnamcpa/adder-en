def _점함수(점):
    def f(t):
        if t <= 점[0][0]:
            return 점[0][1]
        for (a, va), (b, vb) in zip(점, 점[1:]):
            if t <= b:
                return va + (vb - va) * (t - a) / (b - a)
        return 점[-1][1]
    return f


def _반입함수(반입, 단위, 지연, 완성):
    def f(t):
        s = 0.0
        for r in 반입:
            d = t - r
            if d <= 지연:
                continue
            s += 단위 * (1.0 if 완성 <= 지연 else min(1.0, (d - 지연) / (완성 - 지연)))
        return s
    return f


def _라인읽기(j, 날것, 시):
    """라인 j 의 한 시나리오 → (월별 능력 함수, 반입 월 목록 또는 None)."""
    자리 = "일정.라인.%d" % j
    v = _풀기(날것, 시, 자리)
    꼴 = v.get("꼴")
    if 꼴 not in 라인꼴:
        raise 일정오류("%s.꼴 「%s」 — %s 가운데 하나를 적습니다" % (자리, 꼴, " · ".join(라인꼴)))
    _키검사(v, 라인꼴[꼴], 자리)
    if 꼴 == "점":
        if not isinstance(v["점"], list) or not v["점"]:
            raise 일정오류("%s.점 — [[월, 능력], …] 을 한 점 이상 적습니다" % 자리)
        점 = []
        for x in v["점"]:
            if not isinstance(x, list) or len(x) != 2:
                raise 일정오류("%s.점 의 「%s」 — [월, 능력] 두 칸으로 적습니다" % (자리, x))
            점.append((월번호(x[0], 자리 + ".점"), _수(x[1], 자리 + ".점 의 능력")))
        for a, b in zip(점, 점[1:]):
            if b[0] <= a[0]:
                raise 일정오류("%s.점 — 월이 앞에서 뒤로 늘어야 합니다(%s 다음에 %s)" % (자리, 월글(a[0]), 월글(b[0])))
        return _점함수(점), None
    시작 = 월번호(v["시작"], 자리 + ".시작")
    간격 = _수(v["간격개월"], 자리 + ".간격개월", 정수=True, 최소=1)
    횟수 = _수(v["횟수"], 자리 + ".횟수", 정수=True, 최소=1)
    단위 = _수(v["단위능력"], 자리 + ".단위능력")
    지연 = _수(v["투입지연개월"], 자리 + ".투입지연개월", 최소=0)
    완성 = _수(v["완성개월"], 자리 + ".완성개월", 최소=지연)
    반입 = [시작 + 간격 * i for i in range(횟수)]
    return _반입함수(반입, 단위, 지연, 완성), 반입


def _프로젝트읽기(p, 날것, 시, 반입표):
    """프로젝트 p 의 한 시나리오 → None(열별) 또는 (라인, 반입 월 목록, 회당금액, 앞개월, 앞비중, 뒤개월, 뒤비중)."""
    자리 = "일정.프로젝트.%d" % p
    v = _풀기(날것, 시, 자리)
    꼴 = v.get("꼴")
    if 꼴 not in 프로젝트꼴:
        raise 일정오류("%s.꼴 「%s」 — %s 가운데 하나를 적습니다" % (자리, 꼴, " · ".join(프로젝트꼴)))
    _키검사(v, 프로젝트꼴[꼴], 자리)
    if 꼴 == "열별":
        return None
    j = _수(v["라인"], 자리 + ".라인", 정수=True, 최소=1)
    if 반입표.get(j) is None:
        raise 일정오류("%s.라인 이 %d 입니다 — `일정.라인` 에 「반입」 꼴로 적은 라인이어야 합니다" % (자리, j))
    회당 = _수(v["회당금액"], 자리 + ".회당금액")
    앞 = _수(v["앞개월"], 자리 + ".앞개월", 정수=True, 최소=0)
    뒤 = _수(v["뒤개월"], 자리 + ".뒤개월", 정수=True, 최소=0)
    앞비 = _수(v["앞비중"], 자리 + ".앞비중", 최소=0)
    뒤비 = _수(v["뒤비중"], 자리 + ".뒤비중", 최소=0)
    if (앞 == 0 and 앞비 != 0) or (뒤 == 0 and 뒤비 != 0):
        raise 일정오류("%s — 개월이 0 인 쪽의 비중은 0 이어야 합니다(앞 %s개월 %s · 뒤 %s개월 %s)" % (자리, 앞, 앞비, 뒤, 뒤비))
    return j, 반입표[j], 회당, 앞, 앞비, 뒤, 뒤비


def _다듬기(v):
    """유효숫자 15자리(엑셀이 지니는 자릿수) — 덧셈 끝자리의 부동소수 잡음을 걷는다."""
    return float("%.15g" % v)


# ────────────────────────────────────────────────────────────── 지문

def _정규화(o):
    """지문에 넣을 꼴 — 설명 키를 걷고, 정수인 수는 정수로, 월 글은 "YYYY-MM" 으로."""
    if isinstance(o, dict):
        return {"%s" % k: _정규화(v) for k, v in o.items() if not _설명키(k)}
    if isinstance(o, list):
        return [_정규화(x) for x in o]
    if isinstance(o, bool):
        return o
    if isinstance(o, (int, float)):
        return int(o) if int(o) == o else float(o)
    if isinstance(o, str):
        m = re.match(r"^\s*(\d{4})-(\d{1,2})\s*$", o)
        return "%s-%02d" % (m.group(1), int(m.group(2))) if m else o
    return o


def 지문(가정, 축=None):
    """정규화한 `일정` 구획(지문 빼고) + `기간` 의 네 값 + 기준일 열 날짜 → sha1 앞 16자.
    기준일 열 날짜는 열이 서는 날(날짜 둘 — 재무기준일 F)이다. 기간축이 `재무기준일` 을 주면 그것, 아니면 `평가기준일`(옛 축 · F = T — 지문 그대로).
    몸의 열쇠 이름 「평가기준일」 은 옛 지문과 같게 두려고 그대로 쓴다."""
    축 = 축 or 기간축(가정)
    일정 = {k: v for k, v in 가정["일정"].items() if k != 지문키}
    열날 = getattr(축, "재무기준일", None) or 축.평가기준일
    몸 = {"일정": _정규화(일정),
          "기간": {k: int(getattr(축, k)) for k in 기간지문키},
          "평가기준일": 열날.isoformat()}
    글 = json.dumps(몸, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha1(글.encode("utf-8")).hexdigest()[:16]


