def 전개(가정):
    """`일정` 구획을 기간 축의 열별 값으로 편다. 가정을 고치지 않는다.

    → {"지문": 글, "기준일": 기간 ID, "예측": [기간 ID], "줄": [{번호 · 이름 · 요약}],
       "값": {번호(글): {시나리오: {기간 ID: 값}}}, "밖": {번호(글): {시나리오: {"앞": 금액, "뒤": 금액}}},
       "직접": [열별 꼴의 프로젝트 번호], "알림": [글]}"""
    if not isinstance(가정, dict) or not isinstance(가정.get("일정"), dict):
        raise 일정오류("일정 이 객체가 아닙니다 — {지문, 라인, 프로젝트}")
    일정 = 가정["일정"]
    모르는 = [k for k in 일정 if k not in 구획키 and not _설명키(k)]
    if 모르는:
        raise 일정오류("일정 — 모르는 키 %s (받는 키: %s)" % (" · ".join(모르는), " · ".join(구획키)))
    try:
        축 = 기간축(가정)
    except 기간축오류 as e:
        raise 일정오류("%s" % e)
    달 = 열의달(축)
    기준일 = 축.ID[축.기준일]
    예측 = [축.ID[i] for i in 축.예측]
    첫달, 끝달 = 달[예측[0]][0], 달[예측[-1]][0] + 달[예측[-1]][1]          # 예측기간 = [첫달, 끝달)
    라인들 = _자리들(일정.get("라인"), "라인", 라인수상한)
    프로젝트들 = _자리들(일정.get("프로젝트"), "프로젝트", 프로젝트수상한)
    선언라인, 선언프로젝트 = _선언(가정)
    for 이름, 있는, 선언 in (("라인", 라인들, 선언라인), ("프로젝트", 프로젝트들, 선언프로젝트)):
        안된 = [n for n, _ in 있는 if 선언 is not None and n not in 선언]
        if 안된:
            raise 일정오류("일정.%s 의 %s 은 구조가 선언하지 않은 번호입니다(선언한 번호: %s)"
                          % (이름, " · ".join("%d" % n for n in 안된), " · ".join("%s" % n for n in sorted(선언)) or "없음"))

    값, 밖, 줄, 직접, 알림 = {}, {}, [], [], []
    for 시 in 시나리오목록:
        반입표 = {}
        for j, 날것 in 라인들:
            f, 반입표[j] = _라인읽기(j, 날것, 시)
            평균번호, 기말번호 = 능력번호(j)
            평균, 기말 = {}, {기준일: _다듬기(f(달[기준일][0] + 달[기준일][1] - 1))}
            for ID in 예측:
                첫, n = 달[ID]
                평균[ID] = _다듬기(sum(f(t) for t in range(첫, 첫 + n)) / n)
                기말[ID] = _다듬기(f(첫 + n - 1))
            값.setdefault("%d" % 평균번호, {})[시] = 평균
            값.setdefault("%d" % 기말번호, {})[시] = 기말
        for p, 날것 in 프로젝트들:
            읽은 = _프로젝트읽기(p, 날것, 시, 반입표)
            if 읽은 is None:
                continue
            j, 반입, 회당, 앞, 앞비, 뒤, 뒤비 = 읽은
            if abs(앞비 + 뒤비 - 1.0) > 1e-9:
                알림.append("일정.프로젝트.%d(%s) — 앞비중 + 뒤비중 이 %s 입니다(1 이 아니면 회당 금액이 다 실리지 않습니다)"
                            % (p, 시, _다듬기(앞비 + 뒤비)))
            열 = dict.fromkeys(예측, 0.0)
            밖앞 = 밖뒤 = 0.0
            for r in 반입:
                for t in range(r - 앞, r + 뒤):
                    금 = 회당 * ((앞비 / 앞) if t < r else (뒤비 / 뒤))
                    if t < 첫달:
                        밖앞 += 금
                    elif t >= 끝달:
                        밖뒤 += 금
                    else:
                        for ID in 예측:
                            if 달[ID][0] <= t < 달[ID][0] + 달[ID][1]:
                                열[ID] += 금
                                break
            번호 = "%d" % 프로젝트번호(p)
            값.setdefault(번호, {})[시] = {ID: _다듬기(x) for ID, x in 열.items()}
            밖.setdefault(번호, {})[시] = {"앞": _다듬기(밖앞), "뒤": _다듬기(밖뒤)}

    for j, 날것 in 라인들:
        꼴 = 날것.get("꼴")
        이름 = (선언라인 or {}).get(j) or "라인 %d" % j
        평균번호, 기말번호 = 능력번호(j)
        줄.append({"번호": 평균번호, "이름": "%s 생산능력 (기간 평균)" % 이름,
                   "요약": "일정 구획의 라인 %d(%s 꼴)에서 낸 월별 생산능력을 그 열에 든 달로 평균한 값" % (j, 꼴)})
        줄.append({"번호": 기말번호, "이름": "%s 생산능력 (기말)" % 이름,
                   "요약": "일정 구획의 라인 %d(%s 꼴)에서 낸 월별 생산능력의 그 열 마지막 달 값" % (j, 꼴)})
    for p, 날것 in 프로젝트들:
        if 날것.get("꼴") == "열별":
            직접.append(p)
            continue
        이름 = (선언프로젝트 or {}).get(p) or "프로젝트 %d" % p
        줄.append({"번호": 프로젝트번호(p), "이름": "%s CAPEX (환율 조정 전)" % 이름,
                   "요약": "일정 구획의 프로젝트 %d(반입연동 꼴)에서 반입마다 편 월별 지출을 그 열에 든 달로 더한 값" % p})
    return {"지문": 지문(가정, 축), "기준일": 기준일, "예측": 예측, "줄": 줄, "값": 값, "밖": 밖,
            "직접": 직접, "알림": sorted(set(알림))}


def 적기(가정, 결과):
    """전개한 값 · 지문 · 근거의 첫머리를 가정 사전에 적는다(제자리)."""
    칸들 = 가정.setdefault("가정", {})
    근거 = 가정.setdefault("근거", {})
    if not isinstance(칸들, dict) or not isinstance(근거, dict):
        raise 일정오류("가정 · 근거 가 객체가 아닙니다")
    머리 = 근거머리 + 결과["지문"][:8]
    for 줄 in 결과["줄"]:
        번호 = "%d" % 줄["번호"]
        칸들[번호] = copy.deepcopy(결과["값"][번호])
        칸 = 근거.get(번호)
        if 칸 is None:
            칸 = []
        if not isinstance(칸, list) or len(칸) > 근거칸수:
            raise 일정오류("근거.%s 가 네 칸 목록이 아닙니다 — [출처, 기준일, 산정 근거, 비고]" % 번호)
        칸 = ["" if x is None else x for x in 칸] + [""] * (근거칸수 - len(칸))
        본문 = _근거머리꼴.sub("", "%s" % 칸[산정근거칸]).strip()
        칸[산정근거칸] = "%s · %s" % (머리, 본문 or 줄["요약"])
        근거[번호] = 칸
    옛 = 가정["일정"]
    새 = {지문키: 결과["지문"]}
    for k, v in 옛.items():
        if k not in (지문키, 밖키):
            새[k] = v
    if 결과["밖"]:
        새[밖키] = copy.deepcopy(결과["밖"])
    가정["일정"] = 새
    return 가정


def _같은가(a, b):
    if isinstance(a, bool) or isinstance(b, bool) or not isinstance(a, (int, float)) or not isinstance(b, (int, float)):
        return False
    return abs(a - b) <= 허용오차 * max(1.0, abs(a), abs(b))


def 검산(가정):
    """다시 전개해 가정 파일의 값 · 지문 · 근거의 첫머리와 견준다 → (결과, 어긋남 목록). 가정을 고치지 않는다."""
    결과 = 전개(가정)
    어긋남 = []
    적힌지문 = 가정["일정"].get(지문키)
    if 적힌지문 != 결과["지문"]:
        어긋남.append("일정.지문 — 파일 「%s」 · 지금의 일정 구획 「%s」 (일정 구획 · 기간 · 평가기준일이 전개한 뒤에 바뀌었습니다)"
                      % (적힌지문, 결과["지문"]))
    머리 = 근거머리 + 결과["지문"][:8]
    for 줄 in 결과["줄"]:
        번호 = "%d" % 줄["번호"]
        적힌 = (가정.get("가정") or {}).get(번호)
        if not isinstance(적힌, dict):
            어긋남.append("가정.%s (%s) — 값이 없습니다" % (번호, 줄["이름"]))
            continue
        for 시 in 시나리오목록:
            벌 = 적힌.get(시, 적힌.get("공통"))
            새 = 결과["값"][번호][시]
            if not isinstance(벌, dict):
                어긋남.append("가정.%s.%s (%s) — 값이 없습니다" % (번호, 시, 줄["이름"]))
                continue
            for ID in 새:
                if ID not in 벌:
                    어긋남.append("가정.%s.%s.%s — 값이 없습니다(일정의 값 %s)" % (번호, 시, ID, _글(새[ID])))
                elif not _같은가(벌[ID], 새[ID]):
                    어긋남.append("가정.%s.%s.%s — 파일 %s · 일정의 값 %s" % (번호, 시, ID, _글(벌[ID]), _글(새[ID])))
            for ID in 벌:
                if ID not in 새:
                    어긋남.append("가정.%s.%s.%s — 일정이 내지 않는 열에 값 %s 이 있습니다" % (번호, 시, ID, _글(벌[ID])))
        칸 = (가정.get("근거") or {}).get(번호)
        산정 = 칸[산정근거칸] if isinstance(칸, list) and len(칸) > 산정근거칸 else None
        if not ("%s" % (산정,)).startswith(머리):
            어긋남.append("근거.%s 의 산정 근거 칸 — 첫머리가 「%s」 가 아닙니다" % (번호, 머리))
    return 결과, 어긋남


# ────────────────────────────────────────────────────────────── 화면 · 파일

def _글(v):
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        return "%s" % (v,)
    글 = "{:,.6f}".format(v)
    return 글.rstrip("0").rstrip(".") if "." in 글 else 글


def 찍기(결과, 쓰기=print):
    """전개한 값의 표."""
    for 줄 in 결과["줄"]:
        번호 = "%d" % 줄["번호"]
        열 = list(결과["값"][번호][시나리오목록[0]])
        쓰기("A-%s %s" % (번호, 줄["이름"]))
        쓰기("  %-4s %s" % ("", " ".join("%18s" % ID for ID in 열)))
        for 시 in 시나리오목록:
            쓰기("  %-4s %s" % (시, " ".join("%18s" % _글(결과["값"][번호][시][ID]) for ID in 열)))
        if 번호 in 결과["밖"]:
            for 시 in 시나리오목록:
                b = 결과["밖"][번호][시]
                if b["앞"] or b["뒤"]:
                    쓰기("  예측기간 밖의 지출(%s): 평가기준일까지 %s · 최종 예측 연도 뒤 %s — 열별 값에 들어 있지 않습니다"
                         % (시, _글(b["앞"]), _글(b["뒤"])))
    for p in 결과["직접"]:
        쓰기("프로젝트 %d 는 「열별」 꼴입니다 — 이 도구가 적지 않습니다(A-%d 에 직접 적고 산정 근거를 채웁니다)" % (p, 프로젝트번호(p)))
    for 글 in 결과["알림"]:
        쓰기("알림: %s" % 글)


def _읽기(경로):
    with io.open(경로, "r", encoding="utf-8") as f:
        return json.load(f)


def _쓰기(경로, 값):
    임시 = 경로 + ".일정전개임시"
    with io.open(임시, "w", encoding="utf-8", newline="\n") as f:
        json.dump(값, f, ensure_ascii=False, indent=1, allow_nan=False)
        f.write("\n")
    os.replace(임시, 경로)


