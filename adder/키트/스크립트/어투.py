# -*- coding: utf-8 -*-
"""어투 — 레터 글의 끝맺음을 가르고 바꾼다(레터 v27 문장 단계 · 2026-11-11).

레터의 독자는 재무제표를 읽을 줄 아는 개인투자자이고, 레터는 합쇼체(~습니다)로 설명한다. 평서체(~다)와 섞이지 않게
끝맺음의 판정과 바꾸기를 이 한 곳에 둔다. 판정을 쓰는 곳 — 게이트 ③(`레터.문장검수` 「평서체 끝」) · 넣기 검수(`레터.원고검사`) ·
인터랙티브 판의 고정 글 검사(`레터인터랙티브.틀문체`) · 문체검사 H1(`끝꼴`). 바꾸기를 쓰는 곳 — `원고어투.py`(지난 회차의 원고 묶음 ·
편집 목록 · 가정 파일의 글 블록).

  평서체끝(글)            → [(줄 번호, 낱말, 줄)] 줄글의 문장이 평서체(~다)로 끝난 곳
  끝꼴(문장)              → 「평서」 · 「합쇼」 · 「기타」 — 문장 하나의 끝맺음 꼴
  합쇼체로(글)            → (새 글, 바꾼 수, 못 바꾼 것[]) 문장 끝의 평서체만 합쇼체로. 숫자 · 장부 자리표시 · 낫표 인용 · 코드는 그대로.
                            숫자 바로 뒤의 한 글자 + 「다」 는 명사 + 서술격(「779주다」 → 「779주입니다」 · `숫자뒤명사` — 1.1.19)
  합쇼(낱말)              → 「했다」 → 「했습니다」 · 「이다」 → 「입니다」 · 「한다」 → 「합니다」 … (모르면 None)
  평서로(글)              → 합쇼체 끝을 평서체 꼴로 되돌린 글 — 평서체로 적은 낱말 목록(상투어 · 비유어 …)을 합쇼체 글과 맞대는 데만 쓴다
  방향(값, 오름, 내림, 같음) → 증감 방향의 낱말(부호로 방향을 대신하지 않는다 — 문장 원칙 6)

무엇을 보나(평서체끝)
  - 보는 줄: 본문 · 3분 레터 · 부록의 줄글과 불릿, 「> 」 인용 띠(「> 원문:」 은 빼고), 굵은 머리를 단 문단, 그림 · 표 제목 줄의 설명 글
  - 빼는 줄: 「#」 제목 · 「|」 표 · 「> 원문:」 · 「```」 코드 · 「$$」 수식 · 「<」 로 여는 HTML 줄과 주석 · 목차 링크 줄 ·
    그림 · 표 제목 줄의 굵은 제목(「**그림 N. …**」 — 주장 문장이라 어투를 따로 정하지 않는다 · 그 뒤 「 — 」 설명은 본다)
  - **낫표 안은 보지 않는다.** 「…」 · 『…』 안은 회사 · 자료의 말을 옮긴 인용이거나 이름이다 — 인용한 원문의 어투는 바꾸지 않는다.
    낫표 밖에서 문장이 끝나면(「…」고 밝혔다) 그 끝맺음은 본다. 장부 자리표시 `{…}` 와 `코드` 안도 보지 않는다
  - 문장 끝: 낱말 끝 「다」 뒤에 마침표 · 물음표 · 느낌표 · 쌍점 · 여는 괄호 · 닫는 괄호 · 「 —」 가 오거나 줄이 끝나는 자리.
    「ㅂ니다 · 습니다」 로 끝나면 합쇼체다. 「바다」 · 「캐나다」 처럼 「다」 로 끝나는 이름은 뺀다(`이름다`)
"""
from __future__ import annotations

import re

__all__ = ["평서체끝", "평서체문장", "합쇼체로", "합쇼", "합쇼체낱말", "방향", "끝찾기", "끝꼴", "평서로", "숫자뒤명사"]

_가, _힣 = 0xAC00, 0xD7A3
_ㄴ, _ㄹ, _ㅂ = 4, 8, 17

# 「다」 로 끝나지만 서술어가 아닌 낱말(이름 · 일반 명사)
이름다 = ("바다", "캐나다", "플로리다", "네바다", "우간다", "르완다")
# 「이」 로 끝나는 명사 + 서술격 「다」(차이다 → 차이입니다 — 「차입니다」 가 아니다)
_이명사 = ("차이", "사이", "길이", "높이", "깊이", "넓이", "나이", "아이", "오이")
# 받침 없는 줄기의 용언(형용사 · 서술격) — 이 말로 끝나면 줄기에 ㅂ 을 붙인다(크다 → 큽니다 · 다르다 → 다릅니다)
_열린용언끝 = ("다르다", "빠르다", "이르다", "가파르다", "고르다", "바르다", "그르다", "모르다", "느리다", "흐리다",
          "나쁘다", "기쁘다", "바쁘다", "아프다", "슬프다", "예쁘다")
_열린용언낱말 = ("크다", "쓰다", "되다", "자다", "가다", "오다", "보다", "주다", "두다", "하다")
_열린줄기 = ("이", "니", "하", "되")          # 서술격 「이다」 · 「아니다」 · 「-하다」 · 「되다」


def _분해(c):
    n = ord(c) - _가
    return n // 588, (n % 588) // 28, n % 28


def _조합(초, 중, 종):
    return chr(_가 + 초 * 588 + 중 * 28 + 종)


def _한글(c):
    return bool(c) and _가 <= ord(c) <= _힣


def _ㅂ붙여(s):
    """줄기 끝 글자의 받침을 ㅂ 으로 — 「하」 → 「합」 · 「든」 → 「듭」 · 「길」 → 「깁」."""
    초, 중, _ = _분해(s[-1])
    return s[:-1] + _조합(초, 중, _ㅂ)


def 합쇼체낱말(낱말):
    """「…ㅂ니다 · 습니다」 로 끝나는가(「아니다」 는 아니다)."""
    w = 낱말
    return len(w) >= 3 and w.endswith("니다") and _한글(w[-3]) and _분해(w[-3])[2] == _ㅂ


def 합쇼(낱말):
    """평서체 서술어 한 낱말(「다」 로 끝남) → 합쇼체. 이미 합쇼체거나 서술어가 아니면 None.
    낱말이 「다」 하나면(앞이 숫자 · 기호 · 영문 · 자리표시) 서술격의 줄임으로 보고 「입니다」."""
    w = 낱말
    if not w.endswith("다") or 합쇼체낱말(w):
        return None
    if w in 이름다:
        return None
    s = w[:-1]
    if not s:
        return "입니다"
    if not _한글(s[-1]):
        return s + "입니다"
    for n in _이명사:
        if s.endswith(n):
            return s + "입니다"
    if s.endswith("이하") or s.endswith("영하"):
        return s + "입니다"
    if w == "는다":                                   # 늘다 → 는다
        return "늡니다"
    _초, _중, 종 = _분해(s[-1])
    if 종 == _ㄴ:
        if s[-1] == "는":                             # 받침 있는 줄기 + 는다(받는다 · 않는다 · 남는다)
            return s[:-1] + "습니다"
        return _ㅂ붙여(s) + "니다"                     # 받침 없는 · ㄹ 줄기 + ㄴ다(한다 · 된다 · 만든다 · 오른다)
    if 종 == _ㄹ:                                     # ㄹ 줄기 형용사(길다 → 깁니다 · 드물다 → 드뭅니다)
        return _ㅂ붙여(s) + "니다"
    if 종 == 0:
        if s[-1] in _열린줄기 or w.endswith(_열린용언끝) or w in _열린용언낱말:
            return _ㅂ붙여(s) + "니다"
        return s + "입니다"                            # 받침 없는 명사 + 서술격 줄임(주가다 → 주가입니다)
    return s + "습니다"                                # 받침 있는 줄기(있다 · 없다 · 했다 · 같다 · 많다 · 겠다)


# ── 문장 끝 찾기 ────────────────────────────────────────────────────────────

_끝뒤 = r"(?=\**(?:[.!?:(]|\)|\s+—|\s*$))"
_끝식 = re.compile(r"([가-힣]*)다" + _끝뒤)


def _가리기(글):
    """낫표 · 겹낫표 · 장부 자리표시 { } · 코드 ` ` 안을 같은 길이의 빈칸 글자(\x01)로 가린다(자리 번호는 그대로)."""
    밖 = list(글)
    깊 = {"「": "」", "『": "』", "{": "}", "`": "`"}
    i, n = 0, len(글)
    while i < n:
        c = 글[i]
        if c in 깊:
            닫 = 깊[c]
            j = 글.find(닫, i + 1)
            if c == "「":                              # 겹친 낫표(「…「…」…」)는 바깥 닫힘까지
                k, d = i + 1, 1
                while k < n and d:
                    if 글[k] == "「":
                        d += 1
                    elif 글[k] == "」":
                        d -= 1
                    k += 1
                j = k - 1 if d == 0 else -1
            if j < 0:
                i += 1
                continue
            for k in range(i + 1, j):
                밖[k] = "\x01"
            i = j + 1
            continue
        i += 1
    return "".join(밖)


def 끝찾기(글, 코드=False):
    """글 한 조각에서 문장 끝 평서체 자리 — [(시작, 끝, 낱말, 새 낱말 또는 None)]. 낫표 · 자리표시 · 코드 안은 보지 않는다.
    코드 = True 면 파이썬 문자열 조각으로 본다 — 조각 끝의 「다」 도 문장 끝이다(마침표는 다른 조각이 붙인다)."""
    가린 = _가리기(글)
    낸 = []
    for m in _끝식.finditer(가린):
        a, b = m.start(), m.end()
        w = 글[a:b]
        if not m.group(1):                            # 「다」 하나 — 앞이 처음 · 빈칸이면 부사(모두 다), 숫자 · 기호 · 영문 뒤면 서술격 줄임
            if a == 0 or 글[a - 1].isspace():
                continue
        if 합쇼체낱말(w) or w in 이름다:
            continue
        낸.append((a, b, w, 합쇼(w)))
    return 낸


_빼는줄 = re.compile(r"^(?:#|\||<|\$\$|> ?원문:|!\[)")
_그림제목 = re.compile(r"^\*\*(?:그림|표)(?: \d+)?\. .*?\*\*\s*(?:—\s*)?")       # 그림 · 표 제목(굵은 머리) — 그 뒤의 설명 글은 본다
_목차줄 = re.compile(r"^[-*] \[[^\]]+\]\(#[^)]*\)\s*$")


def _줄글인가(t):
    return bool(t) and not _빼는줄.match(t) and not _목차줄.match(t)


def _줄머리걷기(t):
    t = re.sub(r"^>\s?", "", t)
    t = re.sub(r"^(?:[-*+]|\d+\.)\s+", "", t)
    return t


def 평서체문장(줄):
    """줄글 한 줄의 평서체 끝 낱말들(표 · 제목 따위를 가리지 않는다 — 부른 쪽이 줄글만 준다). 그림 · 표 제목 줄은 굵은 제목을 걷고 설명만 본다."""
    t = _그림제목.sub("", 줄.strip(), count=1)
    return [w for _a, _b, w, _n in 끝찾기(_줄머리걷기(t))]


def 평서체끝(글):
    """레터 글(마크다운)에서 줄글의 문장이 평서체로 끝난 곳 — [(줄 번호, 낱말, 줄)]."""
    낸, 코드, 수식 = [], False, False
    for n, 줄 in enumerate(글.split("\n"), 1):
        t = 줄.strip()
        if t.startswith("```"):
            코드 = not 코드
            continue
        if t == "$$":
            수식 = not 수식
            continue
        if t.startswith("$$") and t.endswith("$$"):
            continue
        if 코드 or 수식 or not _줄글인가(t):
            continue
        for w in 평서체문장(t):
            낸.append((n, w, t))
    return 낸


def 합쇼체로(글, 코드=False):
    """문장 끝의 평서체를 합쇼체로 — (새 글, 바꾼 수, 못 바꾼 것[(낱말, 그 둘레)]).
    표 · 제목 · 코드 블록 줄도 그대로 둔다(마크다운 글을 줄 때). 코드 = True 는 파이썬 문자열 조각 하나(줄 판정 없이 조각 전체)."""
    if 코드:
        return _조각바꾸기(글, 코드=True)
    밖, 수, 못 = [], 0, []
    블록 = False
    for 줄 in 글.split("\n"):
        t = 줄.strip()
        if t.startswith("```"):
            블록 = not 블록
            밖.append(줄)
            continue
        if 블록 or not _줄글인가(t):
            밖.append(줄)
            continue
        새, k, 남 = _조각바꾸기(줄)
        밖.append(새)
        수 += k
        못 += 남
    return "\n".join(밖), 수, 못


_수앞 = re.compile(r"[\d}]")                         # 숫자 · 숫자를 내는 장부 자리표시의 닫힘


def 숫자뒤명사(글, a, w):
    """1.1.19 — 끝 낱말 w(글[a:] · 「다」 로 끝남)가 숫자(또는 장부 자리표시의 닫힘 「}」) 바로 뒤에 붙은 한 글자 + 「다」 인가.
    숫자에 붙은 한글은 용언이 아니다(용언은 숫자에 붙여 쓰지 않는다) — 「779주다」 · 「52주다」 · 「3자다」 의 한 글자는 수 단위 · 명사이고
    끝은 서술격이다(「779주입니다」 — 「779줍니다」 가 아니다). 「10이다」 는 서술격 「이」 그대로(「10입니다」). 판정은 낱말 목록이 아니라 앞 글자다."""
    return len(w) == 2 and w[0] != "이" and a > 0 and bool(_수앞.match(글[a - 1]))


def _조각바꾸기(글, 코드=False):
    자리 = 끝찾기(글, 코드=코드)
    밖, 앞, 수, 못 = [], 0, 0, []
    for a, b, w, 새 in sorted(자리):
        if a < 앞:
            continue
        if 숫자뒤명사(글, a, w):                       # 1.1.19 — 「779주다」 → 「779주입니다」(모든 호출자가 같은 판정 — `원고어투` 와 같다)
            새 = w[0] + "입니다"
        if 새 is None:
            못.append((w, 글[max(0, a - 20):b + 5]))
            continue
        밖.append(글[앞:a])
        밖.append(새)
        앞 = b
        수 += 1
    밖.append(글[앞:])
    return "".join(밖), 수, 못


def 방향(값, 오름, 내림, 같음=None):
    """증감의 방향 낱말 — 값 > 0 이면 오름, < 0 이면 내림, 0(또는 None)이면 같음(없으면 오름 · 내림 가운데 쓸 수 없어 None).
    부호와 「움직였다 · 변했다」 로 방향을 대신하지 않는다(문장 원칙 6). 값은 차이 · 증감률 따위 부호가 뜻이 되는 숫자."""
    try:
        v = float(값)
    except (TypeError, ValueError):
        return 같음
    if v > 0:
        return 오름
    if v < 0:
        return 내림
    return 같음

def 평서로(글):
    """합쇼체 끝맺음을 평서체 꼴로 되돌린 글 — **검사의 낱말 대조용**(레터에 쓰지 않는다). 낱말 목록(상투어 · 비유어 · 메타 선언 · 안내 꼴)은
    평서체로 적혀 있어 합쇼체 글에서도 같은 표현을 찾으려고 쓴다 — 목록을 두 벌로 늘리지 않는다(금지 목록은 늘리지 않는다).
    「…습니다」 → 「…다」(있습니다 → 있다 · 했습니다 → 했다), 「…ㅂ니다」 → 「…ㄴ다」(합니다 → 한다 · 됩니다 → 된다), 「입니다」 → 「이다」.
    형용사(큽니다 → 큰다)는 바르게 되돌리지 못한다 — 대조용이라 둔다."""
    def 하나(m):
        w = m.group(0)
        if not 합쇼체낱말(w):
            return w
        if w.endswith("습니다"):
            return w[:-3] + "다"
        s = w[:-2]
        if s.endswith("입"):
            return s[:-1] + "이다"
        초, 중, _ = _분해(s[-1])
        return s[:-1] + _조합(초, 중, _ㄴ) + "다"
    return re.sub(r"[가-힣]+니다", 하나, 글)

_합쇼끝 = re.compile(r"(?:니다|니까|죠|까요)[.?!]?$")


def 끝꼴(문장):
    """문장 하나의 끝맺음 꼴 — 「평서」(~다 · `끝찾기` 가 잡는 자리가 있음) · 「합쇼」(~니다 · ~니까 · ~죠 · ~까요) · 「기타」(명사 · 물음 따위).
    게이트 ③ 의 「평서체 끝」 과 문체검사 H1 이 같은 판정을 쓴다. 문장 끝 괄호(「…했습니다(15절).」)는 떼고 본다."""
    g = re.sub(r"[\s*」』\]\"']+$", "", ("%s" % 문장).strip())
    if 끝찾기(g):
        return "평서"
    떼 = re.sub(r"\s*\([^()]*\)\s*([.?!]?)$", lambda m: m.group(1), g)
    if _합쇼끝.search(g) or _합쇼끝.search(떼):
        return "합쇼"
    return "기타"
