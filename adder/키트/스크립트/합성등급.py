# -*- coding: utf-8 -*-
"""합성등급 — 이자보상배율 → 다모다란 등급 → 스프레드 → 세전 타인자본비용 (2026-10-17 S7-11).

왜 있는가
    타인자본비용 규칙은 「등급이 없으면 합성등급」 이라고만 했고 그 계산을 하는 도구가 없었다. 다모다란 등급표는 둘(대형 비금융 ·
    중소형 · 고위험)인데 어느 것을 쓰는지 규칙이 없어 회차마다 사람이 고르는 자리였다. 무등급 국내 회사의 Kd 가 사람마다
    다른 길로 나왔다 — 금융투자협회 국내 등급 수익률(국내 척도)에 글로벌 척도 등급을 붙이거나, 다모다란 스프레드를 어떤 Rf 위에
    얹는지 맞추지 않았다.

규칙 (값을 보기 전에 정해진 순서)
    ① 분자는 **기준일 연환산 EBIT**(반기 실적이면 직전 12개월 · 그게 없으면 반기 × 2 — 어느 쪽인지 적는다)
    ② 분모는 **이자비용 단독**이다. 금융원가 · 금융비용 묶음을 쓰지 않는다
    ③ **무차입이면 최상위 구간** — 이자비용이 0 이거나 순차입금이 음수(현금 > 이자부부채)면 문면대로 나누지 않는다 —
       적자 회사가 최하 등급으로 발산한다. 그 판정을 적는다
    ④ 표 선택 — **시가총액 50억 달러 이상이면 「대형 비금융」, 미만이면 「중소형·고위험」**(다모다란 표 머리말의 구분).
       금융회사는 「금융회사」 표 · 인프라 · 유틸리티는 `--표 인프라` 로 그 표
    ⑤ **국내 회사의 척도** — 합성등급은 다모다란의 **글로벌 척도**다. 그래서 국내 무등급 회사는
       「합성등급(글로벌) → 다모다란 스프레드 + 표시통화 국채(= 무위험이자율 + 국가 부도스프레드)」 가 본값이다.
       금융투자협회 등급별 회사채 수익률(**국내 척도**)은 **실제 국내 신용등급이 있을 때만** 쓴다 — 글로벌 척도 등급을 국내
       척도 수익률 표에 붙이지 않는다(국내 AA+ 와 글로벌 AA+ 는 같은 위험이 아니다)
    ⑥ **스프레드는 국채 위의 값이다.** 다모다란 등급 스프레드는 국채 수익률 위의 가산이다. 가정이 무위험이자율을
       「부도스프레드차감」 으로 낼 때 엔진의 Kd = 무위험이자율 + 스프레드 칸이므로 **스프레드 칸에 등급 스프레드 +
       국가 부도스프레드** 를 넣어야 Kd = 국채 + 등급 스프레드가 된다. 이 도구가 그 값을 `가정_스프레드` 로 낸다

사용
    python 스크립트/합성등급.py --기준일 2026-06-30 --국가 KR --EBIT 152000 --이자비용 4100 --시가총액USD 3.2e9
    python 스크립트/합성등급.py --기준일 2026-06-30 --국가 US --EBIT 9.1e9 --이자비용 0 --순차입금 -2e9 --시가총액USD 2.1e11
    (금액 단위는 EBIT 와 이자비용이 같기만 하면 된다 — 비율만 쓴다)

가져다 쓰기
    from 합성등급 import 판정
    r = 판정(ebit, 이자비용, 시가총액USD, 표들, 순차입금=None, 표선택=None)
"""
from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

대형문턱USD = 5e9          # 다모다란 표 머리말 「large non-financial service companies (market cap > $5 billion)」


def 표고르기(시가총액USD=None, 표선택=None):
    """(표 이름, 사유). 값을 보기 전에 정해진 규칙 — 표선택(금융 · 인프라)이 먼저, 그다음 시가총액 50억 달러."""
    if 표선택 in ("금융", "금융회사"):
        return "금융회사", "금융회사 — 다모다란 금융회사 표"
    if 표선택 in ("인프라", "유틸리티", "인프라·유틸리티"):
        return "인프라·유틸리티", "인프라 · 유틸리티 — 다모다란 그 표"
    if 시가총액USD is None:
        return "중소형·고위험", "시가총액 미상 — 보수적으로 중소형 · 고위험 표(확인 필요)"
    if 시가총액USD >= 대형문턱USD:
        return "대형 비금융", "시가총액 %.2f bn USD ≥ 5 bn — 대형 비금융 표" % (시가총액USD / 1e9)
    return "중소형·고위험", "시가총액 %.2f bn USD < 5 bn — 중소형 · 고위험 표" % (시가총액USD / 1e9)


def 판정(ebit, 이자비용, 시가총액USD, 표들, 순차입금=None, 표선택=None):
    """→ dict(이자보상배율, 등급, 스프레드, 표, 표사유, 판정사유). 표들 = market_data 캐시의 「합성등급 스프레드 표」 값."""
    이름, 표사유 = 표고르기(시가총액USD, 표선택)
    구간들 = (표들 or {}).get(이름) or []
    out = {"이자보상배율": None, "등급": None, "스프레드": None, "표": 이름, "표사유": 표사유, "판정사유": ""}
    if not 구간들:
        out["판정사유"] = "캐시에 「%s」 표가 없다 — market_data.py 로 등급 스프레드 표를 받는다" % 이름
        return out
    위 = max(구간들, key=lambda g: g["이하"])
    # S7R1-N4(S8 개선 1) — 순차입금이 음수(순현금)여도 이자비용이 있으면 이자보상배율로 잰다. 종전에는 순현금이면 무차입으로 보아 최상위 구간을
    # 주었는데, 차입금을 쓰며 이자를 내는 회사의 Kd 를 순현금 하나로 무위험에 붙였다(차입 · 현금이 다른 법인 · 다른 통화에 있는 회사 — 예: 다국적
    # 제조 · 지주). 순현금은 판정 사유에 적는다. 이자비용이 0 이면(분모 0) 무차입 그대로다
    순현금 = 순차입금 is not None and 순차입금 < 0
    무차입 = (not 이자비용) or (순현금 and (ebit is None or ebit <= 0))
    if 무차입:
        out.update({"이자보상배율": None, "등급": 위["등급"], "스프레드": 위["스프레드"],
                    "판정사유": ("무차입 취급 — " + ("이자비용 0(분모 0)" if not 이자비용 else
                                              "순차입금 %s < 0 이고 EBIT 이 0 이하" % 순차입금)
                             + " → 최상위 구간(문면대로 나누면 적자 회사가 최하 등급으로 발산한다)")})
        return out
    if ebit is None:
        out["판정사유"] = "EBIT 이 없다 — 확인 불가"
        return out
    cov = ebit / 이자비용
    out["이자보상배율"] = cov
    if 순현금:
        out["순현금"] = "순차입금 %s < 0 이지만 이자비용이 있어 이자보상배율로 잰다(S7R1-N4)" % 순차입금
    for g in sorted(구간들, key=lambda g: g["이자보상배율_초과"]):
        if g["이자보상배율_초과"] < cov <= g["이하"]:
            out.update({"등급": g["등급"], "스프레드": g["스프레드"],
                        "판정사유": "이자보상배율 %.2f — (%g, %g] 구간" % (cov, g["이자보상배율_초과"], g["이하"])})
            return out
    아래 = min(구간들, key=lambda g: g["이자보상배율_초과"])
    if cov <= 아래["이자보상배율_초과"]:
        out.update({"등급": 아래["등급"], "스프레드": 아래["스프레드"], "판정사유": "이자보상배율 %.2f — 최하 구간 아래" % cov})
    else:
        out.update({"등급": 위["등급"], "스프레드": 위["스프레드"], "판정사유": "이자보상배율 %.2f — 최상위 구간 위" % cov})
    return out


def main():
    ap = argparse.ArgumentParser(allow_abbrev=False, description="합성등급 — 이자보상배율 → 다모다란 등급 · 스프레드")
    ap.add_argument("--기준일", required=True, help="평가기준일 YYYY-MM-DD — 시장데이터 캐시를 이 날짜로 읽는다")
    ap.add_argument("--국가", default="KR", help="시장데이터 캐시 국가(KR · US · ISO 두 글자)")
    ap.add_argument("--EBIT", type=float, required=True, help="기준일 연환산 EBIT(LTM 또는 반기 × 2 — 어느 쪽인지 근거에 적는다)")
    ap.add_argument("--이자비용", type=float, required=True, help="이자비용 단독(금융원가 묶음이 아니다) — 같은 기간 · 같은 단위")
    ap.add_argument("--순차입금", type=float, default=None, help="음수면 무차입 취급(최상위 구간)")
    ap.add_argument("--시가총액USD", type=float, default=None, help="표 선택 — 50억 달러 이상이면 대형 비금융")
    ap.add_argument("--표", default=None, help="금융 · 인프라 — 그 표를 쓴다")
    ap.add_argument("--국내등급", default=None, help="실제 국내 신용등급(있으면 합성등급을 쓰지 않는다 — 금융투자협회 수익률로)")
    a = ap.parse_args()
    import market_data as md
    d, 어디 = md.캐시읽기(a.국가.upper(), a.기준일)
    if not d:
        sys.exit("시장데이터 캐시가 없습니다 — python 스크립트/market_data.py --date %s --country %s 를 먼저 돌립니다" % (a.기준일, a.국가))
    표 = (d.get("합성등급 스프레드 표") or {})
    r = 판정(a.EBIT, a.이자비용, a.시가총액USD, 표.get("값"), a.순차입금, a.표)
    국채 = (d.get(md.국채칸이름(a.국가.upper())) or {}).get("값")
    부도 = (d.get("국가 부도스프레드") or {}).get("값")
    r["표기준일"], r["표출처"] = 표.get("기준일"), 표.get("출처")
    if r["스프레드"] is not None and 국채 is not None:
        r["세전Kd"] = 국채 + r["스프레드"]
        r["가정_스프레드"] = r["스프레드"] + (부도 or 0)
        r["가정_주의"] = ("구조.할인.무위험이자율 = 부도스프레드차감 이면 WACC.<구간>.스프레드 = 등급 스프레드 %.4f + 국가 부도스프레드 %.4f "
                       "= %.4f(Kd = 국채 %.4f + 등급 스프레드). 「직접」(국채 그대로)이면 등급 스프레드만 넣는다"
                       % (r["스프레드"], 부도 or 0, r["가정_스프레드"], 국채))
    if a.국내등급:
        r["국내등급"] = a.국내등급
        r["주의"] = ("실제 국내 등급(%s)이 있다 — 타인자본비용 규칙: 등급이 있으면 합성등급을 쓰지 않는다. 금융투자협회 %s 10년 수익률을 "
                   "회사채수익률(관측수익률 갈래)로 쓰고 이 합성등급은 대조값으로 병기한다" % (a.국내등급, a.국내등급))
    elif a.국가.upper() == "KR":
        r["척도"] = ("글로벌 척도(다모다란) — 금융투자협회 국내 등급 수익률 표에 붙이지 않는다. 본값 = 국고채 + 다모다란 스프레드")
    print(json.dumps(r, ensure_ascii=False, indent=1))


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
