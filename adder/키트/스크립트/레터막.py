def 절글줄(맥, 자리, x):
    """저자 덧글 하나 → 줄들. 글(「{키|꼴}」) · {"글", "뒤"} · {"표": {"머리": [글], "줄": [[글]], "정렬"?}, "뒤"?}. 독자 층이면 어림 꼴."""
