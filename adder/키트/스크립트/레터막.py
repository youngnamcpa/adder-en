def 앞자리글인가(x):
    """절 머리 쪽에 둘 원고인가 — 요소가 「자료 · 분류 · 방법」 만이고 범위 · 한계 따위를 함께 달지 않은 문단(사슬: 공시가 준 것 → 방법 → … → 범위 → 한계)."""
    v = x.get("요소") if isinstance(x, dict) else None
    요 = {v} if isinstance(v, str) else {e for e in (v or []) if isinstance(e, str)}
    return bool(요 & _앞요소) and not (요 & _뒤요소)


