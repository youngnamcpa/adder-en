def 막는몫(값, 키, 몫):
    """막음 지표의 자리가 게이트를 막는가 — 몫이 없으면(원고 조각을 주지 않았다) 막는다. 「원고」 는 「원고막음」 일 때만,
    「섞임」 은 「섞임표시」 에 든 지표가 아니면 막고, 든 지표는 원고 몫처럼 「원고막음」 을 따른다(1.1.13 — 교열 고리가 섞임 문장의 낫표 안을 고친다)."""
    if 몫 == "원고":
        return bool(값.get("원고막음"))
    if 몫 == "섞임":
        return 키 not in (값.get("섞임표시") or ()) or bool(값.get("원고막음"))
    return True


def 막음걸림(값, 뺄=("⑨",)):
    """막음 지표가 문턱을 넘은 자리 → [(등급, 줄, 항목, 조각)] — 막는 자리는 「오류」, 원고 몫으로 둔 자리는 「경보」(항목에 「원고 몫」).
    ⑨(문장 길이)는 게이트 ⑬ 의 문장 길이(`레터문장.점검`)가 같은 몫 규칙으로 막으므로 기본으로 뺀다(두 번 세지 않는다)."""
    낸 = []
    for 키, x in (값.get("항목") or {}).items():
        if x.get("등급") != "막음" or not x.get("넘음") or 키 in 뺄:
            continue
        if 키.startswith("④"):
            낸.append(("오류", 0, "구조%s:%s %s%% — 문턱 %s%%" % (키, x["이름"], x.get("비율"), x.get("문턱")), ""))
            continue
        for z in x.get("자리") or []:
            말 = (" 「%s」" % z["말"]) if z.get("말") else ((" %d번(%s행)" % (z["수"], " · ".join("%d" % k for k in z.get("줄들") or [])))
                                                        if z.get("수") else ((" %d자" % z["길이"]) if z.get("길이") else ""))
            막 = 막는몫(값, 키, z.get("몫"))
            몫 = ((" [%s]" % z["몫"]) if 막 else (" — 원고 몫(%s · 교열 검토가 고친다)" % z["몫"])) if z.get("몫") else ""
            낸.append(("오류" if 막 else "경보", z.get("줄") or 0, "구조%s:%s%s%s" % (키, x["이름"], 말, 몫), (z.get("글") or "")[:90]))
        if x.get("자리수", 0) > len(x.get("자리") or []):
            낸.append(("오류", 0, "구조%s:%s — 자리 %d곳 가운데 %d곳만 적었다(설정 「자리상한」)" % (키, x["이름"], x["자리수"], len(x["자리"])), ""))
    return 낸


def 원고몫목록(값):
    """막음 지표에 걸렸으나 원고 몫으로 둔 자리 → [(지표, 줄, 몫, 문장)] — 교열 검토 단계 · 사람 몫의 목록."""
