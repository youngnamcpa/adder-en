def 지문구조(가정):
    """구조 지문에 넣는 구조 — 가정의 `구조` 에 기본값을 채운 것(`엔진.구조.기본채움`). 구조가 없으면 빈 사전, 틀이 깨진 구조면 적힌 그대로.

    생성기(`구조펴기.키트채움`)가 줄을 펴고 지문을 낼 때 쓰는 것과 같은 사전이다 — 기본값을 적든 안 적든 지문이 같다."""
    원 = 가정.get("구조") if isinstance(가정, dict) else None
    if not isinstance(원, dict):
        return {}
    import importlib                                               # noqa: PLC0415
    채운, 오류 = importlib.import_module("엔진.구조").기본채움(원)
    return 원 if 오류 else 채운


