def 파일지문찍기(경로, 지문):
    """xlsx 파일에 배치 지문을 남긴다 — 사용자 지정 문서 속성 한 조각만 더한다(시트·서식 조각은 바이트 그대로 둔다).

    **짝이 정해지는 자리에서만 부른다**(생성기가 지을 때). 붓기는 부르지 않는다."""
    import tempfile
    import zipfile
    from xml.etree import ElementTree as ET
    with zipfile.ZipFile(경로) as z:
        조각 = [(i, z.read(i.filename)) for i in z.infolist()]
    이름들 = [i.filename for i, _b in 조각]
    새속성 = ('<Properties xmlns="%s"><property name="%s" fmtid="{D5CDD505-2E9C-101B-9397-08002B2CF9AE}" pid="2">'
             '<vt:lpwstr xmlns:vt="%s">%s</vt:lpwstr></property></Properties>'
             % (_속성NS, 지문이름, _값NS, 지문)).encode("utf-8")
    바꿈 = {}
    if _사용자속성 in 이름들:
        ET.register_namespace("", _속성NS)
        ET.register_namespace("vt", _값NS)
        뿌리 = ET.fromstring(dict((i.filename, b) for i, b in 조각)[_사용자속성])
        있던 = [속 for 속 in 뿌리 if 속.get("name") == 지문이름]
        if 있던:
            for 값 in 있던[0]:
                값.text = 지문
        else:
            pid = max([int(속.get("pid") or 1) for 속 in 뿌리] + [1]) + 1
            속 = ET.SubElement(뿌리, "{%s}property" % _속성NS,
                              {"name": 지문이름, "fmtid": "{D5CDD505-2E9C-101B-9397-08002B2CF9AE}", "pid": "%d" % pid})
            ET.SubElement(속, "{%s}lpwstr" % _값NS).text = 지문
        바꿈[_사용자속성] = ET.tostring(뿌리, encoding="utf-8")
    else:
        for 이름, 끝, 넣을 in (("[Content_Types].xml", "</Types>", '<Override PartName="/%s" ContentType="%s"/>' % (_사용자속성, _속성종류)),
                            ("_rels/.rels", "</Relationships>", None)):
            글 = dict((i.filename, b) for i, b in 조각)[이름].decode("utf-8")
            if 넣을 is None:
                쓴 = set(re.findall(r'Id="([^"]+)"', 글))
                n = 1
                while "rId%d" % n in 쓴:
                    n += 1
                넣을 = '<Relationship Type="%s" Target="%s" Id="rId%d"/>' % (_속성관계, _사용자속성, n)
            if 끝 not in 글:
                raise 좌표오류("지문을 못 남겼습니다 — %s 의 꼴을 모릅니다: %s" % (이름, 경로))
            바꿈[이름] = 글.replace(끝, 넣을 + 끝).encode("utf-8")
    손, 임시 = tempfile.mkstemp(suffix=".xlsx", dir=os.path.dirname(os.path.abspath(경로)))
    os.close(손)
    try:
        with zipfile.ZipFile(임시, "w", zipfile.ZIP_DEFLATED) as z:
            for i, b in 조각:
                z.writestr(i, 바꿈.get(i.filename, b))
            if _사용자속성 not in 이름들:
                z.writestr(_사용자속성, 새속성)
        os.replace(임시, 경로)
    finally:
        if os.path.exists(임시):
            os.remove(임시)


class 장(object):
    """openpyxl 시트 한 장을 번호로 만지는 손잡이.

    번호는 이 시트(본 시트)의 것이다. 배치가 줄을 다른 시트로 옮겼으면 그 줄의 칸은 놓인 시트에서 준다(워크북을 받아 둔다)."""

    def __init__(self, 지, ws, 번호, wb=None):
        self.지, self.ws, self.wb = 지, ws, wb
        self.번호 = 지.시트번호(지.sid(번호))
        self.이름 = ws.title

    def 주소(self, 칸번호, 번호=None, 밖허용=False):
        """칸 번호 → 지금 칸 주소(뺀 줄·열이면 None). 다른 시트로 옮겨진 줄이면 놓인 시트에서의 주소다."""
        return self.지.칸(self.번호, 칸번호, 번호, 밖허용)

    def 칸(self, 칸번호, 번호=None, 밖허용=False):
        """칸 번호 → openpyxl 칸. 이 배치에 없는 자리면 None."""
        시트명, a = self.지.자리(self.번호, 칸번호, 번호, 밖허용)
        if a is None:
            return None
        if 시트명 == self.이름:
            return self.ws[a]
        if self.wb is None:
            raise 좌표오류("%s번 %s 은 다른 시트(%s)로 옮겨진 줄입니다 — 워크북 없이 만든 손잡이로는 못 만집니다"
                        % (self.번호, 칸글(칸번호 if 번호 is None else (칸번호, 번호)), 시트명))
        return self.wb[시트명][a]

    def 값(self, 칸번호, 번호=None, 밖허용=False):
        c = self.칸(칸번호, 번호, 밖허용)
        return None if c is None else c.value

    def 쓰기(self, 칸번호, v, 번호=None):
        """쓴 것이면 True. 이 배치에 없는 자리이거나 병합 칸의 딸린 칸이면(쓸 수 없다) False."""
        c = self.칸(칸번호, 번호)
        if c is None or 병합딸린칸(c):
            return False
        c.value = v
        return True

    def 비우기(self, 칸번호, 번호=None):
        return self.쓰기(칸번호, None, 번호)

    def 줄들(self):
        """[(가정 번호, 지금 행)] — 이 시트에 놓인 줄, 지금 놓인 순서대로."""
        return self.지.줄들(self.번호)

    def 말(self, 칸번호, 번호=None):
        return self.지.말(self.번호, 칸번호, 번호)


def 병합딸린칸(칸):
    """병합 범위의 왼쪽 위가 아닌 칸인가 — openpyxl 은 이런 칸에 값을 못 쓴다(AttributeError)."""
    from openpyxl.cell.cell import MergedCell
    return isinstance(칸, MergedCell)


def 묶음스캔(장, 이름열=이름열):
    """줄 이름이 「· 비관 / · 기준 / · 낙관」 인 세 줄을 아래에 가진 줄을 가정 머리 줄로 본다.

    **글이 열쇠인 자리다.** 생성기가 좌표 지도에 「가정묶음」을 실어 주면 이 스캔은 쓰이지 않는다.
    옛 꼴 지도(가정묶음 없음)를 만났을 때만 쓴다 — 생성기가 지은 지도에는 「가정묶음」이 있다."""
    ws, 지 = 장.ws, 장.지
    열 = _열수(지.열(장.번호, 이름열))
    찾음 = []
    줄 = 장.줄들()
    거꾸로 = {n: 번 for 번, n in 줄}
    for 번, n in 줄:
        세 = []
        for k in (1, 2, 3):
            v = ws.cell(row=n + k, column=열).value
            글 = ("%s" % v).replace("·", "").strip() if v is not None else ""
            if 글 != 시나리오목록[k - 1] or (n + k) not in 거꾸로:
                break
            세.append(거꾸로[n + k])
        if len(세) == 3:
            찾음.append((번, tuple(세)))
    return 찾음


def 이름글(틀, 방식, 이름):
    """이름 칸에 쓸 글. 붙임은 이름이 바탕 글에 이미 들어 있으면 바탕 글 그대로다."""
    if 방식 == "붙임":
        return 틀 if 이름 in 틀 else "%s%s%s" % (틀, 붙임이음, 이름)
    return 틀.replace(이름틀자리, 이름)


def 이름틀맞나(틀, 방식, 글):
    """그 칸의 지금 글이 틀에서 나올 수 있는 글인가 — 자리표시가 든 스캐폴드의 글도, 이름이 이미 든 글도 맞는다.

    채움: 틀의 「{이름}」 자리에 무엇이든(한 글자 이상) 든 글.   붙임: 바탕 글 그대로이거나 그 뒤에 「 — 이름」이 붙은 글.
    **자리표시 글자가 무엇인지는 모른다** — 틀의 「{이름}」 자리를 뺀 글이 같은가만 본다."""
    if not isinstance(글, str):
        return False
    글, 틀 = 글.rstrip(), ("%s" % 틀).rstrip()
    if 방식 == "붙임":
        return 글 == 틀 or 글.startswith(틀 + 붙임이음)
    조각 = 틀.split(이름틀자리)
    if len(조각) == 1:
        return 글 == 틀
    return re.fullmatch("(.+?)".join(re.escape(x) for x in 조각), 글, re.S) is not None


def 자리풀기(글):
    """「12!167」(그 줄 전체) · 「12!G167」(그 칸 하나) · 「12!FY2027E@167」(글자가 아닌 열 ID 는 @ 로 번호와 가른다)
    → (시트 번호 글, 열 ID 또는 None, 번호). 꼴이 아니면 None.

    **열 ID 는 적힌 그대로 돌려준다**(대문자로 바꾸지 않는다 — 「2!No74」의 「No」). 지도의 표에 있는 이름으로 맞추는 일은
    `지도.열이름` 이 한다. 열 ID 에 숫자가 섞여 있으면(「H1」「FY2027E」) 번호와 못 가르므로 @ 로 적는다."""
    s = ("%s" % 글).strip()
    if "!" not in s:
        return None
    시, 나머지 = s.split("!", 1)
    시 = 시.strip().split(".", 1)[0].strip()
    나머지 = 나머지.replace("$", "").strip()
    if not 시 or not 나머지:
        return None
    if "@" in 나머지:                                    # 열 ID@번호 — 기간 열 설계가 표기를 정하면 여기를 맞춘다
        열ID, 번 = 나머지.rsplit("@", 1)
        return (시, 열ID.strip(), int(번)) if 열ID.strip() and 번.strip().isdigit() else None
    if 나머지.isdigit():
        return (시, None, int(나머지))
    풀 = 칸풀기(나머지)
    return (시, 풀[0], 풀[1]) if 풀 else None


