def 산업βU값(산업, 사전지역=None):
    """`산업베타.대조값` 결과 → (산업 βU(현금보정), 지역, 줄) — 대상 지역 줄이 먼저, 없으면 GLOBAL. 없으면 (None, None, None).
    1.1.4 — 사전지역(설정 「베타축소.사전지역」 · 다시 셈 `--사전지역`)을 주면 그 지역 줄(GLOBAL · EM · US · 그 밖 다모다란 지역)이 먼저 —
    본선이 판단으로 고른 업종 줄과 축소의 사전값을 맞춘다(국내 · 신흥시장 대상이 늘 대상 지역 줄을 사전값으로 받던 자리)."""
    if not 산업 or not 산업.get("산업"):
        return None, None, None
    지역 = (산업.get("지역") or "GLOBAL").upper()
    고른 = ("%s" % (사전지역 or "")).strip().upper()
    if 고른 in ("", "대상지역먼저", "자동"):
        고른 = None
    for 곳 in dict.fromkeys(([고른] if 고른 else []) + [지역, "GLOBAL"]):
        for x in 산업["산업"]:
            v = x.get("βU현금보정")
            if (x.get("지역") or "").upper() == 곳 and isinstance(v, (int, float)) and v > 0:
                return float(v), 곳, 산업.get("줄")
    return None, None, 산업.get("줄")


