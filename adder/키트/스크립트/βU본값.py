def Ke(β, W):
    """엔진 3번 WACC 구간 값(`R["WACC"]["예측기간"]` — Rf · ERP · 현금비중 · 한계세율 · DE · 부채베타 · 규모프리미엄)으로 βU = β 일 때의 자기자본비용.
    엔진 `wacc계산` 과 같은 식(하마다 · 부채베타 일반형)."""
    if not isinstance(W, dict) or β is None:
        return None
    rf, mrp, t, de = (W.get(k) for k in ("Rf", "ERP", "한계세율", "DE"))
    if None in (rf, mrp, t, de):
        return None
    c = W.get("현금비중") or 0.0
    bu = β / (1 - c) if c else β
    bd = W.get("부채베타")
    bl = bu * (1 + (1 - t) * de) if bd is None else bu + (bu - bd) * (1 - t) * de
    return rf + bl * mrp + (W.get("규모프리미엄") or 0.0)


def 서열하한(β, W, 문턱=0.01):
    """1.1.4 — 축소 결과(또는 채택 βU) β 의 자기자본비용이 세전 타인자본비용 + 문턱(자체검사 ⑲-⑦ 과 같은 1%p · 설정)보다 낮으면 경보와
    문턱까지 올린 βU. 정밀도 가중은 회귀가 잡음이 아니라 치우침(지수 쏠림 · 창 끝 급락)일 때 그 치우침을 넘긴다 — 서열이 그 신호다.
    → {"βU", "Ke", "Kd", "차", "문턱", "경보", "하한βU", "올린값", "식"} (셈할 수 없으면 None)."""
    ke = Ke(β, W)
    kd = (W or {}).get("Kd")
    if ke is None or kd is None:
        return None
    rf, mrp, t, de = W["Rf"], W["ERP"], W["한계세율"], W["DE"]
    c = W.get("현금비중") or 0.0
    bd = W.get("부채베타")
    목 = kd + 문턱
    if not mrp:
        return None
    bl = (목 - rf - (W.get("규모프리미엄") or 0.0)) / mrp
    bu = bl / (1 + (1 - t) * de) if bd is None else (bl + bd * (1 - t) * de) / (1 + (1 - t) * de)
    하 = bu * (1 - c) if c else bu
    경 = ke < 목 - 1e-12
    return {"βU": β, "Ke": ke, "Kd": kd, "차": ke - kd, "문턱": 문턱, "경보": 경, "하한βU": 하, "올린값": max(β, 하) if 경 else β,
            "식": "Ke(βU) ≥ 세전 Kd + 문턱 — 하한 βU = (Kd + 문턱 − Rf − 규모프리미엄) ÷ MRP 를 리레버 식으로 되돌린 값"}


def 창이동폭(T판, F판, 키="βU_본"):
    """1.1.4 — 같은 표본을 두 창 끝으로 셈한 두 βU 산출(T 창 · F 창 또는 끝을 옮긴 창) → {"동종 중앙값": |차|, "대상 자체": |차|, "근거", "짝수"}.
    동종은 두 판 모두에 본값으로 든 회사(종목코드 · 티커)만 짝지어 중앙값을 견준다. 대상은 `본값.대상자체.βU_본`."""
    def 표본(d):
        낸 = {}
        for z in (d or {}).get("표") or []:
            if not isinstance(z, dict) or z.get("본값제외") or not isinstance(z.get(키), (int, float)):
                continue
            if "(대상)" in ("%s" % (z.get("회사명") or z.get("티커") or "")):
                continue
            k = ("%s" % (z.get("종목코드") or z.get("티커") or "")).strip()
            if k:
                낸[k] = z[키]
        return 낸
    a, b = 표본(T판), 표본(F판)
    짝 = sorted(set(a) & set(b))
    낸 = {"짝수": len(짝)}
    근 = []

    def 통계(d):                                          # 축소가 쓰는 동종 통계(그 판의 축소 블록 · 없으면 세 겹 ②)
        bv = (d or {}).get("본값") or {}
        v = ((bv.get("축소") or {}).get("회귀동종") or {}).get("값")
        return v if isinstance(v, (int, float)) else (bv.get("세겹") or {}).get("전체중앙값")
    st, sf = 통계(T판), 통계(F판)
    if isinstance(st, (int, float)) and isinstance(sf, (int, float)):
        낸["동종 중앙값"] = abs(st - sf)
        근.append("동종 중앙값(축소가 쓰는 통계) %.3f(이 창) · %.3f(비교 창)" % (st, sf))
    if len(짝) >= 기본값최소표본:
        mt, mf = statistics.median(a[k] for k in 짝), statistics.median(b[k] for k in 짝)
        낸["같은표본"] = abs(mt - mf)
        if "동종 중앙값" not in 낸:
            낸["동종 중앙값"] = abs(mt - mf)
        근.append("두 판에 함께 든 %d곳의 중앙값 %.3f(이 창) · %.3f(비교 창)" % (len(짝), mt, mf))
    ta = (((T판 or {}).get("본값") or {}).get("대상자체") or {}).get("βU_본")
    fa = (((F판 or {}).get("본값") or {}).get("대상자체") or {}).get("βU_본")
    if isinstance(ta, (int, float)) and isinstance(fa, (int, float)):
        낸["대상 자체"] = abs(ta - fa)
        근.append("대상 자체 %.3f(이 창) · %.3f(비교 창)" % (ta, fa))
    elif isinstance(ta, (int, float)) or isinstance(fa, (int, float)):   # 1.1.8 — 한쪽 판에만 대상 자체가 있으면 조용히 건너뛰지 않는다
        낸["대상빠짐"] = "비교 창" if isinstance(ta, (int, float)) else "이 창"
        근.append("**대상 자체가 %s 판에 없어 대상 창 이동 폭을 재지 못했다 — 그 판을 지금 키트로 다시 셈한다(대상 자체 회귀가 드는 판)**" % 낸["대상빠짐"])
    낸["근거"] = " · ".join(근)
    return 낸


def 주봉회귀(대상주봉, 지수주봉, 끝, 주수=260):
    """주봉 캐시([[날짜, 종가]] 또는 {날짜: 종가})의 로그 수익률 OLS — 창 끝(YYYYMMDD) 이하 마지막 주수+1 주. → {"βL", "R2", "표본주", "창"} 또는 None."""
    y0, x0 = dict(대상주봉 or {}), dict(지수주봉 or {})
    끝 = ("%s" % 끝).replace("-", "")[:8]
    날 = sorted(d for d in set(y0) & set(x0) if ("%s" % d).replace("-", "")[:8] <= 끝)[-(주수 + 1):]
    쌍 = [(math.log(x0[날[i]] / x0[날[i - 1]]), math.log(y0[날[i]] / y0[날[i - 1]])) for i in range(1, len(날))
         if y0[날[i]] and y0[날[i - 1]] and x0[날[i]] and x0[날[i - 1]]]
    if len(쌍) < 30:
        return None
    n = len(쌍)
    mx, my = sum(a for a, _b in 쌍) / n, sum(b for _a, b in 쌍) / n
    sxx = sum((a - mx) ** 2 for a, _b in 쌍)
    sxy = sum((a - mx) * (b - my) for a, b in 쌍)
    syy = sum((b - my) ** 2 for _a, b in 쌍)
    if not sxx or not syy:
        return None
    return {"βL": sxy / sxx, "R2": sxy * sxy / (sxx * syy), "표본주": n, "창": [날[0], 날[-1]]}


