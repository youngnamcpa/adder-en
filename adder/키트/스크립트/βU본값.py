def 세방식(행들, 세율=None, 키="βU", 비중키=None):
    """(a) 평균βL ÷ [1+(1−평균 t)·평균DE] · (b) 중앙값 · (c) 평균 — 행마다 `세율` 이 있으면 그 평균(회사별 세율)."""
    ok = [z for z in 행들 if z.get(키) is not None]
