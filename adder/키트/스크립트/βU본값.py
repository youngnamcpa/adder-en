def _중앙값표준오차(행들, 구간95=None, 키="βU_본"):
    """동종 중앙값의 표준오차 — 부트스트랩 95% 구간이 있으면 (상 − 하) ÷ 3.92, 없으면 1.2533 × 표본 표준편차 ÷ √n(n ≥ 2). → (값, 근거)."""
    if isinstance(구간95, dict) and isinstance(구간95.get("하"), (int, float)) and isinstance(구간95.get("상"), (int, float)) and 구간95["상"] > 구간95["하"]:
        return (구간95["상"] - 구간95["하"]) / 3.92, "부트스트랩 95%% 구간 %.3f ~ %.3f ÷ 3.92" % (구간95["하"], 구간95["상"])
    v = [z[키] for z in 행들 or [] if not z.get("본값제외") and isinstance(z.get(키), (int, float))]
    if len(v) >= 2:
        return 1.2533 * statistics.stdev(v) / math.sqrt(len(v)), "1.2533 × 표본 표준편차 ÷ √%d(구간 없음)" % len(v)
    return None, "동종 본값 표본 %d곳 — 표준오차를 못 낸다" % len(v)


def 대상자체조정(대상, 조정):
    """1.1.4 — 대상 자체 회귀의 평균 회귀 조정(조정 베타 꼴). 조정 = {"꼴": "블룸", "가중": a, "닻": 1.0} 이면
    βL조정 = a × βL + (1 − a) × 닻, βU 는 같은 무차입 · 현금 보정(βU = A · βL + B 의 A = 1 ÷ ((1 + (1 − t)D/E)(1 − 현금비중)))으로 옮기고
    표준오차는 a 배. 꼴이 없거나 「없음」 이면 그대로. → (값, 표준오차 배수, 기록 dict 또는 None)."""
    if not isinstance(조정, dict) or (조정.get("꼴") or "없음") in ("없음", None):
        return 대상.get("βU_본"), 1.0, None
    a, 닻 = float(조정.get("가중", 0.67)), float(조정.get("닻", 1.0))
    βL, bu = 대상.get("βL"), 대상.get("βU_본")
    if not isinstance(βL, (int, float)) or not isinstance(bu, (int, float)) or not βL:
        return bu, 1.0, None
    βL조 = a * βL + (1 - a) * 닻
    de, t, c = 대상.get("DE_본"), 대상.get("세율"), 대상.get("현금비중_본") or 0.0
    if isinstance(de, (int, float)) and isinstance(t, (int, float)) and isinstance(c, (int, float)) and c < 1:
        A = 1.0 / ((1 + (1 - t) * de) * (1 - c))
        새 = bu + A * (βL조 - βL)
        식 = "βU + (βL조정 − βL) ÷ ((1 + (1 − t)D/E)(1 − 현금비중))"
    else:
        새 = bu * βL조 / βL
        식 = "βU × βL조정 ÷ βL(무차입 비율 그대로)"
    return 새, a, {"꼴": 조정.get("꼴"), "가중": a, "닻": 닻, "βL": βL, "βL조정": βL조, "원값": bu, "식": 식,
                  "근거": 조정.get("근거") or "단일 회사 회귀 베타의 평균 회귀(Blume 1971 · 1975) — 시장 실무의 조정 베타 꼴"}


