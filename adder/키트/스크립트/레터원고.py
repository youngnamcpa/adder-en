_표4번호식 = re.compile(r"(?<![\w:])((?:민:표4:줄|가:역셀):(\d+))(?=:)")


def 표4번호들(글, 줄들=None):
    """원고 글에서 표 Ⅳ 의 줄을 자리 번호로 부른 키 → [(키 머리, 말)]. 줄 차례는 판마다 바뀌어(축 선언 · 유형 기본 · 시나리오 축) 같은 번호에
    다른 가정의 값이 실렸다(1.1.9 실측 — 「영구기간 영업이익률 하나만 풀면」 에 매출 증가율 값). 줄들(`엔진.민감도.역산축목록`)을 주면 지금 그 번호의 줄을 알려 준다."""
    낸 = []
    for m in _표4번호식.finditer("%s" % (글 or "")):
        i = int(m.group(2))
        if 줄들 is not None and i < len(줄들):
            대 = "+".join("%s" % x for x in 줄들[i].get("대상") or [])
            말 = "지금 줄 %d 은 「%s」 — 가정 이름 키 「%s:대상:%s:…」 로 쓴다" % (i, 줄들[i].get("이름"), "민:표4" if m.group(1).startswith("민") else "가:역셀", 대)
        else:
            말 = "가정 이름 키 「민:표4:대상:<대상>:…」 · 「가:역셀:대상:<대상>:…」 로 쓴다(줄 차례는 판마다 바뀐다)"
        낸.append((m.group(0), 말))
    return 낸


def 조사관측(조사들):
    """조사 산출(B1 · B2 — 최상위 `업황_지표[]` · `과거_사이클[]` · `경쟁_위치[]` · `전방_매출[]` · `반대_대조[]` 와 비고)을 레터 원고의
    관측 칸 꼴로 옮긴다 → (관측 사전, 방향별 반대 대조 줄 {수요: [...], 공급: [...], 모름: [...]}). 여러 파일이면 이어 붙인다(병합은 스트림병합의 몫)."""
    관 = {"업황지표": [], "과거사이클": [], "경쟁": []}
    전, 전비고, 사비고 = [], None, None
    반 = {"수요": [], "공급": [], "모름": []}
    for j in 조사들 if isinstance(조사들, list) else [조사들]:
        if not isinstance(j, dict):
            continue
        관["업황지표"] += [x for x in j.get("업황_지표") or [] if isinstance(x, dict)]
        관["과거사이클"] += [x for x in j.get("과거_사이클") or [] if isinstance(x, dict)]
        관["경쟁"] += [x for x in j.get("경쟁_위치") or [] if isinstance(x, dict)]
        기 = [x.strip() for x in (j.get("경쟁_기준") or []) if isinstance(x, str) and x.strip()]
        if len(기) >= 3 and not 관.get("경쟁기준"):            # 1.1.8 — 조사가 고른 업종별 경쟁 기준(B1 「경쟁_기준[]」) — 종전에는 옮기지 않아 기본 넷으로 쟀다
            관["경쟁기준"] = 기
        전 += [x for x in j.get("전방_매출") or [] if isinstance(x, dict)]
        전비고 = 전비고 or j.get("전방_매출_비고")
        사비고 = 사비고 or j.get("과거_사이클_비고")
        for x in j.get("반대_대조") or []:
            if isinstance(x, dict):
                반[x.get("방향") if x.get("방향") in ("수요", "공급") else "모름"].append(x)
    if not 관["과거사이클"] and isinstance(사비고, str):
        관["과거사이클"] = {"해당없음": 사비고}
    if 전:
        관["전방매출"] = {"표": {"머리": ["전방", "비중", "기간"], "줄": [[x.get("전방"), x.get("비중"), x.get("기간")] for x in 전]},
                     "출처": " · ".join(sorted({"%s" % x.get("출처") for x in 전 if x.get("출처")}))}
    elif isinstance(전비고, str):
        관["전방매출"] = {"공시없음": 전비고}
    return 관, 반


def 조사대조(조사들, 부문=()):
    """A21 — 가정이 없는 조사 단계에서 조사 산출을 요건판 3 의 관측 칸으로 미리 대조한다 → (누락 목록, 알림 줄).
    업황 지표 · 과거 사이클 · 경쟁 · 전방 매출은 `대조` 와 같은 판정(문체 검수는 레터 원고의 몫이라 하지 않는다)이고,
    반대 쪽 대조는 방향을 레터가 고르므로(A24) 두 방향의 연도 수를 따로 센다 — 어느 쪽이든 연도 셋 이상이면 통과로 본다."""
    관, 반 = 조사관측(조사들)
    부 = list(부문 or [])
    R = [{"자리": "관측.업황지표", "절": "업황", "꼴": "업황지표", "최소": 업황지표최소, "부문": 부 if len(부) >= 2 else [], "무엇": "외부 관측 지표"},
         {"자리": "관측.과거사이클", "절": "업황", "꼴": "사이클", "무엇": "과거 사이클"},
         {"자리": "관측.경쟁", "절": "업황", "꼴": "경쟁표", "기준": list(경쟁기준), "추가물량": list(추가물량칸), "무엇": "경쟁 위치 표"},
         {"자리": "관측.전방매출", "절": "매출", "꼴": "전방", "무엇": "전방별 매출"}]
    누 = 대조({"관측": 관}, R, None)
    해 = {방: len({"%s" % x.get("연도") for x in 줄 if x.get("연도") not in (None, "") and not 자기출처인가(x.get("출처"))})
         for 방, 줄 in 반.items()}
    알 = ["반대 쪽 대조 재료 — 수요 대조 %d해 · 공급 상한 대조 %d해 · 방향 없음 %d해(레터가 방향을 고른다 · 조사는 두 방향을 다 모은다)"
         % (해["수요"], 해["공급"], 해["모름"])]
    if max(해.values()) < 반대대조최소줄:
        누.append({"자리": "관측.반대대조", "절": "매출", "무엇": "반대 쪽 대조 재료", "묶음": 묶음("관측.반대대조"),
                  "까닭": "어느 방향도 연도 %d해 이상의 외부 출처 줄이 없다(`반대_대조[]` — 방향 · 연도 · 지표 · 값 · 출처)" % 반대대조최소줄})
    return 누, 알


