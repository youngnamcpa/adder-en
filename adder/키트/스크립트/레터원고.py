def 요건표(요건들, 누락=None):
    """사람이 읽는 요건표(마크다운) — 원고를 쓰는 사람 · 갈래가 이것을 보고 쓴다."""
    빠 = {(x["자리"], x["무엇"].split(" — 「")[0]) for x in 누락 or []}
    L = ["| 자리 | 절 | 무엇을 쓰나 | 요소 | 상태 | 묶음 |", "|---|---|---|---|---|---|"]
    for r in 요건들:
        상 = "누락" if any(a == r["자리"] for a, _b in 빠) else "있음"
        if 상 == "있음" and r.get("선택") and r.get("상태") == "없음":
            상 = "없음(선택)"
        L.append("| `%s` | %s | %s | %s | %s | %s |" % (r["자리"], r.get("절") or "", r["무엇"], 블록요약(r) if r.get("꼴") == "블록글" else (" · ".join(r.get("요소") or []) or "—"), 상,
                                                    r.get("묶음") or 묶음(r["자리"])))
    경보들 = []                                               # 1.1.19 — 요건에 달린 경보(원형 이름 따위)는 표 아래 한 번씩
    for r in 요건들:
        if r.get("경보") and r["경보"] not in 경보들:
            경보들.append(r["경보"])
    if 경보들:
        L += [""] + ["경보 — %s" % x for x in 경보들]
    L += ["", "요소의 뜻", ""]
    L += ["- **%s** — %s" % (k, v) for k, v in 요소뜻.items()]
    if 누락:                                                  # 2026-10-25 R1 — 누락을 맡을 L 갈래 묶음(회차 구동이 이 줄을 보고 그 묶음만 다시 띄운다)
        셈 = {}
        for x in 누락:
            g = next((r.get("묶음") for r in 요건들 if r["자리"] == x["자리"] and r.get("묶음")), None) or 묶음(x["자리"])
            셈[g] = 셈.get(g, 0) + 1
        L += ["", "누락을 맡을 묶음 — %s" % " · ".join("%s %d건" % (g, 셈[g]) for g in sorted(셈))]
    return "\n".join(L)


