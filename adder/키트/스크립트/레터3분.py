def 같은값한번(이름들, 글들):
    """구분마다의 값 글 → 「범용 DRAM 91 · NAND 90」. 값이 모두 같으면 한 번만(v4d — 「범용 DRAM 187 · NAND 187」 → 「범용 DRAM · NAND 모두 187」).
    이름들이 비면 값만(같으면 「187」 하나, 다르면 「91 · 90」)."""
    글들 = list(글들)
    if len(글들) == 1:
        return 글들[0]
    if len(set(글들)) == 1:
        return ("%s 모두 %s" % (" · ".join(이름들), 글들[0])) if 이름들 else 글들[0]
    if not 이름들:
        return " · ".join(글들)
    return " · ".join("%s %s" % (n, g) for n, g in zip(이름들, 글들))


