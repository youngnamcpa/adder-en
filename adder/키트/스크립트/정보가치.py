def _수(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def 번호꼴(x):
    s = "%s" % x
    return s.lstrip("0") or "0" if s.isdigit() else s


# ═══════════════════════════════════════════════ 사전 대기

def 사전대기(출처글, 사전):
    """범위출처 글 → 사전 항목(처음 맞는 것). 못 맞으면 `기본`."""
    글 = 출처글 or ""
    for 항 in 사전["항목"]:
        for p in 항["패턴"]:
            if re.search(p, 글):
                return dict(항)
    return dict(사전["기본"], 유형="%s(%s)" % (사전["기본"]["유형"], 글[:40] or "출처 없음"))


def 판단칸출처(지도, 번호):
    """동인 지도의 판단 칸 `범위출처` · `근거강도` · 노드 — 번호로."""
    if not isinstance(지도, dict):
        return None
    n = 번호꼴(번호)
    for 노드 in 지도.get("노드") or []:
        if not isinstance(노드, dict):
            continue
        for 칸 in 노드.get("판단칸") or []:
            if isinstance(칸, dict) and 번호꼴(칸.get("번호")) == n:
                return {"노드": 노드.get("노드"), "범위출처": 칸.get("범위출처") or "", "근거강도": 칸.get("근거강도") or 노드.get("근거강도")}
    return None


def 축번호들(가정):
    """시나리오이야기.<쪽>.driver · 딸린행 의 번호 집합(없으면 빈 집합)."""
    낸 = set()
    for 쪽 in ((가정.get("시나리오이야기") or {}).values() if isinstance(가정.get("시나리오이야기"), dict) else []):
        if isinstance(쪽, dict):
            for k in ("driver", "딸린행"):
                for n in 쪽.get(k) or []:
                    낸.add(번호꼴(n))
    return 낸


# ═══════════════════════════════════════════════ 분석

def 분석(가정, 가정경로, 사전=None, 거친=None, 지도=None):
    사전 = 사전 or 사전읽기()
    T = 사전["문턱"]
    신호, 제안 = [], []

    def 신(종류, 대상글, 값, 문턱, 글, 등급="참고"):
        신호.append({"출처": "정보가치", "종류": 종류, "대상": 대상글, "값": 값, "문턱": 문턱, "글": 글, "등급": 등급})

    거친경로 = 지도경로 = None
    if 거친 is None:
        거친, 거친경로 = 파일찾기("거친바퀴.json", 가정경로)
    if 지도 is None:
        지도, 지도경로 = 파일찾기("동인지도.json", 가정경로)
    머리 = {"형식": "정보가치 1", "만든날": datetime.date.today().isoformat(), "설정": {"문턱": T, "사전항목수": len(사전["항목"])},
          "입력": {"가정": os.path.abspath(가정경로), "거친바퀴": 거친경로, "동인지도": 지도경로}}
    if not isinstance(거친, dict) or not isinstance(거친.get("표"), list):
        신("재료 없음", "거친바퀴.json", None, None, "가정 곁 _raw/거친바퀴.json 이 없거나 꼴이 아니다 — `거친바퀴.py 가정.json --json _raw/거친바퀴.json` 을 먼저")
        return dict(머리, 폴백="거친 바퀴 산출이 없다 — 정보가치를 내지 않는다(문항은 거친 바퀴의 순위 그대로)", 칸=[], 조사배분표=[], 축후보=[], 제안=제안, 신호=신호), ""
    머리["입력"]["거친바퀴_시나리오"] = 거친.get("시나리오")
    머리["입력"]["기준주당"] = 거친.get("기준주당")
    축 = 축번호들(가정)
    칸들 = []
    없는출처 = set()
    for 묶, 범위없음 in ((거친.get("표") or [], False), (거친.get("범위없음") or [], True)):
        for r in 묶:
            if not isinstance(r, dict) or not _수(r.get("최대변화")):
                continue
            대상 = r.get("대상") or []
            번호 = "%s" % 대상[0] if 대상 else ""
            출처 = r.get("범위출처") or r.get("폭출처") or ""
            근거강도 = r.get("근거강도")
            판 = 판단칸출처(지도, 번호) if (r.get("종류") == "판단칸" or 출처.startswith("판단 칸")) and 번호.isdigit() else None
            세부출처 = 판["범위출처"] if (판 and 판.get("범위출처")) else None
            항 = 사전대기(세부출처 or 출처, 사전)
            if 항["종류"] == "모름" and 세부출처 and 출처:      # 세부 출처가 사전 밖이면 일반 출처(「판단 칸(… · 근거 추정)」)로 다시(2026-10-23 밤)
                항2 = 사전대기(출처, 사전)
                if 항2["종류"] != "모름":
                    없는출처.add(세부출처[:60])
                    항 = dict(항2, 유형="%s · 세부 출처는 사전 밖" % 항2["유형"])
            if 항["종류"] == "모름":
                없는출처.add((세부출처 or 출처)[:60])
            축소율 = 항["예상_축소율"] if _수(항.get("예상_축소율")) else 1.0
            정 = r["최대변화"] * (1 - 축소율)
            칸 = {"대상": 대상, "번호": 번호 if 번호.isdigit() else None, "이름": r.get("이름"), "줄종류": r.get("종류"), "순위": r.get("순위"),
                 "문항": bool(r.get("문항") or r.get("범위문항")), "축아님": r.get("축아님"), "범위없음": 범위없음,
                 "최대변화": r["최대변화"], "범위": r.get("범위"), "지금": r.get("지금"), "위치": r.get("위치"),
                 "범위출처": 출처, "판단칸출처": 세부출처, "노드": (판 or {}).get("노드"), "근거강도": (판 or {}).get("근거강도") or 근거강도,
                 "유형": 항["유형"], "좁힐_갈래": 항["좁힐_갈래"], "예상_축소율": 축소율, "종류": 항["종류"], "비용_분": 항.get("비용_분"),
                 "정보가치": round(정, 6), "축에있음": (번호꼴(번호) in 축) if 번호.isdigit() else None}
            칸들.append(칸)
    칸들.sort(key=lambda k: -k["정보가치"])
    # 조사 배분표 — 줄어듦 · 섞임 · 모름(=조사로 확인할 자리) 가운데 정보가치 ≥ 최소
    배분 = [k for k in 칸들 if k["종류"] in ("줄어듦", "섞임", "모름") and k["정보가치"] >= T["정보가치_최소"] and not k.get("축아님")]
    for i, k in enumerate(배분, start=1):
        k["조사순위"] = i
    # 축 후보 — 줄어들지 않음 · 섞임 가운데 최대변화 ≥ 문턱(축 아님 빼고)
    축후보 = sorted([k for k in 칸들 if k["종류"] in ("줄어들지 않음", "섞임") and k["최대변화"] >= T["축후보_민감도"] and not k.get("축아님") and not k["범위없음"]],
                 key=lambda k: -k["최대변화"])
    # 신호
    for k in 배분:
        if k["문항"] and k["종류"] == "줄어듦" and k["예상_축소율"] <= T["줄어듦_축소율_상한"]:
            신("조사로 줄어드는 칸이 문항으로", "%s" % k["이름"], round(k["최대변화"], 4), "축소율 ≤ %.2f" % T["줄어듦_축소율_상한"],
              "%s 은 %s 로 폭을 %.0f%% 로 줄일 수 있다(범위출처 「%s」) — 묻기 전에 그 갈래를 먼저 돌리고, 좁힌 범위로 다시 재어 문항 여부를 정한다"
              % (k["이름"], k["좁힐_갈래"], k["예상_축소율"] * 100, (k["판단칸출처"] or k["범위출처"])[:60]), "경보")
    for k in 축후보:
        if k["종류"] == "줄어들지 않음" and k["축에있음"] is False:
            신("줄어들지 않는 칸이 축에 없음", "%s" % k["이름"], round(k["최대변화"], 4), "±%.0f%%" % (T["축후보_민감도"] * 100),
              "%s 은 조사해도 폭이 남는 칸(「%s」)인데 시나리오 이야기의 driver · 딸린행에 없다 — 축으로 담거나 고정한 까닭을 적는다" % (k["이름"], k["유형"]))
    범없 = [k for k in 칸들 if k["범위없음"] and k["최대변화"] >= T["축후보_민감도"] and not k.get("축아님")]
    if 범없:
        신("범위 없는 칸 — 범위 세우기가 먼저", " · ".join("%s" % k["이름"] for k in 범없)[:200], len(범없), "±%.0f%%" % (T["축후보_민감도"] * 100),
          "참고 폭으로도 주당 %.0f%% 를 넘는데 근거 범위가 없는 칸 %d개 — %s. 범위가 서면 정보가치 · 문항이 다시 정해진다"
          % (T["축후보_민감도"] * 100, len(범없), 범없[0]["좁힐_갈래"]))
    if 없는출처:
        신("사전에 없는 범위출처", " · ".join(sorted(없는출처))[:200], len(없는출처), None,
          "범위출처 %d개가 축소가능사전.json 의 패턴에 없다 — 축소율 1.0(안 줄어듦)으로 두었다. 사전에 패턴을 더한다(개정이력에 적는다)" % len(없는출처))
    # 제안 — 조사 배분 상위(근거범위 없음 — 거친 바퀴 통계범위가 건너뛴다)
    for k in 배분[:5]:
        if k["번호"]:
            제안.append({"자리": "A-%s(%s)" % (k["번호"], k["이름"]), "값": None, "근거범위": None, "딱지": "[계산 — 정보가치]",
                        "확신": "중" if k["종류"] == "줄어듦" else "약",
                        "글": "조사 배분 %d위 — 정보가치 %.1f%%(민감도 %.1f%% × 줄어드는 몫 %.0f%%) · 갈래 %s · 약 %s분"
                             % (k["조사순위"], k["정보가치"] * 100, k["최대변화"] * 100, (1 - k["예상_축소율"]) * 100, k["좁힐_갈래"], k["비용_분"])})
    낸 = dict(머리, 폴백=None, 칸=칸들, 조사배분표=배분, 축후보=축후보, 제안=제안, 신호=신호,
            요약={"칸수": len(칸들), "조사배분": len(배분), "축후보": len(축후보), "종류별": {s: sum(1 for k in 칸들 if k["종류"] == s) for s in ("줄어듦", "줄어들지 않음", "섞임", "모름")}})
    return 낸, ""


def 표찍기(낸):
    if 낸.get("폴백"):
        print("정보가치 — 폴백: %s" % 낸["폴백"])
