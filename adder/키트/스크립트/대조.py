    ap.add_argument("--자체검사만", action="store_true")
    ap.add_argument("--경보무시", action="store_true", help="자체 검사 경보만 있으면 rc에 반영하지 않는다")
    ap.add_argument("--지문없이", action="store_true",
                    help="배치 지문이 없는 옛 워크북도 대조한다 — 짝을 확인하지 못했으므로 「지문 미확인」 경보가 남고 rc=1 이다")
