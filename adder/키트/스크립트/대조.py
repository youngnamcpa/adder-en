    if len(a.인자) == 1:
        워크북, 가정경로 = None, a.인자[0]
    elif len(a.인자) == 2:
        워크북, 가정경로 = a.인자[0], a.인자[1]
    else:
        sys.stderr.write("인자 오류 — 워크북.xlsx 가정.json (또는 가정.json 하나)\n")
        sys.exit(입력오류)

    try:
        가정 = json.load(io.open(가정경로, "r", encoding="utf-8"))
    except Exception as e:
        sys.stderr.write("가정 JSON 오류 — %s 를 읽지 못했습니다: %s\n" % (가정경로, e))
        sys.exit(입력오류)

    # ── ⓪ 그 앞에 **도구가 본체와 같은 판인지** 본다 (2026-09-11 신설 — 현대차 실측)
    # 옛 도구로 돌면 대조는 **같은 옛 엔진끼리** 재므로 0곳이 나오고 자체검사도 제
    # 기준으로는 멀쩡하다 — **아무도 안 운다.** 여기서 한 번 알린다. 막지는 않는다:
    # 회차 전용 스크립트를 두는 것은 정상이고, 본체가 없는 자리에서도 돌아야 한다.
    도구말 = []
    try:
        import 도구대조 as _도구
        _본체 = _도구.본체찾기()
        if _본체 and os.path.abspath(os.path.dirname(os.path.dirname(
                os.path.abspath(_도구.__file__)))) != _본체:
            갈림, _전용, _빠짐 = _도구.대조(_본체)
            if 갈림:
                도구말 = ["⚠ **도구대조 — 회차 도구가 본체와 갈렸습니다(%d개): %s**"
                        % (len(갈림), " · ".join(f for f, _a, _b in 갈림)),
                        "   본체가 새것이면 다시 복사하고 전 과정을 다시 돌리십시오 —",
                        "   **검사만 바뀐 판이면 값은 그대로지만 계산부가 바뀐 판이면 값이 조용히 갈립니다.**",
                        "   자세히: `python 스크립트/도구대조.py`", ""]
                for x in 도구말:
                    print(x)
            _배치 = _도구.배치대조(_본체) if hasattr(_도구, "배치대조") else []
            if _배치:                                    # 스캐폴드·좌표 지도의 짝 — 스크립트가 같아도 이것이 갈리면 엉뚱한 칸에 붓는다
                _배치말 = ["⚠ **도구대조 — 회차의 스캐폴드·좌표 지도가 짝이 아니거나 본체와 갈렸습니다(%d건)**" % len(_배치)] \
                    + ["   " + x for x in _배치] + [""]
                for x in _배치말:
                    print(x)
                도구말 = 도구말 + _배치말
    except Exception:                                    # noqa: BLE001
        pass                                             # 도구대조가 없어도 대조는 돈다

    # ── ① 대조 본체 앞에 자체 검사가 먼저 돈다 (워크북이 없어도 돈다)
    # 자체검사는 스키마 v13 의 가정(기간 ID · 구조)과 엔진 결과(시트 키 · 줄 번호)를 그대로 읽는다(W7a) — 가정 파일을
    # 그대로 넘긴다. 실적 열 수는 가정의 기간이 정한다(실적 열 넷도 받는다). 옛 판(v12)은 자체검사가 이전 도구로 옮겨 보고, 옛꼴다리로 편 가정은 받지 않는다
    자체글, 자체오류, 자체경보 = _자체.자체검사(가정, _자체.라벨읽기(_내부한국어본(워크북)))
    print(자체글)
    조각 = (도구말 + [""] if 도구말 else []) + [자체글, ""]

    n = 0
    지문경보 = []
    if 워크북 is None or a.자체검사만:
        조각.append("(대조 본체는 돌리지 않았습니다 — 워크북 미지정 또는 --자체검사만)")
    else:
        try:
            본문, n = 대조(워크북, 가정경로, a.임계, a.상대, 지문없이=a.지문없이)
            지문경보 = 대조.지문경보
        except _좌표.좌표오류 as e:
            sys.stderr.write("좌표 오류 — %s\n" % e)
            sys.exit(입력오류)
        except _다리.다리오류 as e:
            sys.stderr.write("가정 JSON 오류 — %s\n" % e)
            sys.exit(입력오류)
        except _엔진.가정오류 as e:
            sys.stderr.write("%s\n" % e)
            sys.exit(입력오류)
        except (KeyError, TypeError, ValueError) as e:
            sys.stderr.write("가정 JSON 오류 — %s\n" % e)
            sys.exit(입력오류)
        print(본문)
        조각.append(본문)

    글 = "\n".join(조각)
    if a.출력:
        _경로, _말 = 산출물.안전쓰기(a.출력, 글)      # 회차 규약 — 남의 산출물을 안 덮는다
        for x in _말:
            print(x)
    if n or 자체오류 or 지문경보 or (자체경보 and not a.경보무시):      # 지문 경보는 --경보무시 로 안 넘어간다(짝이 깨진 것이다)
        sys.exit(발견)
    sys.exit(통과)


