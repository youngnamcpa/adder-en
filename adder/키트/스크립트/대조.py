def 대조대상(지, E):
    """좌표 지도의 「대조줄」과 엔진 결과 E → 무엇을 견주고 무엇을 견주지 않는가.

    {"열줄": [(시트 키, 번호, 시트 번호, 속성)] — 시간축의 열 줄(엔진 = {기간 ID: 값}),
     "값줄": [(시트 키, 번호, 시트 번호, 속성, [(열 ID, 엔진 값)])] — 한 값 줄 · 칸마다 값을 내는 줄(엔진 = 한 값 또는 {칸 별칭 · 열 ID: 값}),
     "미계산": [(시트 번호, 번호, 속성, 칸 또는 None)] — 엔진의 시트에 지은 계산 줄(· 그 줄의 수식 칸)인데 엔진 결과에 없다,
     "꼴다름": [(시트 번호, 번호, 속성, 글)] — 엔진이 낸 꼴(한 값)과 워크북의 칸 수가 안 맞는다,
     "안견줌줄": {행 ID: 까닭} — 줄 명세가 대조에서 뺀 줄, "안견줌시트": {시트 번호: (줄 수, 까닭)}, "엔진만": [(시트 키, 번호)]}
    지도에 「대조줄」이 없으면 좌표오류(「다시 지으십시오」)."""
    줄표 = 대조줄(지)
    if 줄표 is None:
        raise _좌표.좌표오류("좌표 지도(%s)에 「대조줄」이 없습니다 — 대조할 줄의 등록부를 싣기 전에 지은 스캐폴드입니다. 다시 지으십시오: %s"
                          % (지.경로 or "?", _좌표.짓는명령))
    시트of = 엔진시트()
    낸 = {"열줄": [], "값줄": [], "미계산": [], "꼴다름": [], "안견줌줄": dict(지.자료.get("견주지않는줄") or {}),
         "안견줌시트": {}, "엔진만": [], "종류밖": {}}
    for sid, 종류들 in (지.자료.get("대조밖수식줄") or {}).items():       # 종류가 계산 줄이 아닌 수식 줄 — 머리 · 점검 · 입력만 받는다
        for 종류, 번호들 in 종류들.items():
            if 종류 in 견주지않는종류:
                낸["종류밖"][종류] = 낸["종류밖"].get(종류, 0) + len(번호들)
            else:
                낸["미계산"] += [(지.시트번호(sid), "%d" % n, {"종류": 종류}, 종류밖) for n in 번호들]
    for 시, 줄들 in 줄표.items():
        키 = 시트of.get(시)
        if 키 is None:                                     # 엔진이 번호 줄로 내지 않는 시트 — 얼려 둔 번호만 견주지 않는 줄이다
            까닭, 얼린 = 견주지않는시트.get(시, ("엔진이 번호 줄로 내지 않는 시트", ""))
            얼린 = _번호들(얼린)
            if any(번 in 얼린 for 번 in 줄들):
                낸["안견줌시트"][시] = (sum(1 for 번 in 줄들 if 번 in 얼린), 까닭)
            낸["미계산"] += [(시, 번, 속, 얼림밖) for 번, 속 in 줄들.items() if 번 not in 얼린]
            continue
        엔 = E.get(키) or {}
        축시트 = _시간축시트(지, 시)
        for 번, 속 in 줄들.items():
            if 번 not in 엔:
                낸["미계산"].append((시, 번, 속, None))
                continue
            a = 엔[번]
            칸 = (속.get("칸") or {}) if 속.get("쓰임") else None      # 쓰임이 있는 줄 — {칸 별칭: 열 ID}(수식이 선 칸)
            수식열 = list(속.get("열") or ())
            if 칸 is None and 축시트 and isinstance(a, dict):
                낸["열줄"].append((키, 번, 시, 속))
            elif isinstance(a, dict):                               # 칸마다 값 — 쓰임 줄은 칸 별칭, 시간축이 아닌 시트의 열 줄은 열 ID
                낱 = []
                for 별칭, 열id in (칸 if 칸 is not None else {c: c for c in 수식열}).items():
                    if 별칭 in a:
                        낱.append((열id, a[별칭]))
                    else:
                        낸["미계산"].append((시, 번, 속, 별칭))
                낸["값줄"].append((키, 번, 시, 속, 낱))
            else:                                                   # 한 값 — 「값」 칸, 없으면 수식이 선 단 한 칸
                후보 = ([칸["값"]] if "값" in 칸 else list(칸.values())) if 칸 is not None else 수식열
                if len(후보) == 1:
                    낸["값줄"].append((키, 번, 시, 속, [(후보[0], a)]))
                elif not 후보 and a is None:
                    낸["값줄"].append((키, 번, 시, 속, []))          # 수식이 선 칸도 엔진 값도 없다 — 견줄 것이 없다
                else:
                    낸["꼴다름"].append((시, 번, 속, "엔진은 한 값(%s)을 내는데 워크북에 수식이 선 칸이 %d개입니다" % (a, len(후보))))
        for 번 in 엔:                                       # 엔진은 내는데 지은 계산 줄이 아닌 번호 — 참고로만 센다
            if str(번).isdigit() and 번 not in 줄들 and "%sR%03d" % (지.sid(시), int(번)) not in 낸["안견줌줄"]:
                낸["엔진만"].append((키, 번))
    return 낸


def 견줄칸(지, E):
    """대조가 읽을 칸 전부 → [(시트 번호, 칸 번호, 엔진 값)] — 시험이 흉내 워크북을 차릴 때 쓴다."""
    대상, 낸 = 대조대상(지, E), []
    for 키, 번, 시, 속 in 대상["열줄"]:
        낸 += [(시, (c, int(번)), E[키][번].get(c)) for c in 지.기간열()]
    for _키, 번, 시, _속, 낱 in 대상["값줄"]:
        낸 += [(시, (열id, int(번)), a) for 열id, a in 낱]
    return 낸


def _자리말(지, 시트번호, 칸번호):
    """「시트 이름!지금 칸」. 지금 칸이 번호와 다르면(옮긴 배치) 번호를 덧붙인다."""
    시트명, 칸 = 지.자리(시트번호, 칸번호)
    글 = _좌표.칸글(칸번호)
    if 칸 is None:
        raise _좌표.좌표오류("대조할 칸 %s번 %s 가 이 배치의 워크북에 없습니다(뺀 줄·열)" % (시트번호, 글))
    return 시트명, 칸, ("%s!%s" % (시트명, 칸)) + ("" if 칸 == 글 else " 〔번호 %s!%s〕" % (시트번호, 글))


def 재계산(워크북, 시나리오, 지, 지문없이=False):
    """formulas 패키지로 워크북을 재계산한다. 키 형식은 '[파일명.xlsx]시트명'!셀
    — 파일명은 원형 그대로, 시트명만 대문자화."""
    import formulas
    import openpyxl
    import tempfile
    import shutil

    임시 = tempfile.mkdtemp()
    사본 = os.path.join(임시, os.path.basename(워크북))
    shutil.copy(워크북, 사본)
    wb = openpyxl.load_workbook(사본)
    지.확인(wb, 필수=not 지문없이)            # 이 워크북이 그 좌표 지도의 배치가 맞는지 — 지문이 없으면 멈춘다
    시트명, 칸 = 지.자리(*적용시나리오칸)
    wb[시트명][칸] = 시나리오
    wb.save(사본)

    xl = formulas.ExcelModel().loads(사본).finish()
    풀 = xl.calculate()
    이름 = os.path.basename(사본)

    값 = {}
    for k, v in 풀.items():
        값[k.upper()] = v

    def 읽기(시트, 셀):
        키 = ("'[%s]%s'!%s" % (이름, 시트.upper(), 셀)).upper()
        v = 값.get(키)
        if v is None:
            return 값없음                # 재계산의 결과에 그 칸이 없다 — 빈칸(입력이 없는 칸)이거나 값을 내지 못한 수식 칸이다
        try:
            x = v.value[0, 0]
        except Exception:
            try:
                x = v.value
            except Exception:
                return None
        try:
            return float(x)
        except Exception:
            return x

    return 읽기, 임시


def _가름(x):
    """읽은 값을 가른다 → ("수", float) · ("빈칸", None) · ("글", 글). 엑셀 오류 값(#N/A · #REF! …)은 글이다."""
    if x is 값없음:
        return "없음", None             # `formulas` 의 결과에 그 칸이 없다 — 수식 칸이면 값을 내지 못한 것이고, 아니면 빈칸이다
    if x is None:
        return "빈칸", None
    if isinstance(x, bool):
        return "글", "%s" % x
    if isinstance(x, (int, float)):
        return ("글", "NaN") if x != x else ("수", float(x))
    글 = ("%s" % (x,)).strip()
    return ("빈칸", None) if 글 == "" else ("글", 글)


def _오류값인가(글):
    """엑셀 오류 값의 글인가 — #N/A · #REF! · #DIV/0! · #VALUE! · #NAME? · #NUM! · #NULL!"""
    return isinstance(글, str) and 글.startswith("#")


def _읽은말(종류, 값):
    if 종류 in ("빈칸", "없음"):
        return "빈칸" if 종류 == "빈칸" else "값 없음(재계산이 값을 내지 못했습니다)"
    return "오류 값 %s" % 값 if _오류값인가(값) else "글 「%s」" % ("%s" % 값)[:30]


def _문턱넘나(시트키, 번, 속, a, b, 임계, 상대):
    """두 수가 어긋났는가 — 금액 줄은 절대 `임계` 와 상대 `상대` 를 함께 넘을 때, 주당가치는 절대 1e-6, 그 밖은 상대(값이 1 보다 작으면 절대)."""
    차 = abs(float(a) - float(b))
    if (시트키, 번) in 주당가치줄:
        return 차 > 1e-6
    if 속.get("서식") in 금액서식:
        return 차 > 임계 and 차 > 상대 * max(abs(float(a)), abs(b), 1.0)
    return 차 > 상대 * max(abs(float(a)), abs(b), 1.0)


def _엔진말(a):
    return "값 없음" if a is None or isinstance(a, (str, bool)) else "%.10g" % a


def 견주기(E, 읽기, 지, 임계=1.0, 상대=1e-9):
    """한 시나리오의 엔진 결과 E 를 워크북에서 읽은 값과 견준다 → (줄, 어긋남 수, 수).

    E 는 `dcf엔진.계산()` 의 결과다(줄 = {기간 ID: 값} · 새 부호). `읽기(시트 이름, 칸 주소)` 는 워크북의 값을 준다
    (재계산이 낸다 — 시험에서는 흉내를 넣는다. `formulas` 의 결과에 그 칸이 없으면 `값없음` 을 준다).
    무엇을 견줄지는 좌표 지도의 「대조줄」이 정한다(`대조대상`).
    수 = {"전열": 견준 열 줄의 칸, "스칼라": 견준 한 값 칸, "건너뜀": 엔진이 값을 내지 않는 칸(워크북은 빈칸 · 글 · 0),
          "없음0": 그 가운데 워크북이 0 인 칸(수식이 빈 입력을 0 으로 낸 칸) · "없음0줄": 그 줄 {(시트 번호, 번호)},
          "줄": 대조한 줄, "열줄" · "값줄", "미계산": 엔진에 없는 번호 · 칸, "안견줌줄" · "안견줌시트줄": 견주지 않는 줄, "엔진만"}"""
    열이름 = 지.기간열()          # 축 순서의 열 ID(= 기간 ID)
    대상 = 대조대상(지, E)
    줄, 어긋남 = [], 0
    수 = {"전열": 0, "스칼라": 0, "건너뜀": 0, "없음0": 0, "없음0줄": set(), "줄": len(대상["열줄"]) + len(대상["값줄"]),
         "열줄": len(대상["열줄"]), "값줄": len(대상["값줄"]), "미계산": len(대상["미계산"]) + len(대상["꼴다름"]),
         "안견줌줄": len(대상["안견줌줄"]), "안견줌시트줄": sum(n for n, _까닭 in 대상["안견줌시트"].values()), "엔진만": len(대상["엔진만"]),
         "종류밖줄": sum(대상["종류밖"].values())}
    # ── 엔진 미계산 — 엔진의 시트에 지은 계산 줄인데 엔진 결과에 그 번호(· 그 칸)가 없다
    for 시, 번, 속, 칸 in 대상["미계산"]:
        어긋남 += 1
        if 칸 is 종류밖:
            줄.append("  어긋남 엔진 미계산 — %s번 %s: 종류가 「%s」 인 줄에 수식이 섰습니다. 산식 줄이면 종류를 계산 · 소계 · 합계 · 비율로 적고 "
                      "엔진이 그 번호를 냅니다(수식이 설 수 있는 그 밖의 종류는 %s 뿐입니다)" % (시, 번, 속.get("종류"), " · ".join(견주지않는종류)))
            continue
        if 칸 is 얼림밖:
            줄.append("  어긋남 엔진 미계산 — %s번 %s (%s): 엔진이 번호 줄로 내지 않는 시트에 새 계산 줄이 섰습니다(얼려 둔 「견주지 않는 줄」 목록 밖). "
                      "엔진이 그 시트를 번호 줄로 내게 하거나(`엔진.등록.결과시트키` — 그 시트의 계산 줄 전부를 낸다), 견줄 것이 없는 줄이면 "
                      "줄 명세에 \"대조\": false 를 답니다" % (시, 번, 속.get("종류")))
            continue
        줄.append("  어긋남 엔진 미계산 — %s번 %s%s (%s%s): 지은 계산 줄인데 엔진 결과에 그 %s 없습니다. 엔진의 시트 함수가 그 줄을 "
                  "내거나(줄묶음에 번호로 싣는다), 견줄 것이 없는 줄이면 줄 명세에 \"대조\": false 를 답니다"
                  % (시, 번, "" if 칸 is None else " 의 칸 「%s」" % 칸, 속.get("종류"),
                     " · 쓰임 %s" % 속["쓰임"] if 속.get("쓰임") else "", "번호가" if 칸 is None else "칸이"))
    for 시, 번, 속, 글 in 대상["꼴다름"]:
        어긋남 += 1
        줄.append("  어긋남 엔진 미계산 — %s번 %s (%s): %s. 엔진이 칸마다 값을 내야 합니다({칸 별칭 또는 열 ID: 값})" % (시, 번, 속.get("종류"), 글))

    def 한칸(시트키, 번, 시, 속, 열id, a, 열줄, 수식칸):
        """칸 하나를 견준다 → 어긋남이면 1. 「전열」 · 「스칼라」 · 「건너뜀」을 센다."""
        시트명, 칸, 말 = _자리말(지, 시, (열id, int(번)))
        말 = "%s (%s)" % (말, 열id) if 열줄 else "%s!%s 〔번호 %s!%s〕" % (시트명, 칸, 시, 번)      # 한 값 줄은 줄 번호로 부른다
        종류, b = _가름(읽기(시트명, 칸))
        if 종류 == "없음":                                       # 재계산의 결과에 그 칸이 없다
            if 수식칸:
                줄.append("  어긋남 %s  엔진=%s  워크북=값 없음 — 수식 칸인데 재계산이 값을 내지 못했습니다(순환 참조의 신호)" % (말, _엔진말(a)))
                return 1
            종류 = "빈칸"
        if 종류 == "글" and _오류값인가(b):                      # 워크북이 오류 값이다 — 엔진이 무엇을 냈든 어긋남
            줄.append("  어긋남 %s  엔진=%s  워크북=%s" % (말, _엔진말(a), _읽은말(종류, b)))
            return 1
        if a is None or isinstance(a, (str, bool)):              # 엔진이 값을 내지 않는 칸 — 워크북은 빈칸 · 글(빈 글 · n/a) · 0 이어야 한다
            if 종류 == "수" and abs(b) > 임계 * 1e-9:
                줄.append("  어긋남 %s  엔진=값 없음  워크북=%.10g — 엔진이 값을 내지 않는 칸에 워크북의 수가 있습니다" % (말, b))
                return 1
            수["건너뜀"] += 1
            if 종류 == "수":                                     # 엔진 값 없음 ↔ 워크북 0 — 어긋남은 아니지만 따로 세어 화면에 낸다
                수["없음0"] += 1
                수["없음0줄"].add((시, 번))
            return 0
        if 종류 != "수":                                         # 엔진은 수를 냈는데 워크북은 빈칸 · 글이다 — 한쪽만 수면 어긋남
            줄.append("  어긋남 %s  엔진=%.10g  워크북=%s — %s"
                      % (말, a, _읽은말(종류, b), "엔진이 수를 낸 칸에 워크북의 수가 없습니다" if 열줄 else "좌표 지도가 가리킨 칸에 수가 없습니다"))
            return 1
        수["전열" if 열줄 else "스칼라"] += 1
        if _문턱넘나(시트키, 번, 속, a, b, 임계, 상대):
            줄.append("  어긋남 %s  엔진=%.10f  워크북=%.10f  차=%.3g" % (말, a, b, abs(float(a) - b)))
            return 1
        return 0

    # ── 열 줄 — 축의 전 열(「대조열」을 적은 줄은 그 묶음에서 수식이 선 열만)
    for 시트키, 번, 시, 속 in 대상["열줄"]:
        엔 = E[시트키][번]
        if set(엔) != set(열이름):
            raise _좌표.좌표오류("기간 열이 맞지 않습니다 — 좌표 지도의 기간 열은 %d개(%s …)인데 엔진 %s[%s] 는 %d개(%s …)"
                              % (len(열이름), " · ".join(열이름[:3]), 시트키, 번, len(엔), " · ".join("%s" % k for k in list(엔)[:3])))
        수식열 = set(속.get("열") or ())
        for c in (열이름 if not 속.get("대조열") else [c for c in 열이름 if c in 수식열]):
            어긋남 += 한칸(시트키, 번, 시, 속, c, 엔[c], True, c in 수식열)
    # ── 한 값 줄 · 칸마다 값을 내는 줄
    for 시트키, 번, 시, 속, 낱 in 대상["값줄"]:
        for 열id, a in 낱:                                      # 낱이 비면(수식이 선 칸도 엔진 값도 없는 줄) 견줄 칸이 없다
            어긋남 += 한칸(시트키, 번, 시, 속, 열id, a, False, True)
    시트명, 칸, 말 = _자리말(지, *주당가치칸)
    종류, b = _가름(읽기(시트명, 칸))
    줄.append("  주당가치 — 엔진 %.10f / 워크북 %s"
              % (E["요약"]["주당가치"], b if 종류 == "수" else _읽은말(종류, b)))
    if 종류 != "수" and not any((시트키, 번) in 주당가치줄 for 시트키, 번, _시, _속, _낱 in 대상["값줄"]):
        어긋남 += 1                     # 주당가치 줄이 등록부에 없을 때만 따로 센다(있으면 위에서 셌다)
        줄.append("  어긋남 %s  워크북 주당가치 칸에 수가 없습니다(%s)" % (말, _읽은말(종류, b)))
    return 줄, 어긋남, 수


def 대상말(지, E):
    """대조할 줄과 견주지 않는 줄을 글로 — 화면의 머리에 낸다(조용히 빠지는 줄이 없게)."""
    대상 = 대조대상(지, E)
    시트 = ["%s번 %d줄" % (시, n) for 시, (n, _까닭) in sorted(대상["안견줌시트"].items(), key=lambda x: int(x[0]))]
    시트줄 = sum(n for n, _ in 대상["안견줌시트"].values())
    글 = ("대조 줄 %d(열 줄 %d · 한 값 줄 %d) · 엔진 미계산 %d · 견주지 않는 줄 %d — 줄 명세가 뺀 줄 %d(「대조」: false) + "
         "엔진이 번호 줄로 내지 않는 시트 %d줄(%s)%s"
         % (len(대상["열줄"]) + len(대상["값줄"]), len(대상["열줄"]), len(대상["값줄"]), len(대상["미계산"]) + len(대상["꼴다름"]),
            len(대상["안견줌줄"]) + 시트줄, len(대상["안견줌줄"]), 시트줄, " · ".join(시트),
            "" if not 대상["엔진만"] else " · 엔진만 내는 번호 %d(%s)" % (len(대상["엔진만"]), " · ".join("%s.%s" % x for x in 대상["엔진만"][:6]))))
    for 시, (n, 까닭) in sorted(대상["안견줌시트"].items(), key=lambda x: int(x[0])):
        글 += "\n  견주지 않는 시트 %s번(%d줄) — %s" % (시, n, 까닭)
    if 대상["종류밖"]:
        글 += "\n  종류가 계산 줄이 아닌 수식 줄 %d줄(견주지 않는다) — %s" % (
            sum(대상["종류밖"].values()), " · ".join("%s %d(%s)" % (k, n, 견주지않는종류[k]) for k, n in 대상["종류밖"].items()))
    return 글


def 지문견줌(워크북, 지, 지문없이=False):
    """워크북 · 좌표 지도 · (지도 곁의) 스캐폴드의 배치 지문을 견준다 → (줄, 경보 줄).

    워크북의 지문이 지도와 다르면 좌표오류(재계산 전에 멈춘다). 없으면 `지문없이` 일 때만 지나가고 경보를 남긴다.
    스캐폴드의 지문이 없거나 지도와 다르면 경보다 — 대조가 읽는 워크북은 맞지만 그 폴더에서 다시 부으면 틀린 짝이다."""
    경보 = []
    워 = _좌표.파일지문(워크북)
    지.파일확인(워크북, 필수=not 지문없이)
    조각 = ["워크북 %s" % (워 or "없음"), "좌표 지도 %s (%s)" % (지.지문(), 지.경로)]
    if 워 is None:
        경보.append("  ⚠ 지문 미확인 — 워크북에 배치 지문이 없어 좌표 지도와 맞는 짝인지 확인하지 못한 채 대조했습니다(--지문없이). "
                  "줄 자리가 다른 지도면 엉뚱한 칸을 읽습니다 — 아래 「견준 칸」 수와 빈칸 어긋남을 보십시오")
    틀 = os.path.join(os.path.dirname(지.경로), _좌표.스캐폴드이름) if 지.경로 else None
    if 틀 and os.path.isfile(틀) and os.path.abspath(틀) != os.path.abspath(워크북):
        스 = _좌표.파일지문(틀)
        조각.append("스캐폴드 %s" % (스 or "없음"))
        if 스 is None:
            경보.append("  ⚠ 스캐폴드 지문 없음 — 좌표 지도 곁의 스캐폴드(%s)에 배치 지문이 없습니다. 그 지도의 짝인지 알 수 없습니다"
                      "(붓기가 멈춥니다). 스캐폴드와 좌표 지도를 키트에서 함께 다시 복사하십시오" % 틀)
        elif 스 != 지.지문():
            경보.append("  ⚠ 스캐폴드 지문 다름 — 좌표 지도 곁의 스캐폴드(%s)는 다른 배치입니다(스캐폴드 %s / 지도 %s). "
                      "스캐폴드와 좌표 지도는 함께 복사해야 합니다" % (틀, 스, 지.지문()))
    return ["배치 지문 — " + " · ".join(조각)] + 경보, 경보


def 구조견줌(워크북, 지, 지문없이=False):
    """워크북의 구조가 좌표 지도와 맞는가 → (줄, 경보 줄). 지문은 꼬리표라 지문을 남긴 뒤에 줄을 끼운 워크북을 못 가린다.

    대조가 읽는 것은 값이 든 워크북이다 — **수식 칸**이 전부 지도의 「칸」 표 안에 있는지와 붓기가 안 바꾸는 줄 이름을 본다.
    지문으로 확인한 워크북의 구조가 다르면 좌표오류(재계산 전에 멈춘다). 지문 없는 워크북(`지문없이`)이면 경보로 남기고 돈다."""
    import openpyxl
    try:
        wb = openpyxl.load_workbook(워크북)
    except Exception as e:                               # noqa: BLE001
        raise _좌표.좌표오류("워크북을 못 열었습니다: %s (%s: %s)" % (워크북, type(e).__name__, e))
    지.워크북구조지문확인(wb)                               # 워크북에 남은 구조 지문 = 지도의 구조 지문(검증 ① D3) — 다르면 좌표오류
    걸림, 본 = 지.구조견줌(wb, 부은=True)
    말 = "구조 — 수식 칸 %s칸%s" % ("?" if 본["칸"] is None else "{:,}".format(본["칸"]),
                              "" if 본["줄이름"] is None else " · 줄 이름 {:,}줄".format(본["줄이름"]))
    if not 걸림:
        return [말 + ("이 전부 좌표 지도와 맞습니다" if 본["칸"] is not None else " (좌표 지도에 「칸」 표가 없어 자리를 못 견줬습니다)")], []
    if _좌표.워크북지문(wb) is not None:
        지.구조필수(wb, os.path.basename(워크북), 부은=True)      # 지문은 같은데 구조가 다르다 — 좌표오류
    경보 = ["  ⚠ 구조 다름 — %s. 줄 자리가 다른 지도면 엉뚱한 칸을 읽습니다(지문 없는 워크북이라 멈추지 않았습니다 — --지문없이)"
          % " · ".join(걸림)]
    return [말 + " — **좌표 지도와 다릅니다**"] + 경보, 경보


def _내부한국어본(워크북):
    """영문 시트(`1. Value_per_share`)로 변환된 납품본이면 곁의 `짓기/_internal_ko.xlsx` 를 돌려준다."""
    if not 워크북 or not os.path.isfile(워크북):
        return 워크북
    for _후 in (
        os.path.join(os.path.dirname(os.path.abspath(워크북)), "짓기", "_internal_ko.xlsx"),
        os.path.join(os.path.dirname(os.path.abspath(워크북)), "_internal_ko.xlsx"),
    ):
        if os.path.isfile(_후):
            return _후
    return 워크북


def 대조(워크북, 가정경로, 임계=1.0, 상대=1e-9, 지문없이=False):
    """→ (글, 어긋난 자리 수). 지문 경보(스캐폴드 지문 · 지문 미확인)는 `대조.지문경보` 에 남긴다."""
    워크북 = _내부한국어본(워크북)
    가정 = json.load(io.open(가정경로, "r", encoding="utf-8"))
    # 스키마 v13(기간 ID · 구조)으로 — 옛 판(v12)과 다리가 편 옛꼴가정만 다리가 그 자리에서 옮긴다(붓기가 부은 값과 같은 가정).
    # 기간 부분만 옮긴 v13(구조가 없는 파일) · v13 에서 없어진 키가 든 파일은 엔진의 검증이 가정오류로 멈춘다
    if _다리.옛판인가(가정) or (isinstance(가정, dict) and _다리.표식 in 가정):
        가정 = _다리.새꼴가정(가정)
    지 = _좌표.지도찾기(워크북)    # 워크북 곁(없으면 키트)의 좌표 지도 — 번호 → 지금 자리
    지문줄, 대조.지문경보 = 지문견줌(워크북, 지, 지문없이)      # 재계산(느리다) 전에 짝부터 본다
    지.기간열확인(가정)                                        # 이 가정의 기간으로 지은 워크북이 아니면 엉뚱한 열을 읽는다 — 좌표오류
    _엔진.검증하고죽기(가정, 경보출력=False)                    # 엔진이 못 읽는 가정이면 재계산 전에 멈춘다 — 가정오류
    구조지문글 = 지.구조지문확인(가정)                          # 이 가정의 구조로 지은 워크북이 아니면 줄 집합이 다르다 — 좌표오류
    구조줄, 구조경보 = 구조견줌(워크북, 지, 지문없이)           # 지문은 꼬리표다 — 지문 뒤에 줄을 끼운 워크북은 여기서 걸린다
    지문줄, 대조.지문경보 = 지문줄 + 구조줄, 대조.지문경보 + 구조경보
    지문줄.append("구조 지문 — %s" % ("가정 = 좌표 지도 %s" % 지.구조지문() if 구조지문글 is None else "⚠ " + 구조지문글))
    줄 = []
    총어긋남 = 0
    총수 = {"전열": 0, "스칼라": 0, "건너뜀": 0, "없음0": 0}
    없음0줄 = set()
    대상글 = None
    for 시 in 시나리오목록:
        E = _엔진.계산(가정, 시)
        대상글 = 대상글 or 대상말(지, E)                        # 무엇을 견주고 무엇을 견주지 않는가 — 구조가 정하니 시나리오마다 같다
        읽기, 임시 = 재계산(워크북, 시, 지, 지문없이)
        줄.append("")
        줄.append("════ 시나리오: %s ════" % 시)
        try:
            시줄, n, 수 = 견주기(E, 읽기, 지, 임계, 상대)
        finally:
            import shutil
            shutil.rmtree(임시, ignore_errors=True)
        줄.extend(시줄)
        총어긋남 += n
        for k in 총수:
            총수[k] += 수[k]
        없음0줄 |= 수["없음0줄"]
        대조.줄수 = {k: v for k, v in 수.items() if k not in 총수 and k != "없음0줄"}
    머리 = ("대조 결과 — 임계 %g (절대) · %g (상대). 어긋난 자리 %d곳 · 견준 칸 %d(전 열 %d · 스칼라 %d) · "
          "건너뛴 칸 %d(엔진이 값을 내지 않는 칸 — 워크북은 빈칸 · 글 %d칸 · 0 %d칸)"
          % (임계, 상대, 총어긋남, 총수["전열"] + 총수["스칼라"], 총수["전열"], 총수["스칼라"], 총수["건너뜀"],
             총수["건너뜀"] - 총수["없음0"], 총수["없음0"]))
    if 없음0줄:                          # 엔진 값 없음 ↔ 워크북 0 — 수식이 빈 입력 · 선언하지 않은 자리를 0 으로 낸 칸이다(어긋남이 아니다). 줄을 낸다
        시트별 = {}
        for 시, 번 in 없음0줄:
            시트별.setdefault(시, []).append(int(번))
        대상글 = (대상글 or "") + "\n  엔진 값 없음 · 워크북 0 인 줄(%d줄 — 견주지 않는 칸) — %s" % (
            len(없음0줄), " / ".join("%s번 %s" % (시, " · ".join("%d" % n for n in sorted(ns))) for 시, ns in sorted(시트별.items(), key=lambda x: int(x[0]))))
    return 머리 + "\n" + (대상글 or "") + "\n" + "\n".join(지문줄) + "\n" + "\n".join(줄), 총어긋남


