def _그림블록뺀(줄):
    """[(행, 글)] 에서 그림 블록(「<!-- 그림:…-->」 표지 · 굵은 그림 제목 줄 · 이어지는 숫자표 · 그 사이 빈 줄)을 뺀다 — 3분 레터의 글자 · 표 수 셈에서
    그림은 화면에서 그림으로 그려지는 재료다(레터 v27 7단계 — 첫 화면 범위 그림)."""
    낸, 안 = [], False
    for n, t in 줄:
        s = ("%s" % t).strip()
