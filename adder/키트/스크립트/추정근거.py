def 설정읽기(경로=None):
    """`추정근거설정.json`(없으면 기본값). 칸마다 기본값 위에 얹는다."""
    s = copy.deepcopy(기본설정)
    try:
        j = json.load(io.open(경로 or 설정파일, encoding="utf-8"))
    except (OSError, ValueError):
        return s
    for k, v in (j or {}).items():
        if k.startswith("_"):
            continue
        if isinstance(v, dict) and isinstance(s.get(k), dict):
            s[k].update(v)
        else:
            s[k] = v
    return s


