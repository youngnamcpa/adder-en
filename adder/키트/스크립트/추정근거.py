def _경로꼴(값들):
    """예측 열 값의 꼴 — 한 값 · 한 방향 · 꺾임(전환 열 하나) · 여러 번 꺾임. → (꼴, 전환 자리 i 또는 None)."""
    v = [x for x in 값들 if x is not None]
    if len(v) < 2 or all(abs(x - v[0]) <= 1e-12 for x in v):
        return "한 값", None
    차 = [b - a for a, b in zip(v, v[1:])]
