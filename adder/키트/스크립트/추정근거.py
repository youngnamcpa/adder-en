def 관측숫자대조(t, 번):
    """1.1.19 — 근거 첫 칸(관측 글)의 「연도 + 값(% · 일)」 이 그 회계연도 실적 열에서 같은 정의로 잰 값(`_실적값들`)과 다르면 알림 한 줄.
    관측 글은 원고가 장부 키로 부르지 않으면 레터에 서지 않지만, 낡은 숫자는 원고를 쓰는 사람을 헷갈리게 한다. 정의가 다른 자(`정의차`)는 보지 않는다.
    어림이다(값을 고치지 않는다). → [글]"""
    근 = t.근거(번)
    if not 근 or not 근["관측글"] or 정의차(t, 번):
        return []
    꼴 = t.가정꼴(번)
    단위 = "일" if int(번) in (178, 182, 186) else ("%" if 꼴[:1] == "퍼" else None)
    if not 단위:
        return []
    값 = dict(_실적값들(t, 번))
    열 = {("%s" % (t.속성.get(c, {}).get("회계연도") or "")): c for c in 값}
    낸 = []
    for m in _관측값틀.finditer(근["관측글"]):
        c = 열.get(m.group(1))
        if not c or m.group(3) != 단위:
            continue
        try:
            적은 = float(m.group(2).replace("−", "-")) / (100 if 단위 == "%" else 1)
        except ValueError:
            continue
        v = 값[c]
        if abs(v - 적은) > (0.0051 if 단위 == "%" else 0.51):
            낸.append("근거.%s 첫 칸(관측) 「%s」 — 같은 정의의 실적 %s" % (번, m.group(0).strip(), ("%.1f%%" % (v * 100)) if 단위 == "%" else ("%.1f일" % v)))
    return 낸


