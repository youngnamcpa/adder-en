def 축배선적기(곳, 쌍들, 국면="B1"):
    """`--배선 "이름=034"` — 축배선 파일에 이름으로 갈아 끼운다(다른 축은 그대로). 국면은 이름이 합본의 `축추가[]` 에 있으면 B2."""
    import datetime
    j = json.load(io.open(곳, "r", encoding="utf-8")) if os.path.exists(곳) else {}
    j.setdefault("소유", "본선(3-1 배선) — 병합이 다시 돌아도 지워지지 않는다. 합본에 가정번호를 쓰지 않는다")
    축 = [x for x in (j.get("축") or []) if isinstance(x, dict)]
    for 쌍 in 쌍들:
        if "=" not in 쌍:
            raise ValueError("--배선 은 「축 이름=가정번호」 꼴입니다: %s" % 쌍)
        이름, 번 = [x.strip() for x in 쌍.rsplit("=", 1)]
        축 = [x for x in 축 if ("%s" % x.get("이름")).strip() != 이름]
        축.append({"이름": 이름, "가정번호": 번, "국면": 국면.get(이름, "B1") if isinstance(국면, dict) else 국면,
                  "배선일": datetime.date.today().isoformat()})
    j["축"] = 축
    os.makedirs(os.path.dirname(os.path.abspath(곳)), exist_ok=True)
    with io.open(곳, "w", encoding="utf-8", newline="\n") as f:
        json.dump(j, f, ensure_ascii=False, indent=1)
        f.write("\n")
    return j


