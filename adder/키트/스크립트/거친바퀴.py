def 대안값(가정, 대안들, 시나리오="기준"):
    """멈춤 선택지 값 — 대안 가정마다 같은 엔진으로 주당가치 · 영구기간 영업이익률(결과) · 예측기간 WACC 를 낸다."""
    out = []
    for 이름, 대안 in [("기준 가정", 가정)] + list(대안들):
        try:
            오류, _ = E.검증(대안)
            if 오류:
                raise E.가정오류(" / ".join(오류[:3]))
            R = _조용히(계.계산, 대안, 시나리오)
            out.append({"이름": 이름, "주당": R["요약"]["주당가치"], "영구기간영업이익률": R["요약"].get("영구기간영업이익률"),
                        "WACC": R["요약"].get("예측기간WACC")})
        except Exception as e:                                    # noqa: BLE001
            out.append({"이름": 이름, "오류": str(e)})
    return {"시나리오": 시나리오, "대안": out}


