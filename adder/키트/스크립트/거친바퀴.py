def _원(x):
    return "-" if x is None else "{:,.0f}".format(x)


def _퍼(x, 부호=False):
    return "-" if x is None else (("%+.1f%%" if 부호 else "%.1f%%") % (x * 100))


def _폭말(r):
    if r["방식"] == "배율":
        return "×(1%+.0f%%/1%+.0f%%)" % (r["하오프셋"] * 100, r["상오프셋"] * 100)
    if r.get("비율"):
        return "%+.2f%%p/%+.2f%%p" % (r["하오프셋"] * 100, r["상오프셋"] * 100)
    return "%+g/%+g" % (r["하오프셋"], r["상오프셋"])


