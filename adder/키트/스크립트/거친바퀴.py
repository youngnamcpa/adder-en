def 시나리오값민감도(가정, 시나리오="기준", 문턱=0.05):
    """S9-14 · 집대성 4단계 — 「한 묶음씩 그 줄의 비관 · 낙관 값으로 뒤집어」 주당가치가 몇 % 움직이나(나머지는 기준 그대로).
    묶음은 이야기 묶음(엔진 `민감도.이야기묶음` — 매출 물량 · 단가 · 능력 · 원가 · 인건비 · 투자 · 운전자본 · 법인세 · 영구 · 할인).
    ±문턱 안 묶음은 「축에서 뺀다」. → [{묶음, 줄, 비관변화, 낙관변화, 최대, 판정}]"""
    가정 = copy.deepcopy(가정)
    R0 = _조용히(계.계산, 가정, 시나리오)
    기준주당 = R0["요약"]["주당가치"]
    묶음들 = 민.시나리오갈림(가정)
    낸 = []
    for 묶, 줄들 in sorted(묶음들.items()):
        한 = {"묶음": 묶, "줄": sorted(줄들, key=lambda x: (len(x), x))}
        for 쪽 in ("비관", "낙관"):
            try:
                a = 민.시나리오값덮기(가정, 줄들, 쪽, 시나리오)
                v = _조용히(계.계산, a, 시나리오)["요약"]["주당가치"]
                한[쪽 + "주당"] = v
                한[쪽 + "변화"] = (v / 기준주당 - 1) if 기준주당 else None
            except Exception as e:                                # noqa: BLE001
                한[쪽 + "변화"] = None
                한.setdefault("비고", []).append("%s 계산 불가: %s" % (쪽, ("%s" % e)[:80]))
