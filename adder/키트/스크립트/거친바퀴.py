def _참고정의역(첫, h, 하, 상, 지금, 가정, 시나리오, 행):
    """범위 없음 줄의 참고 폭 — 율 줄 정의역을 지킨다(상한 1 · 가동률 × 수율 ≤ 1). → (하, 상) 오프셋(손잡이 방식대로)."""
    if not ("%s" % 첫).isdigit() or not _숫자(지금) or 지금 == 0:
        return 하, 상
    방식 = h.get("방식", "가산")
    끝 = (lambda x: 지금 * (1 + x)) if 방식 == "배율" else (lambda x: 지금 + x)
    lo, hi = sorted((끝(하), 끝(상)))
    lo2, hi2, 비고 = _정의역("%s" % 첫, 가정칸척도(첫), lo, hi, 지금, 가정, 시나리오)
    if (lo2, hi2) == (lo, hi):
        return 하, 상
    행["비고"] += 비고
    되 = (lambda v: v / 지금 - 1) if 방식 == "배율" else (lambda v: v - 지금)
    return 되(lo2), 되(hi2)


def _변화(행, 기준주당):
    for 라벨 in ("하", "상"):
        v = 행.get(라벨 + "주당")
        행[라벨] = v
        행[라벨 + "변화"] = ((v - 기준주당) / abs(기준주당)) if (_숫자(v) and 기준주당) else None
    변 = [abs(행[k]) for k in ("하변화", "상변화") if 행.get(k) is not None]
    행["최대변화"] = max(변) if 변 else None
    if 행["최대변화"] == 0 and not 행["비고"]:
        행["비고"].append("주당 불변 — 이 판의 계산이 안 읽는 줄(그 줄을 쓰지 않는 구조) · 다른 가정이 막고 있는지 본다")
    # 유리쪽 위치 — 값을 올리는 쪽 끝을 1 로(0 = 가장 보수적 끝)
    p = 행.get("위치")
    if p is not None and _숫자(행.get("하주당")) and _숫자(행.get("상주당")) and 행["하주당"] != 행["상주당"]:
        행["유리쪽위치"] = p if 행["상주당"] > 행["하주당"] else 1 - p


def 쏠림판정(표, 끝=0.25, 최소=3):
    """순위 줄(축 아님 · 순위 밖 빼고) 셋 이상이 모두 같은 쪽 끝(유리쪽위치 ≥ 75% 또는 ≤ 25%)이면 습관 신호."""
    p = [r.get("유리쪽위치") for r in 표 if r.get("유리쪽위치") is not None and not r.get("축아님") and not r.get("순위밖")]
    if len(p) < 최소:
        return {"신호": None, "수": len(p), "글": "위치를 잴 줄이 %d개 — 쏠림을 판정하지 않는다(셋 이상)" % len(p)}
    if all(x >= 1 - 끝 for x in p):
        return {"신호": "낙관 쪽 끝", "수": len(p), "글": "근거 범위가 있는 줄 %d개가 모두 값을 올리는 쪽 끝(상위 25%%)에 있다 — 판단이 아니라 습관이다" % len(p)}
    if all(x <= 끝 for x in p):
        return {"신호": "보수 쪽 끝", "수": len(p), "글": "근거 범위가 있는 줄 %d개가 모두 값을 낮추는 쪽 끝(하위 25%%)에 있다 — 판단이 아니라 습관이다" % len(p)}
    return {"신호": None, "수": len(p), "글": "쏠림 없음 — %d줄의 위치가 갈린다" % len(p)}


