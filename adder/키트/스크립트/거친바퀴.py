def _이름(대상, 줄이름):
    """손잡이 대상 → 화면 이름. 번호면 「A-030 줄 이름」."""
    낸 = []
    for x in 대상:
        x = "%s" % x
        if x.isdigit():
            n = 줄이름.get(int(x))
            낸.append(("A-%03d %s" % (int(x), n)) if n else "A-%03d" % int(x))
        else:
            낸.append(x)
    return " + ".join(낸)


