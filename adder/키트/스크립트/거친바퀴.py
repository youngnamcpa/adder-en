def 기본후보(가정, 시나리오="기준", 폭=0.10, 가산폭=0.01, 종류=None):
    """값이 든 열별 가정 줄 전부(배분율 빼고) + 212 · 219(차 있으면) + 영구이익률 · WACC + 선언한 손잡이."""
    축 = []
    for 번호 in sorted((가정.get("가정") or {}).keys(), key=lambda x: int(x) if str(x).isdigit() else 9999):
        if 번호 in 기본제외 or not str(번호).isdigit():
            continue
        if any(v != 0 for v in _열값들(가정, 번호, 시나리오)):
            축.append(축읽기(번호, 가정, 시나리오, 폭, 가산폭, 종류))
    for 번호 in ("212", "219"):
        if _숫자(_시점값(가정, 번호, 시나리오)):
            축.append(축읽기(번호, 가정, 시나리오, 폭, 가산폭, 종류))
    # 물가연동 · 물량단위원가 원가 줄의 수준 — 기준 금액(7k5, 한 값)을 ±10%(S3-08). 수준 조정(7k3)은 7k5 와 곱이라 같은 손잡이다 —
    # 7k5 가 없을 때만 7k3 을 민다. 그 줄의 「정상 수준」 판단은 E 판단 칸(7k3 범위)이 판단칸 민감도로 따로 잰다
    for x in ((가정.get("구조") or {}).get("원가줄") or []):
        k = x.get("번호")
        if not isinstance(k, int) or x.get("옛식") == "예":
            continue
        if not ({x.get("산식"), x.get("보조산식")} & {"물가연동", "물량단위원가"}):
            continue
        for 번호 in ("7%d5" % k, "7%d3" % k):
            if _숫자(_시점값(가정, 번호, 시나리오)):
                if not any(list(a["손잡이"]["대상"]) == [번호] for a in 축):
                    축.append(축읽기("%s:배율" % 번호, 가정, 시나리오, 폭, 가산폭, 종류))
                break
    축.append(축읽기("영구이익률", 가정, 시나리오, 폭, 가산폭, 종류))
    축.append(축읽기("WACC", 가정, 시나리오, 폭, 가산폭, 종류))
    for h in ((가정.get("민감도") or {}).get("손잡이") or []):
        if isinstance(h, dict) and h.get("이름") and h.get("대상"):
            if not any(list(a["손잡이"]["대상"]) == ["%s" % x for x in h["대상"]] for a in 축):
                축.append(축읽기(h["이름"], 가정, 시나리오, 폭, 가산폭, 종류))
    return 축


