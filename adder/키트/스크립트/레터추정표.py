def 열정의(근거, 블, 접은=0):
    """표 아래 한 줄 — 열과 끝 칸의 뜻(합쇼체). 접은 줄이 있으면 그 뜻도."""
    E = 근거["열"]
    짧은 = [c for c in E["예측"] if (E.get("개월") or {}).get(c) not in (None, 12)]
    조각 = []
    if 블["열"] == "연도" and 짧은:
        조각.append("%s 열은 그 기간의 금액이고, 그 열의 증가율은 회계연도 전체의 전년 대비입니다" % " · ".join((E.get("이름") or {}).get(c, c) for c in 짧은))
    if 블["키"] == "브리지":
        조각.append("주주가치 대비는 그 줄이 주주가치에서 차지하는 몫입니다")
    else:
        조각.append("주당가치 폭은 그 줄의 가정만 비관 · 낙관 값(시나리오에서 같으면 기본 폭)으로 옮긴 주당가치 변화의 큰 쪽입니다")
    if 접은:
        조각.append("주당가치 폭이 %s 미만인 줄은 가정 값 없이 결과만 실었습니다" % 자리("상:%s" % 근거["문턱"]["한문단"], "퍼0"))
    return "열 정의 — %s." % ". ".join(조각)


# ══════════════════════════════════════════════════════════════════ 추정 흐름(모델 설계 장 머리)

def _무거운줄(블):
    줄들 = [z for z in 블["줄"] if (z.get("무게") or {}).get("값") is not None]
    if 줄들:
        return max(줄들, key=lambda z: z["무게"]["값"])
    return 블["줄"][0] if 블["줄"] else None


def _가정값글(근거, g):
    키 = g.get("키") or {}
    if g["종류"] == "WACC":
        return " · ".join("%s %s" % ({"예측": "예측기간", "영구": "영구기간"}[k], 자리(키[k], g["꼴"])) for k in ("예측", "영구") if 키.get(k))
    if g["종류"] in ("한 값", "대조 기준값"):
        return 자리(키["값"], g["꼴"]) if 키.get("값") else 없음
    E = 근거["열"]
    if g["종류"] == "규칙":
        k = (g.get("키") or {}).get("규칙")
        if not k:
            return 없음
        if "<열>" not in k:
            return 자리(k, g["꼴"])
        return " · ".join("%s %s" % ((E.get("이름") or {}).get(c, c), 자리(근.펴키(k, c), g["꼴"])) for c in (E["끝"], E["영구"]) if c)
    이름 = E.get("이름") or {}
    조 = []
    for 칸, 열 in (("첫", E["첫"]), ("전환", None), ("끝", E["끝"]), ("영구", E["영구"])):
        k = 키.get(칸)
        if not k:
            continue
        c = k.split(":")[-1]
        조.append("%s %s" % (이름.get(c, c), 자리(k, g["꼴"])))
    return " · ".join(조) or 없음


def _넘김글(근거, 블):
    결 = next((r for r in 블["결과"] if r.get("굵게")), 블["결과"][0] if 블["결과"] else None)
    if not 결:
        return 없음
    E = 근거["열"]
    이름 = E.get("이름") or {}
    k = 결.get("키꼴") or 결.get("식꼴")
    if 블["열"] == "구간":
        return "%s 예측기간 %s · 영구기간 %s" % (결["이름"], 자리(근.펴키(k, "예측값"), 결["꼴"]), 자리(근.펴키(k, "영구값"), 결["꼴"]))
    if 블["열"] == "한값":
        return "%s %s" % (결["이름"], 자리(k, 결["꼴"]))
    조 = ["%s %s" % (이름.get(c, c), 자리(근.펴키(k, c), 결["꼴"])) for c in (E["끝"], E["영구"]) if c]
    return "%s %s" % (결["이름"], " · ".join(조))


def _갈림글(블):
    갈 = sorted({g["번호"] for z in 블["줄"] for g in z["가정"] if g.get("갈리나") and g.get("번호") and g["종류"] in ("열별", "한 값")},
               key=lambda x: (len(x), x))
    if not 갈:
        return "같음"
    묶 = "+".join(갈)
    return "%s ~ %s" % (자리("가:홀로:비관:%s" % 묶, "주당"), 자리("가:홀로:낙관:%s" % 묶, "주당"))


def _대조글(블):
    조, 본 = [], set()
    for 대 in list(블["대조"]) + [x for z in 블["줄"] for x in z["대조"]]:
        if not 대.get("판정키") or 대["종류"] in 본:
            continue
        본.add(대["종류"])
        조.append("%s %s" % (대["종류"], 자리(대["판정키"], "글")))
    return " · ".join(조[:3]) or 없음


def _딱지글(블):
    수 = {}
    for z in 블["줄"]:
        for d in ((z.get("관측") or {}).get("딱지") or []):
            수[d] = 수.get(d, 0) + 1
    return " · ".join(sorted(수, key=lambda d: (-수[d], d))) or 없음


def 추정흐름표(근거):
    """모델 설계 장 머리의 「추정 흐름」 표 — 블록 열 줄 · 일곱 열(블록 · 무엇으로 셈했나 · 값을 정한 가정 · 근거의 종류 · 넘기는 값 ·
    시나리오에서 갈리나 · 대조)."""
    줄들 = []
    for 블 in 근거["블록"]:
        z = _무거운줄(블)
        if z is None and not 블["결과"]:
            continue
        if z is None:
            줄들.append(["**%s**" % 블["블록"], 없음, 없음, 없음, _넘김글(근거, 블), "같음", _대조글(블)])
            continue
        g = next((x for x in z["가정"] if x["종류"] != "규칙"), z["가정"][0])
        줄들.append(["**%s**" % 블["블록"], z["산식"]["말"], "%s %s" % (g["이름"], _가정값글(근거, g)), _딱지글(블), _넘김글(근거, 블),
                    _갈림글(블), _대조글(블)])
    머리 = ["블록", "무엇으로 셈했나", "값을 정한 가정", "근거의 종류", "넘기는 값", "시나리오에서 갈리나", "대조"]
    return (["**표. 추정 흐름 — 매출에서 주당가치까지**", ""] + _표(머리, 줄들) + [""] +
            ["열 정의 — 값을 정한 가정은 그 블록에서 주당가치 폭이 가장 큰 줄의 가정입니다. 시나리오에서 갈리나는 그 블록의 가정만 비관 · 낙관 값으로 옮긴 "
             "주당가치이고, 대조는 종류마다 그 블록의 판정입니다."])


