def 펴기(맥, 글):
    """자리표시를 레터 맥락의 장부에 적으며 편다 — {키|꼴} 은 `맥.수`, {식:[…]|꼴} 은 `맥.식`, {키|글} 은 `맥.엔진글`."""
    if isinstance(글, list):
        글 = "\n".join(글)

    def 바꿈(m):
        안, 꼴 = m.group(1).strip(), m.group(2).strip()
        if 안.startswith("식:"):
            return 맥.식(json.loads(안[2:]), 꼴)
        if 꼴 == "글":
            v = 맥.엔진글(안)
            return v or 없음
        return 맥.수(안, 꼴)
    return 자리표.sub(바꿈, 글)


def 모든표(근거, 원=None):
    """「추정 흐름」 표 + 블록마다 「가정과 결과」 표(마크다운 줄 목록) — 견본 · 시험용 묶음. 블록에 싣는 조립은 레터 조립 단계의 몫이다."""
    L = 추정흐름표(근거) + [""]
    for _이름, 키 in 근.블록차례:
        t = 가정결과표(근거, 키, 원)
        if t:
            L += t + [""]
    return L
