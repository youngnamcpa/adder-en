자리표 = re.compile(r"\{([^{}|]+)\|([^{}|]+)\}")
없음 = "—"


def 자리(키, 꼴):
    """장부 자리표시 한 칸 — 키(글) · 식(목록)."""
    if isinstance(키, list):
        return "{식:%s|%s}" % (json.dumps(키, ensure_ascii=False, separators=(",", ":")), 꼴)
    return "{%s|%s}" % (키, 꼴)


def _칸글(c):
    """표 칸의 글 — 자리표시 밖의 「|」 만 「·」 로 바꾼다(자리표시 안의 「|」 는 꼴을 가른다)."""
    조 = re.split(r"(\{[^{}]*\})", "%s" % c)
    return "".join(x if x.startswith("{") else x.replace("|", "·") for x in 조)


def _표(머리, 줄들):
    L = ["| " + " | ".join(머리) + " |", "|" + "---|" * len(머리)]
    for r in 줄들:
        L.append("| " + " | ".join(_칸글(c) for c in r) + " |")
    return L


def _열들(근거, 블록):
    """블록의 열 — [(열 ID, 머리 이름, 실적인가)]."""
    E = 근거["열"]
    이름 = E.get("이름") or {}
    if 블록["열"] == "구간":
        return [("예측값", "예측기간", False), ("영구값", "영구기간", False)]
    if 블록["열"] == "한값":
        return [("", "값", False)]
    실 = (E.get("실적열수") or {}).get(블록["키"]) or []
    return ([(c, 이름.get(c, c), True) for c in 실] + [(c, 이름.get(c, c), False) for c in E["예측"]]
            + ([(E["영구"], 이름.get(E["영구"], E["영구"]), False)] if E["영구"] else []))


def _값있나(원, 키):
    if 원 is None:
        return True
    import 레터 as L                                         # noqa: PLC0415
    try:
        v = L.식값(키, 원) if isinstance(키, list) else L.키풀기(키, 원)
    except Exception:                                        # noqa: BLE001
        return False
    return L._n(v) is not None if not isinstance(v, str) else bool(v)


def _칸(원, 꼴키, 열, 꼴, 실적):
    if not 꼴키:
        return 없음
    k = 근.펴키(꼴키, 열) if 열 else 꼴키
    if isinstance(k, str) and k.startswith("A:") and 실적:
        return 없음
    return 자리(k, 꼴) if _값있나(원, k) else 없음


def _가정칸(원, g, 열, 실적, 블록열, 첫열=None):
    if g["종류"] == "WACC":
        k = (g.get("키") or {}).get({"예측값": "예측", "영구값": "영구"}.get(열, ""))
        return 자리(k, g["꼴"]) if k and _값있나(원, k) else 없음
    if g["종류"] in ("한 값", "대조 기준값"):
        k = (g.get("키") or {}).get("값")
        if not k or 실적:
            return 없음
        if 열 and 첫열 and 열 != 첫열 and not (g["꼴"].startswith(("지수", "퍼", "배"))):
            return ""                                        # 기준 수준 · 연도 같은 한 값은 첫 예측 열에만(계수 · 율은 열마다 같은 값을 보인다)
        return 자리(k, g["꼴"]) if _값있나(원, k) else 없음
    if g["종류"] == "규칙":
        return _칸(원, g["키"]["규칙"], 열, g["꼴"], 실적 and False)
    꼴키 = g.get("표키꼴")
    if 실적 and 꼴키 and 꼴키.startswith("A:"):
        return 없음
    return _칸(원, 꼴키, 열, g["꼴"], 실적)


def _폭칸(줄):
    w = 줄.get("무게") or {}
    return 자리(w["식"], "퍼1") if w.get("식") else 없음


범위열 = "실적 범위"


def _범위대조(줄, 번):
    return next((x for x in 줄.get("대조") or [] if x.get("종류") == "실적 이음" and x.get("이름") == "범위.%s" % 번), None)


def _범위칸(원, 블록키, g, 줄):
    """가정 줄의 「실적 범위」 칸 — 「{최저} ~ {최고} · 끝 {끝} · 범위 {판정끝|글}」(장부 자리표시). 범위 대조가 없거나 값이 없으면 「—」.
    1.1.19 — 판정이 「정의 다름」(실적과 가정의 정의가 다르다 · 근거표 대조의 「정의다름」)이면 끝 값과 판정 대신 「{최저} ~ {최고} · {까닭|글}」
    (까닭 글은 「정의 다름 — …」 으로 연다 · HTML 은 띠를 그리지 않는다). 판정이 없는 줄(한 점 — 실적 값이 한 해)은 「—」."""
    번 = g.get("번호")
    if not 번 or g.get("종류") != "열별":
        return 없음
    d = _범위대조(줄, 번)
    if not d or d.get("한점"):
        return 없음
    b = "가:대조:%s:범위:%s" % (블록키, 번)
    꼴 = g.get("꼴") or "퍼1"
    if d.get("정의다름"):
        키 = {"최저": b + ":최저", "최고": b + ":최고", "까닭": d.get("까닭키") or b + ":까닭"}
        if not all(_값있나(원, k) for k in 키.values()):
            return 없음
        return "%s ~ %s · %s" % (자리(키["최저"], 꼴), 자리(키["최고"], 꼴), 자리(키["까닭"], "글"))
    키 = {"최저": b + ":최저", "최고": b + ":최고", "끝": b + ":끝", "판정": b + ":판정끝"}
    if not all(_값있나(원, k) for k in 키.values()):
        return 없음
    return "%s ~ %s · 끝 %s · 범위 %s" % (자리(키["최저"], 꼴), 자리(키["최고"], 꼴), 자리(키["끝"], 꼴), 자리(키["판정"], "글"))


def _범위표지(근거, 표지):
    """근거표의 범위 대조 가운데 표지(「정의다름」 · 「한점」)가 선 것이 있나 — 열 정의 문장에 그 뜻을 한 번 싣는다."""
    return any(d.get("종류") == "실적 이음" and ("%s" % d.get("이름") or "").startswith("범위.") and d.get(표지)
               for b in 근거["블록"] for z in b["줄"] if not 접나(z) for d in z.get("대조") or [])


def 접나(줄):
    """표의 줄(무게가 한 문단 문턱 아래) — 표에서 가정 · 밑 줄을 접고 결과 줄만 둔다."""
    return (줄.get("무게") or {}).get("표지") == "표의 줄"


def 가정결과표(근거, 블록키, 원=None, 정의=True):
    """블록 하나의 「가정과 결과」 표(마크다운 줄 목록). 원(레터 원천)을 주면 값이 없는 칸을 「—」 으로 둔다(없으면 모두 자리표시).
    정의 = False 면 표 아래 열 정의 줄을 싣지 않는다(레터는 열 정의를 첫 표에 한 번 — `첫열정의`)."""
    블 = next((b for b in 근거["블록"] if b["키"] == 블록키), None)
    if 블 is None or not (블["줄"] or 블["결과"]):
        return []
    열 = _열들(근거, 블)
    머리 = ["줄", "구분"] + [h for _c, h, _s in 열] + ["주당가치 폭" if 블록키 != "브리지" else "주주가치 대비"]
    범위들 = {}                                               # v27 7단계 — 가정 줄의 실적 범위 칸(값이 서는 줄이 하나라도 있으면 열을 둔다)
    for 줄 in 블["줄"]:
        if 접나(줄):
            continue
        for g in 줄["가정"]:
            c = _범위칸(원, 블["키"], g, 줄)
            if c != 없음:
                범위들[id(g)] = c
    범위 = bool(범위들)
    if 범위:
        머리 = 머리 + [범위열]
    덧 = [없음] if 범위 else []
    줄들, 접은 = [], 0
    합줄 = [r for r in 블["결과"] if r.get("합")]                 # 합(줄 id 목록 · 「*」 는 접두)을 단 블록 결과는 그 줄들 바로 뒤에(표 구성 합 = 합계)
    마지막 = {}
    for i, 줄 in enumerate(블["줄"]):
        for r in 합줄:
            if any(fnmatch.fnmatch(줄["id"], p) for p in r["합"]):
                마지막[id(r)] = i

    def 블록결과줄(r):
        이 = ("**%s**" % r["이름"]) if r.get("굵게") else r["이름"]
        return [이, "합계"] + [_칸(원, r.get("키꼴") or r.get("식꼴"), c, r["꼴"], s) for c, _h, s in 열] + [없음] + 덧
    for i, 줄 in enumerate(블["줄"]):
        접 = 접나(줄)
        접은 += 1 if 접 else 0
        if not 접:
            for g in 줄["가정"]:
                줄들.append([g["이름"], "규칙" if g["종류"] == "규칙" else "가정"] + [_가정칸(원, g, c, s, 블["열"], 근거["열"]["첫"]) for c, _h, s in 열]
                           + [없음] + ([범위들.get(id(g), 없음)] if 범위 else []))
            for b in 줄.get("밑") or []:
                줄들.append([b["이름"], "밑"] + [_칸(원, b["키꼴"], c, b.get("꼴") or "금액", s) for c, _h, s in 열] + [없음] + 덧)
        결 = 줄["결과"]
        굵은 = [i for i, r in enumerate(결) if r.get("굵게")]
        무게자리 = 굵은[-1] if 굵은 else len(결) - 1
        for i, r in enumerate(결):
            폭 = _폭칸(줄) if i == 무게자리 else 없음
            이 = ("**%s**" % r["이름"]) if r.get("굵게") else r["이름"]
            줄들.append([이, "결과"] + [_칸(원, r.get("키꼴") or r.get("식꼴"), c, r["꼴"], s) for c, _h, s in 열] + [폭] + 덧)
        if not 접:
            for r in 줄.get("식") or []:
                줄들.append([r["이름"], "결과"] + [_칸(원, r["식꼴"], c, r["꼴"], s) for c, _h, s in 열] + [없음] + 덧)
        for r in 합줄:
            if 마지막.get(id(r)) == i:
                줄들.append(블록결과줄(r))
    for r in 블["결과"]:
        if r.get("합") and id(r) in 마지막:
            continue
        줄들.append(블록결과줄(r))
    L = ["**표. %s — 가정과 결과(기준 시나리오)**" % 블["블록"], ""] + _표(머리, 줄들) + [""]
    if 정의:
        L.append(열정의(근거, 블, 접은))
    return L


