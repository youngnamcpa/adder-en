"""레터레짐 — 선택 표 「레짐 기대값」(1.1.6 · 값을 바꾸지 않는다). 재료는 가정 곁 `_raw/레짐.json`(「레짐/1」 — `레짐.py`)과 원고 `관측.레짐`.

  레짐주당   장부 키 「레:i」 — 관측.레짐.목록[i] 의 묶음(시나리오 · 바꿈 · 반대 논거 · βU 대안)을 엔진으로 다시 셈한 주당가치(레터 · 게이트가 같은 함수)
  레짐절     역산 절 소절 — 레짐 · 가정 묶음 · 주당가치 · 확률(기저율 · 판단) · 근거 · 기대값 · 시장가가 함축하는 최상위 레짐 확률
선언이 없거나 재료가 선언 · 엔진 값과 맞지 않으면(낡음) 표를 세우지 않고 저자에게 알린다. 확률은 장부 키 「파일:레짐:레짐:i:확률」,
기대값 · 함축 확률은 장부 식이다(게이트 ⑦ 이 다시 셈한다). 회사 · 업종 이름은 이 모듈에 없다.
"""
from __future__ import annotations

import importlib


def _P():
    return importlib.import_module("레터1부")


def _n(x):
    try:
        return None if x is None or isinstance(x, bool) else float(x)
    except (TypeError, ValueError):
        return None


def 레짐주당(가정, i, 원):
    """「레:i」 — 관측.레짐.목록[i] 의 묶음을 엔진으로 셈한 주당가치(`레짐.주당` — 도구와 같은 셈)."""
    캐 = 원.setdefault("_레짐", {})
    if i not in 캐:
        import 레짐                                          # noqa: PLC0415
        목, _확 = 레짐.선언(가정)
        캐[i] = 레짐.주당(가정, 목[int(i)])
    return 캐[i]


def 재료(맥):
    return ((맥.원.get("파일") or {}).get("레짐")) or {}


K = "파일:레짐:%s"
_차 = {1: "첫째", 2: "둘째", 3: "셋째", 4: "넷째", 5: "다섯째", 6: "여섯째"}
_곳 = {1: "한", 2: "두", 3: "세", 4: "네", 5: "다섯"}


def 묶음칸(맥, k, x):
    """레짐 k 의 가정 묶음 칸 — 원고 「묶음글」 이 있으면 그 글, 없으면 「낙관 시나리오 + 반대 논거 첫째 + 가정 두 곳 바꿈 + Unlevered Beta 1.250」
    (숫자는 장부 키 — βU 는 「G:관측:레짐:목록:k:βU」)."""
    if ("%s" % (x.get("묶음글") or "")).strip():
        return 맥.원고글(x["묶음글"], "관측.레짐.목록[%d].묶음글" % k) or "—"
    조 = ["%s 시나리오" % (x.get("시나리오") or "기준")]
    반 = [int(i) + 1 for i in x.get("반대논거") or [] if ("%s" % i).isdigit()]
    if 반:
        조.append("반대 논거 %s" % " · ".join(_차.get(n, "%d번째" % n) for n in 반))
    n = len(x.get("바꿈") or [])
    if n:
        조.append("가정 %s곳 바꿈" % _곳.get(n, "%d" % n))
    if _n(x.get("βU")) is not None:
        조.append("Unlevered Beta %s" % 맥.수("G:관측:레짐:목록:%d:βU" % k, "지수3"))
    return " + ".join(조)


def 레짐절(맥):
    """역산 절의 「레짐 기대값」 소절 — 선언 · 재료 · 확률이 모두 맞을 때만."""
    import 레짐 as _R                                        # noqa: PLC0415
    P = _P()
    목, _확 = _R.선언(맥.가정)
    if not 목:
        return []
    j = 재료(맥)
