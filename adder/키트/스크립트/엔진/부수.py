def _넷째판정(자본경량, 증분, 증분배, ronic, 구):
    """④ 예측 끝 증분 ROIC ÷ 영구 RONIC 의 판정 글. S8R1-N2(S9 이월) — 예측 끝 이익이 줄어드는 판(ΔNOPLAT ≤ 0 — 마진 정상화 · 사이클 정점 뒤)과
    정상화 계단을 선언한 판은 증분 ROIC 가 성장–재투자의 다리가 아니라 마진 변화를 잰다 → 「해당 없음」(연장.py 의 T3 단서도 이 글을 읽는다)."""
    if 자본경량:
        return "해당 없음 — 자본경량"
    if 증분.get("무재투자"):
        return ("확인 필요 — 예측 끝 성장이 재투자 없이 났습니다(순재투자 ≤ 0) — 영구에서 RONIC %.1f%% 로 재투자가 되살아납니다(재투자 절벽)"
                % (_n(ronic) * 100))
    if 증분["값"] is not None and 증분["값"] < 0:
        return "해당 없음 — 마진 정상화 구간(예측 끝 이익이 줄어든다 · 증분 ROIC %.1f%% — 마진 변화라 성장–재투자의 다리를 재지 않는다)" % (증분["값"] * 100)
    try:
        계단 = 구["영구가치"].get("정상화계단") == "예"
    except Exception:                                   # noqa: BLE001
        계단 = False
    if 계단:
        return "해당 없음 — 정상화 계단(구조.영구가치.정상화계단 = 예 — 영구에서 마진을 내린 판은 증분 ROIC 로 다리를 재지 않는다)"
    if 증분["값"] is None:
        return "재료 없음 — %s" % 증분["까닭"]
    if 증분배 is not None and 0.5 <= 증분배 <= 2.0:
        return "OK"
    return ("확인 필요 — 성장과 재투자의 다리가 영구에서 바뀝니다(증분 ROIC %s ÷ RONIC %.1f%% = %s배 — 0.5~2.0 밖)"
            % (("%.1f%%" % (증분["값"] * 100)) if 증분["값"] is not None else "—", _n(ronic) * 100, ("%.2f" % 증분배) if 증분배 is not None else "—"))


