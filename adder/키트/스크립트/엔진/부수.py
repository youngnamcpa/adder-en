def 증분ROIC(R, 축):
    """S8-05 — 예측 끝 증분 ROIC = (마지막 해 NOPLAT − k 해 앞 NOPLAT) ÷ 그 사이 앞 해들의 순재투자(CAPEX − D&A + 순운전자본 증가) — 연환산.
    {"값", "구간", "무재투자", "까닭"}. 연간 예측 열이 둘 미만이면 재료 없음."""
    d = R["2.DCF"]
    연간 = [i for i in 축.예측 if abs(축.열[i].년 - 1.0) < 1e-9]
    if len(연간) < 2:
        return {"값": None, "구간": None, "까닭": "연간 예측 열이 둘 미만"}
    k = min(증분ROIC해, len(연간) - 1)
    끝i, 앞i = 연간[-1], 연간[-1 - k]
    c끝, c앞 = 축.ID[끝i], 축.ID[앞i]
    구간 = "%s→%s" % (c앞, c끝)
    if "116" in d and "117" in d:                       # Y3-2 — 조정 세후영업이익 · 조정 재투자(연구개발자본화) — 2번 덤의 증분 ROIC 와 같은 잣대
        쓰는 = [d["116"][c끝], d["116"][c앞]] + [d["117"][축.ID[i]] for i in 연간[-1 - k:-1]]
        if any(x is None for x in 쓰는):
            return {"값": None, "구간": 구간, "까닭": "연구자산이 읽는 해의 연구개발비가 비어 조정 세후영업이익 · 재투자가 확인 불가"}
        Δ = d["116"][c끝] - d["116"][c앞]
        재 = sum(d["117"][축.ID[i]] for i in 연간[-1 - k:-1])
    else:
        Δ = _n(d["19"][c끝]) - _n(d["19"][c앞])
        재 = sum(_n(d["21"][축.ID[i]]) - _n(d["20"][축.ID[i]]) + _n(d["22"][축.ID[i]]) for i in 연간[-1 - k:-1])
    if 재 <= 0:
        return {"값": None, "구간": 구간, "무재투자": Δ > 0, "까닭": "그 사이 순재투자가 0 이하(%s) — 증분 ROIC 를 못 잰다" % _금액(재)}
    return {"값": Δ / 재, "구간": 구간, "무재투자": False}


