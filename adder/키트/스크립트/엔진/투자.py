def _겹(a, b, s, L):
    """[a, b] 와 상각 구간 [s, s + L] 이 겹치는 길이(년) — MAX(0, MIN(b, s + L) − MAX(a, s))."""
    return max(0.0, min(b, s + L) - max(a, s))


def _찬(z):
    """clamp(z, 0, 1) = (|z| − |z − 1| + 1) ÷ 2 — 표 T7 의 누적 상각 식과 같은 꼴로 셈한다."""
    return (abs(z) - abs(z - 1) + 1) / 2


