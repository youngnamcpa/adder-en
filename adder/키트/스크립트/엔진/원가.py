def _경로(유형, 매출, 비율행, 물가행, 축, 열별비율=False):
    """옛 물가형 · 비율형(W3b 과도기의 식 그대로). 금액을 축 순서의 목록으로 낸다(실적 열은 None).

    물가형 : 첫 예측 열만 매출액 × 비율. 그 뒤는 앞 열의 연간 수준을 물가로 민다(연 단위) — 금액 = 연간 수준 × 기간(년)
    비율형 : 매출액 × 비율. 열별비율이면 그 열의 비율, 아니면 첫 예측 열의 비율(고정)
    """
    v = [None] * 축.n
    년 = 축.줄("년")
    첫 = 축.첫예측
    첫비율 = 비율행[첫]
    v[첫] = _n(매출[첫]) * _n(첫비율)
    수준 = v[첫] / 년[첫]
    for i in 축.예측[1:] + [축.영구]:
        if 유형 == "비율형":
            v[i] = _n(매출[i]) * _n(비율행[i] if 열별비율 else 첫비율)
            continue
        수준 = 수준 * (1 + _n(물가행[i]))
        v[i] = 수준 * 년[i]
    return v


