def _합(본, 들, i):
    """원가 줄들의 그 열 합 — 워크북의 `{모두 k … 「+」}` 와 같은 차례로 더한다. 하나도 없으면 0."""
    v = 0.0
    for j, k in enumerate(들):
        v = _n(본[k][i]) if j == 0 else v + _n(본[k][i])
    return v


