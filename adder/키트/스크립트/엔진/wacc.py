def 번호줄(W, 가정):
    """결과의 `3.WACC` — 3번 시트의 계산 줄을 번호로 낸다({번호: {열 ID 또는 표의 칸: 값}}).

    구조에 따라 입력인 줄(직접 적는 무위험이자율 · 무차입 베타 · 신용스프레드)의 번호도 함께 낸다 — 대조는 워크북에 수식이 선 칸만 견준다."""
    줄 = {번: {구간열[구간]: W[구간][키] for 구간 in WACC구간} for 번, 키 in _줄키}
    표 = 유사기업표(가정)
    for i, x in enumerate(표["줄"]):
        줄["%d" % (유사기업첫줄 + i)] = {"단순식": x["단순식"]}
    if 표["줄"]:
        줄["%d" % 평균줄] = {"무차입베타": 표["평균"]}
        줄["%d" % 중앙값줄] = {"무차입베타": 표["중앙값"]}
    지역 = 지역가중표(가정)
    if 지역["줄"]:
        줄["%d" % 지역가중줄] = {"위험프리미엄": 지역["가중"]}
    return 줄
