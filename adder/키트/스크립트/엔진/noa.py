    목록 = (가정 or {}).get("지분경로") or []
    if not 목록:
        return noa
    선언 = {x["번호"]: x for x in (((가정.get("구조") or {}).get("가치조정") or {}).get("지분") or [])}
    발생 = ((가정.get("스위치") or {}).get("현금흐름발생시점")) or "기중"
    적용 = 축.적용할인기간(발생)
    예 = list(축.예측)
    낸 = {}
    for d in 목록:
        s = d["구분"]
        줄_ = 매["1%d5" % s]
        P0 = d.get("기준지수")
        if _빈칸(P0):
            P0 = ((가정.get("표") or {}).get("%d" % (600 + 10 * s + 7)) or {}).get("판매단가지수")
        P0 = _n(P0)
        r = 경로DCF(d, [_n(줄_[i]) for i in 예], P0, [축.열[i].년 for i in 예], [적용[i] for i in 예])
        x = 선언[d["지분"]]
        장부, 평가, 세 = 지분평가(가정, 시나리오, x, 배율=r["배율"])
        noa["비영업"][지분줄(x["번호"])] = {"D": 장부, "E": 평가 - 장부, "F": 평가, "G": 세, "H": 평가 + 세}
        낸[d["지분"]] = dict(r, 구분=s, 기준지수=P0, 열=[dict(c, 기간=축.ID[i]) for c, i in zip(r["열"], 예)])
