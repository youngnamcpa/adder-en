def 지분평가(가정, 시나리오, x, 배율=None):
    """R1a(K5) — 지분 x 의 (장부, 세전 평가액, 세효과). 장부 = 시점가정 970+, 평가 = 방식대로, 세효과 = −(평가 − 장부) × 세효과율(대칭) ·
    −MAX(평가 − 장부, 0) × 세효과율(이익만). 세효과율이 없으면 217(비영업자산 평가차익 적용세율).
    배율 — 경로 DCF(`지분경로`)가 낸 배율. 주면 시점가정의 배율 칸 대신 쓴다(방식 = 배율일 때만)."""
    k = x["번호"]

    def S(c):
        return _시점(가정, 지분번호(k, c), 시나리오)
    장부 = _n(S("장부"))
    방식 = x.get("방식") or "시가"                     # noa계산 은 가정의 구조를 그대로 읽는다 — 기본값(구조틀)을 여기서 채운다
    if 방식 == "시가":
        평가 = 장부 if _빈칸(S("시가")) else _n(S("시가"))
    elif 방식 == "배율":
        평가 = 장부 * (_n(S("배율")) if 배율 is None else 배율)
    else:
        평가 = _n(S("이익")) * _n(S("배수")) * _n(S("지분율"))
    율 = _n(_시점(가정, 217, 시나리오)) if _빈칸(S("세효과율")) else _n(S("세효과율"))
    조정 = 평가 - 장부
    세 = -(조정 if (x.get("세효과") or "대칭") == "대칭" else max(조정, 0.0)) * 율
    return 장부, 평가, 세


# ────────────────────────────────────────────────────────────── 지분 방식 「경로 DCF」(재평가 S3 — 0_총괄결정 2026-10-15 10 ⑤)
