def 지분성격몫(R):
    """S10R1-N5 — 교차 보유 · 관계기업 몫. → {"지분": 지분 성격 장부, "금융": 금융상품 성격 장부, "분모": 영업가치 + 비영업 장부(11번 D16),
    "몫": 지분 ÷ 분모 · 영업가치 ≤ 0 이면 None}. 옛 몫(비영업 장부 전체 ÷ 주주가치)은 분자에 금융상품까지, 분모에 결과(주주가치)를 써서
    영업가치가 작거나 음수인 회사에서 124% 같은 몫을 냈다. 분모를 「영업가치 + 비영업」(기업가치 쪽 — 결과의 부호에 안 흔들림)으로 둔다."""
    noa = R.get("NOA") or {}
    비 = noa.get("비영업") or {}

    def D(k):
        v = 비.get(k, 비.get("%s" % k))
        return _n((v or {}).get("D")) if isinstance(v, dict) else 0.0
    지분 = sum(D(k) for k in 지분성격줄) + sum(D(k) for k in 비 if "%s" % k in ("111", "112", "113"))
    금융 = sum(D(k) for k in 금융성격줄)
    영업 = _n(((R.get("요약") or {}).get("영업가치")))
    d16 = _n(noa.get("D16"))
    if 영업 <= 0 or 영업 + d16 <= 0:
        return {"지분": 지분, "금융": 금융, "분모": None, "몫": None, "영업가치": 영업}
    return {"지분": 지분, "금융": 금융, "분모": 영업 + d16, "몫": 지분 / (영업 + d16), "영업가치": 영업}


