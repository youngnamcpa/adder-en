#   금액(기준매출 · 고정비 · 순투자 · 시가총액)은 지분 회사의 한 통화 · 한 단위. 기준매출 · 고정비는 기준 기간(기준기간개월) 한 기간의 값,
#   순투자는 한 해 값. 기준지수를 비우면 그 구분의 기준 기간 웨이퍼당 매출 지수(표 600 + 10s + 7 판매단가지수).
# 식(열 t = 예측 열, 년 = 그 열의 길이, k = 12 ÷ 기준기간개월):
#   기간 매출 q = 기준매출 × 지수(4번 1s5) ÷ 기준지수 · 기간 수 n = k × 년
