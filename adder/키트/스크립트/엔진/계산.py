# -*- coding: utf-8 -*-
"""엔진/계산 — 시트 함수를 차례로 불러 한 시나리오의 결과를 조립한다. 산식은 여기 없다.

  결과 = 계산(가정, "기준")
  결과["4.Sales"]["54"]["FY2027E"]      # 시트 키 → 줄 번호 → {기간 ID: 값}
  결과["2.DCF"]["68"]                   # 한 값 줄은 번호 키에 값 하나(옛 「D68」)

차례(설계서 3-3 · 9-1 — W5f 가 끝 모습으로)
  기간 축 → 구조(검증) → 읽개 → 11번(noa) → 3번(wacc) → 4번(매출) → 8번(투자) → 7번 급여(인원 · 급여 — 성과급 차감 전 인건비)
  → 5 · 6번 원가 줄(산정액 · 적용액 · 재료비 및 경비 소계 · 배분 · 상각 · 발생원가 161) → 9번 재고(재고 변동 반영 = 예 — 9번 111)
  → 5 · 6번 인건비 제외 소계(154 · 184) → 7번 성과급(41 이 154 · 184 를 읽는다) · 배분 → 5 · 6번 합계 · 영업이익
  → 10번(법인세) → 2번 할인표(26~35 — S8-04) → 9번(운전자본 — 재고 줄은 앞에서 낸 것) → 2번(가치) → 1번(요약 줄 — W6a) → 요약 → 부수
  성과급이 원가 소계를 읽지 않는 갈래(성과급 없음 · 매출액비율 · 미분리 · 옛 갈래)는 성과급 단계를 급여 바로 뒤에 부른다 — 발생원가(161)가
  인건비 합계(7번 14 — 매출액비율)를 읽는다

시트 함수는 `줄묶음`({번호: 축 순서의 목록 또는 한 값})을 내고, 뒤의 시트 함수는 앞의 줄묶음을 **번호로** 읽는다(`매["54"]`).
새 시트 함수의 줄을 다른 시트가 읽어야 하면 그 번호를 줄묶음에 싣는 것으로 끝난다 — 이 파일은 차례가 바뀔 때만 고친다.
"""

from .공통 import 가정오류, 시나리오목록, 줄묶음, 열틀, _나눔
from .읽개 import 읽개
from .스키마 import 검증전부
from . import wacc as _wacc, noa as _noa, 매출 as _매출, 인건비 as _인건비, 투자 as _투자, 원가 as _원가
from . import 운전자본 as _운전자본, 법인세 as _법인세, 가치 as _가치, 가정시트 as _가정시트, 요약 as _요약
from .할인 import 할인표
