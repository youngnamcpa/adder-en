def _접은(줄들, 축):
    """줄묶음 → 결과의 시트. 열 줄(축 순서의 목록)은 {기간 ID: 값} 으로 접고, 한 값 줄은 그대로 싣는다."""
    return {k: (축.접기(v) if isinstance(v, list) else v) for k, v in 줄들.items()}


def _가정번호():
    from .등록 import 가정번호전부          # 등록이 시트 함수 파일을 다 읽은 뒤에 부른다
    return 가정번호전부()


def _기말인원(구, 인, 끝):
    """W6c(S6) — 최종 예측 연도의 기말 인원(7번 10). 인원이 없는 갈래(매출액비율 · 수준이 아닌 미분리)면 None — 1번 58 의 옛 식과 같은 빈칸."""
    인구 = 구["인건비"]
    if 인구["산정방식"] == "매출액비율" or (인구["산정방식"] == "미분리" and 인구["인원경로"] != "수준"):
        return None
    r10 = 인.get("10") if 인 is not None else None
    return None if r10 is None else r10[끝]


def _연구요약(투, 값, 틀):
    """Y3-2 — 연구개발자본화의 요약(결과 `요약.연구개발자본화`). 열 값은 `8.CapEx` 701~706 · `2.DCF` 115~119 · 141 이 정본이다."""
    끝, 영 = 틀.끝예측, 틀.영구열
    ID = 틀.축.ID
    덤 = 투.덤.get("연구자산") or {}
    연 = 값.덤.get("연구") or {}
    return {
        "상각연수": 덤.get("상각연수"),
        "마지막실적열": ID[틀.축.FY실적[-1]],
        "기준연구자산": 투["703"][틀.축.FY실적[-1]], "기준상각비": 투["702"][틀.축.FY실적[-1]],
        "기준조정액": 투["704"][틀.축.FY실적[-1]],                                   # 마지막 FY 실적 열 — 다모다란 converter 의 당기
        "마지막예측연구자산": 투["703"][끝], "영구연구자산": 투["703"][영],
        "마지막예측조정액": 투["704"][끝], "영구조정액": 연.get("영구조정액"),
        "마지막해조정영업이익률": 값["119"][끝], "영구기간조정영업이익률": 값["119"][영],
        "조정영구세후영업이익": 연.get("조정영구세후영업이익"), "보고영구세후영업이익": 연.get("보고영구세후영업이익"),
        "영구가치차": 연.get("영구가치차"),                                          # 141 − 45 가 영구가치(최종 예측 연도 말)에 더한 몫
        "확인불가열": 덤.get("확인불가열") or [],
    }


def 계산(가정, 시나리오="기준"):
    """한 시나리오의 전 시트·전 열을 계산한다. 결과의 줄은 {기간 ID: 값} 이다."""
    if 시나리오 not in 시나리오목록:
        raise ValueError("시나리오는 비관/기준/낙관 중 하나여야 합니다: %r" % 시나리오)
    오류, _경보, 구, 축 = 검증전부(가정)
    if 오류:
        raise 가정오류("가정 JSON 오류 %d건\n" % len(오류)
                     + "\n".join("  - " + x for x in 오류))

    틀 = 열틀(축)                                    # 열의 자리는 전부 기간 축에서 온다
    읽 = 읽개(가정, 시나리오, 축)

    noa = _noa.noa계산(가정, 시나리오, 축)                                   # 11번
    W = _wacc.wacc계산(가정, noa["D30"], _wacc._시가총액(가정, 축))          # 3번
    매 = _매출.계산(읽, 틀, 구)                                              # 4번
    noa = _noa.경로반영(noa, 가정, 시나리오, 축, 매)                        # 지분 방식 「경로 DCF」 — 지분경로 가 있으면 매출 경로로 지분 배율(없으면 그대로)
    투 = _투자.계산(읽, 틀, 구, 매)                                          # 8번 — 매출 뒤 · 원가 앞(감가상각 · 3g1 · 3g7 이 5 · 6번으로 흐른다 — W5b)
    인 = _인건비.급여(읽, 틀, 구, 매)                                        # 7번 급여 — 성과급 차감 전 인건비(34)까지(W5e)
    인구 = 구["인건비"]
    성과급뒤 = 인구["산정방식"] == "인원" and 인구["인원경로"] != "수준" and 인구["성과급"] != "없음"
    if not 성과급뒤:                                                         # 성과급이 원가 소계를 읽지 않는 갈래 — 인건비를 먼저 다 낸다
        인 = _인건비.성과급(인, 읽, 틀, 구, 매)
    원, 판 = _원가.원가줄(읽, 틀, 구, 매, 인, 투)                            # 5 · 6번 원가 줄 · 소계(151) · 배분 · 상각 · 발생원가(161) — W5f
    재 = _운전자본.재고(읽, 틀, 구, 원) if 구["원가"]["재고변동반영"] == "예" else None   # 9번 재고 — 성과급보다 먼저(W5c → 5번 153)
    _원가.소계(원, 판, 읽, 틀, 구, 재)                                        # 5번 153 · 154 · 6번 184 — 7번 41 이 읽는다
    if 성과급뒤:
        인 = _인건비.성과급(인, 읽, 틀, 구, 매, 원["154"], 판["184"])          # 7번 성과급 · 배분(23 · 24 · 25)
    _원가.손익(원, 판, 읽, 틀, 구, 매, 인)                                     # 5 · 6번 인건비 줄 · 합계 · 영업이익(결과)
    if _투자.연구켬(구):                                                     # Y3-2 — 8번 연구자산(701~706). 연구개발원가줄이 원가 줄 금액을 읽어 손익 뒤에 선다
        연줄, 연덤 = _투자.연구자산(읽, 틀, 구, 매, 원, 판)                   # (8번의 다른 줄 · 5 · 6번은 이 줄을 읽지 않는다 — 법인세 · 가치 앞이면 된다)
        투.update(연줄)
        투.덤["연구자산"] = 연덤
    세 = _법인세.계산(읽, 틀, 구, 판, 투, 매)                                # 10번 — 9번의 미지급 항목이 법인세를 읽으므로 9번보다 먼저(W5c). 매 = 연구개발 공제의 매출액(R1a K9)
    할 = 할인표(읽, 틀, 구, W)                                                # 2번 26~35 — W · 구조 · 축만으로 정해진다(S8-04). 9번 지급 시점 보정 · 2번이 같은 표를 읽는다
    운 = _운전자본.계산(읽, 틀, 구, 매, 원, 판, 인, 세, W, 재=재, 할=할)      # 9번 — 재고 줄은 앞에서 낸 것을 쓴다
    값 = _가치.계산(읽, 틀, 구, 매, 원, 판, 투, 운, 세, W, noa, 인, 할=할)    # 2번 — 인(7번 42 성과급 지급률)은 초과 상각의 절감률(W6a)
    공장 = _투자.공장표(읽, 틀, 구, 매, 투, 인, 값)                          # R2(K10) — 8번 끝의 공장별 표(값에 넣지 않는다 · 공장표 = 예일 때만)

    기간결과 = 축.사전()
    기간결과["발생시점"] = 값.덤["발생시점"]
    기간결과["적용할인기간"] = 축.접기(값.덤["적용할인기간"])
    끝 = 틀.끝예측
    결과 = {
        "시나리오": 시나리오,
        "기간": 기간결과,
        "WACC": W,
        "NOA": noa,
        "3.WACC": _wacc.번호줄(W, 가정),          # 3번 · 11번의 계산 줄 — 시간축이 아닌 시트라 줄마다 {열 ID: 값} (W4)
        "11.NOA": _noa.번호줄(noa),
        "4.Sales": _접은(매, 축),
        "5.COGS": _접은(원, 축),
        "6.SG&A": _접은(판, 축),
        "7.Payroll": _접은(인, 축),
        "8.CapEx": _접은(투, 축),
        "9.WC": _접은(운, 축),
        "10.Tax": _접은(세, 축),
        "2.DCF": _접은(값, 축),
        "12.가정": _접은(_가정시트.계산(읽, 틀, 구, 값, _가정번호(), (_가치.표번호, _가치.잔여칸)), 축),   # 엔진이 읽은 값 — 대조용
        "1.요약": _요약.계산(읽, 틀, 구, 매, 원, 판, 인, 투, 값, W),      # 1번 — 요약 줄(W6a). 줄마다 {열 ID · 칸 별칭: 값}
        "요약": {
            "주당가치": 값["68"], "주주가치": 값["66"], "영업가치": 값["58"],
            "예측기간FCFF현가합": 값["40"], "영구가치현가": 값["54"],
            "영구가치비중": _나눔(값["54"], 값["58"]),
            "한시적회수현가": 값["55"], "한시적영구제외": 값.덤["한시적영구제외"],
            "예측기간WACC": W["예측기간"]["WACC"], "영구기간WACC": W["영구기간"]["WACC"],
            "영구성장률": 값["47"], "영구ROIC": 값["48"], "재투자율": 값["49"],
            # W4 — 영구가치에 쓴 영업이익률은 둘이다: 영구기간 영업이익률(2번 42 — 결과) · Normalization 영업이익률(2번 140 — 대조 기준값)
            "영구기간영업이익률": 값["42"], "Normalization영업이익률": 값.덤["Normalization영업이익률"],
            "유통주식수": 값["67"], "희석주식수": 값["151"], "적용주식수": 값["152"],
            "지급시점보정": 값.덤["지급시점보정"], "초과상각조정": 값.덤["초과상각조정"],          # W6a — 2번 121 · 131(선언하지 않았으면 0)
            "이월세액공제조정": 값.덤["이월세액공제조정"],                                        # W6c — 2번 132(세액공제이월 = 아니오면 0)
            "이월결손금조정": 값.덤["이월결손금조정"],                                            # S8-08 — 2번 133(결손금처리 = 세율수렴_예측결손이월 이 아니면 0)
            # S8-03 — 영구가치 할인 시점(영구가치 규칙 = 기말)과, 다른 시점(기중 ↔ 기말)으로 두었을 때의 주당가치 차(값에 쓰지 않는다)
            "영구가치할인시점": 값.덤["영구가치할인시점"],
            "다른할인시점주당가치": 값.덤["다른할인시점주당가치"],
            "다른할인시점차": (_나눔(값.덤["다른할인시점주당가치"], 값["68"]) - 1) if 값["68"] else None,
            # S8-05 — 영구 RONIC 의 두 값: 지금(219 · 비우면 영구 WACC)과 예측 끝 증분 ROIC 로 둘 때의 주당가치(값에 쓰지 않는다)
            "증분ROIC": 값.덤["증분ROIC"], "RONIC증분주당가치": 값.덤["RONIC증분주당가치"],
            "기말인원": _기말인원(구, 인, 끝),                                                   # W6c(S6) — 1번 58(붓기가 세 시나리오를 적는다)
            "마지막예측열": 축.ID[끝],
            **({"공장": 공장} if 공장 is not None else {}),                 # R2(K10) — 레터가 읽는 공장별 요약(영구기간 열 + 열마다)
            "마지막해영업이익률": _나눔(판["22"][끝], 매["54"][끝]),
            "예측기간길이합": 값.덤["예측기간길이합"],
            "잔여매출방식": 매.덤["잔여매출방식"], "잔여비율": 매.덤["잔여비율"],
            "구조지문": 구.지문,
            **({"연구개발자본화": _연구요약(투, 값, 틀)} if "704" in 투 else {}),     # Y3-2 — 켰을 때만(끔이면 요약 키 불변)
            # 날짜 둘(2026-10-25) — 이월 판(재무기준일 ≠ 평가기준일)에서만. 주주가치 · 적용주식수 · 주당가치는 평가기준일 값이다(2번 66 · 152 · 68)
            **({k: v for k, v in 값.덤["이월"].items() if k != "사이자본거래"} if 값.덤.get("이월") else {}),
        },
    }
    결과["부수"] = 부수산출(가정, 결과, 축, 구)
    return 결과
