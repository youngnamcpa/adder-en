# -*- coding: utf-8 -*-
"""엔진/가정시트 — 12. 가정_시나리오 의 계산 줄. 산식이 아니라 **엔진이 읽은 값**을 번호 줄로 낸다(W3c — 전 줄 대조).

워크북의 12번은 시나리오 세 줄에서 「적용값」을 고르고(INDEX) 시간 줄을 계산한다. 엔진은 같은 값을 읽개와 기간 축으로 읽는다.
그 둘이 같은지를 대조가 직접 보게, 엔진이 읽은 값을 12번의 번호로 싣는다 — 뒤 시트의 줄이 맞아서 간접으로 맞는 것이 아니라 줄마다 맞는지 본다.

  읽는 것  읽개의 `A(번호)`(시트 함수 파일들이 머리에 적은 `가정번호` 전부) · 기간 축 · `T(399 · 408 · 417)` · 2번이 낸 덤
  내는 것  적용값 줄 — 번호 = 가정 번호(시트 함수 파일의 `가정번호` 에 적으면 저절로 실린다. 이 파일은 고치지 않는다)
           시간 줄   — 24 기간(개월) · 432 기간(년) · 25 할인기간(기말) · 26 할인기간(기중) · 27 할인기간(적용) · 434 회계연도 ·
                       435 기간 시작 시점(년) · 436 회계연도 시작 시점(년)
           한시적    — 399 · 408 · 417 잔여액(예측기간 밖 1 · 2 · 3년차 — 워크북은 시간 열의 넷째~여섯째 칸에 놓는다) ·
                       421 (−) 한시적 현금흐름 연환산(한 값)

**엔진은 워크북에 수식이 없는 칸에 수를 싣지 않는다**(`None`) — 실으면 대조가 「한쪽만 수」로 잡는다. 그래서 줄마다 워크북의 무늬가
서는 열에만 값을 놓는다(할인기간은 예측 열 …).
글 · 날짜를 내는 줄(22 기간 종료일 · 23 실적/예측 · 431 기간 시작일 · 433 예측 구간)과 점검 보조 줄(265 · 266)은 줄 명세가 대조에서 뺀다.
"""

from .공통 import 줄묶음

시트키 = "12.가정"
한값줄 = ("421",)
잔여자리 = (3, 4, 5)                # 한시적 현금흐름 잔여액 1 · 2 · 3년차가 놓이는 시간 열의 자리(줄 명세의 「시간.4~시간.6」)


def 계산(읽, 틀, 구, 값, 가정번호, 잔여표):
    """`가정번호` = 12번 열별 가정의 번호 전부(`등록.가정번호전부()`), `잔여표` = (잔여액 번호들, 칸 이름들) — 2번(가치)의 것."""
    축, n = 틀.축, 틀.n
    줄 = {}
    from .등록 import 영구안읽는전부                      # S10-13 — 영구 칸을 읽지 않는 줄은 그 칸을 내지 않는다(워크북에도 칸이 없다)
    안읽 = 영구안읽는전부()
    for r in 가정번호:                                      # 적용값 — 그 시나리오가 읽는 한 벌(실적 열은 None)
        v = 읽.A(r)
        if str(r) in 안읽:
            v = list(v)
            v[축.영구] = None
        줄[str(r)] = v
    개월, 년, 기말, 기중 = 축.줄("개월"), 축.줄("년"), 축.줄("기말"), 축.줄("기중")
    줄["24"], 줄["432"] = list(개월), list(년)
    줄["25"] = [기말[i] if i in 틀.예측열 else None for i in range(n)]
    줄["26"] = [기중[i] if i in 틀.예측열 else None for i in range(n)]
    줄["27"] = [값.덤["적용할인기간"][i] if i in 틀.예측열 else None for i in range(n)]
    줄["434"] = list(축.줄("회계연도"))
    줄["435"] = list(축.줄("시작"))
    줄["436"] = list(축.줄("FY시작"))
    번호들, 칸들 = 잔여표
    for r in 번호들:                                        # 한시적 현금흐름 잔여액 — 표의 세 칸을 시간 열 넷째~여섯째 자리에
        표 = 읽.T(r) or {}
        v = [None] * n
        for 자리, 칸 in zip(잔여자리, 칸들):
            if 자리 < n:
                v[자리] = 표.get(칸)
        줄[str(r)] = v
    줄["421"] = 값.덤["한시적영구제외"]
    return 줄묶음(줄)
