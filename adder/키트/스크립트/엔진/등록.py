def 빈칸뜻전부():
    """{번호(int): 종류} — 시트 함수 파일의 `빈칸뜻` 을 모은다. 한 번호를 두 파일이 다른 종류로 적으면 먼저 적은 것을 쓴다(시험이 막는다)."""
    낸 = {}
    for m in 시트모듈:
        for 종류, 번호들 in (getattr(m, "빈칸뜻", None) or {}).items():
            for n in 번호들:
                낸.setdefault(int(n), 종류)
    return 낸


def 빈칸뜻점검():
    """등록 점검 — 빈칸뜻의 번호가 그 파일의 가정번호에 있나 · 종류가 셋 가운데 하나인가 · 두 파일이 같은 번호를 다르게 적지 않았나 → 문제 줄 목록."""
    줄, 본 = [], {}
    for m in 시트모듈:
        받는 = {int(x) for x in (getattr(m, "가정번호", ()) or ())}
        for 종류, 번호들 in (getattr(m, "빈칸뜻", None) or {}).items():
            if 종류 not in 빈칸종류:
                줄.append("%s 의 빈칸뜻 종류 「%s」 는 %s 가 아닙니다" % (m.__name__, 종류, " · ".join(빈칸종류)))
            for n in 번호들:
                if int(n) not in 받는:
                    줄.append("%s 의 빈칸뜻 %s 이(가) 그 파일의 가정번호에 없습니다" % (m.__name__, n))
                if int(n) in 본 and 본[int(n)] != 종류:
                    줄.append("빈칸뜻 %s 를 두 파일이 다른 종류로 적었습니다(%s · %s)" % (n, 본[int(n)], 종류))
                본.setdefault(int(n), 종류)
    return 줄


빈칸종류 = ("금액", "규칙", "대조")


