def _시트표(이름):
    """{시트 키: (번호 …)} — 시트 키가 하나인 파일의 `차감` · `한값줄`."""
    낸 = {}
    for m in 시트모듈:
        키, v = getattr(m, "시트키", None), getattr(m, 이름, None)
        if isinstance(키, str) and v:
            낸[키] = tuple(v)
        elif isinstance(v, dict):
            낸.update({k: tuple(x) for k, x in v.items() if x})
    return 낸


