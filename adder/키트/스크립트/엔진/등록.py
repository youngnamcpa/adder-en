# True = 자리 있음 · False = 이 구조에는 자리가 없다(엔진도 읽지 않는다 — 스키마 경보 · 붓기는 경보 후 건너뜀) · None = 이 표가 모르는 줄(옛 잣대 그대로)

def _자산군수(구):
    return len((구.get("투자") or {}).get("자산군") or [])


def 원천자리(구, 번호):
    """구조 구(구조.걷기의 결과 — 기본값이 채워진 것) · 13번 번호 → True · False · None(모름)."""
    try:
        n = int("%s" % 번호)
    except (TypeError, ValueError):
        return None
    투 = 구.get("투자") or {}
    인 = 구.get("인건비") or {}
    if 561 <= n <= 563:                                    # 자산군 g 취득원가(S13R56{g})
        return n - 560 <= _자산군수(구)
    if 564 <= n <= 566 or 597 <= n <= 599:                 # 자산군 g 순장부 · 감가상각비 — 빈티지일 때만
        g = (n - 563) if n <= 566 else (n - 596)
        return 투.get("상각방식") == "빈티지" and g <= _자산군수(구)
    if n == 567:
        return bool(투.get("프로젝트")) or 투.get("건설중인자산대체") == "예"
    if n == 569:
        return 투.get("유지규칙") == "취득원가비율"
    if n == 578:
        return (구.get("원가") or {}).get("재고변동반영") == "예"
    if n == 580:
        return (구.get("법인세") or {}).get("세액공제이월") == "예"
    if 571 <= n <= 577:                                    # 원가 줄 k 의 공시 금액 — 그 줄이 있고 실적 = 공시 · 옛식 아님
        k = n - 570
        return any(x.get("번호") == k and x.get("실적", "공시") == "공시" and x.get("옛식", "아니오") != "예" for x in (구.get("원가줄") or []))
    if 541 <= n <= 543:                                    # 직원 현황(S13 조건: 매출액비율 또는 인원경로 ≠ 수준)
        return 인.get("산정방식") == "매출액비율" or 인.get("인원경로") != "수준"
    # 손개입 개선 1(2026-10-18) — 인건비 블록(531~540 급여 · 퇴직 · 복리후생 · 연구개발 536 · 546~549 주식보상 등)은 생성기 S13 조건과 같은 자:
    #   산정방식 = 매출액비율, 또는 인원 이고 인원경로 ≠ 수준. 미분리(기능별 표시 — 미국)면 자리가 없다. 530 · 544 · 545 는 미지급 항목이 있어도 선다.
    #   종전에는 「모름」이라 붓기가 A3 의 536 을 좌표 오류로 멈췄다(실측: 기능별 표시 회차 — 미국 SaaS).
    인건비블록 = 인.get("산정방식") == "매출액비율" or (인.get("산정방식") == "인원" and 인.get("인원경로") != "수준")
    if n == 530:
        return ((인.get("산정방식") == "매출액비율" or 인.get("인원경로") != "수준") or bool((구.get("운전자본") or {}).get("미지급항목"))
                or 투.get("연구개발자본화", "아니오") == "예")
    if n in (544, 545):
        return 인건비블록 or bool((구.get("운전자본") or {}).get("미지급항목"))
    if n == 536 and 투.get("연구개발자본화", "아니오") == "예":
        return True                                        # Y3-2 — 연구개발자본화의 실적(비용 처리한 연구개발비 — 8번 701). S13R536 조건과 같은 자
    if 531 <= n <= 540 or 546 <= n <= 549:
        return 인건비블록
    return None
