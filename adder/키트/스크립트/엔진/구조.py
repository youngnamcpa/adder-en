def _지문감(v):
    if isinstance(v, dict):
        return {k: _지문감(x) for k, x in sorted(v.items())
                if k not in 지문밖키 and not (k in 기본이면지문밖 and x == 기본이면지문밖[k])}
    if isinstance(v, list):
        return [_지문감(x) for x in sorted(v, key=lambda x: (x.get("번호") if isinstance(x, dict) else 0) or 0)]
    return v


def 구조지문(가정, 구=None):
    """`기간`(네 값) · 평가기준일 · 재무기준일(다를 때만) · `구조`(기본값을 채운 것 — 이름 같은 글은 뺀다) · 지문판의 해시 16자.

    엔진이 읽은 구조의 뜻이 같으면 같은 글자다(기본값을 적든 안 적든 · 이름을 바꾸든). 결과의 `요약.구조지문` 에 실린다.
    지은 워크북의 꼬리표(좌표 지도의 「구조지문」 · 12번의 숨은 이름 `_구조지문`)는 이 글자가 아니다 — 생성기가 가정의 `구조`
    그대로와 명세 지문으로 낸다(`좌표.가정구조지문` 이 같은 셈으로 다시 낸다). 구조가 틀려 정규화하지 못하면 가정오류."""
    if 구 is None:
        오류 = []
        원 = (가정 or {}).get(구조키)
        if not isinstance(원, dict):
            raise 가정오류("구조 가 없어 구조 지문을 낼 수 없습니다")
        구 = _정규화(원, 오류)
        if 오류:
            raise 가정오류("구조 지문을 낼 수 없습니다 — 구조 오류 %d건\n" % len(오류) + "\n".join("  - " + x for x in 오류))
    기간 = (가정.get("기간") or {})
    메 = 가정.get("메타") or {}
    감 = {"판": 지문판, "평가기준일": "%s" % (메.get("평가기준일") or ""),
         "기간": {k: 기간.get(k) for k in ("결산월", "실적연도수", "상세추정연수", "수렴연수")},
         "구조": _지문감(dict(구))}
    if 메.get("재무기준일") not in (None, "") and "%s" % 메.get("재무기준일") != 감["평가기준일"]:
        감["재무기준일"] = "%s" % 메["재무기준일"]          # 날짜 둘(2026-10-25) — 이월 판만(옛 판 · F = T 는 옛 지문 그대로)
    글 = json.dumps(감, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(글.encode("utf-8")).hexdigest()[:16]
