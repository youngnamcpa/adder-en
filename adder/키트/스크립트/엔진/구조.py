def 구조오류(가정, 축=None, 지금받는=None):
    """(오류 줄 목록, 정규화한 구조 또는 None). `구조` 가 없으면 오류 한 줄."""
    원 = 가정.get(구조키) if isinstance(가정, dict) else None
    if 원 is None:
        return (["구조 가 없습니다 — 스키마 v13 의 가정 파일은 `구조` 구획으로 줄을 정합니다. 기간 부분만 옮긴 파일이면 "
                 "이전 도구를 다시 돌립니다: python 스크립트/가정이전_v13.py <가정.json>"], None)
    if not isinstance(원, dict):
        return ["구조 가 객체가 아닙니다 (%s)" % type(원).__name__], None
    오류 = []
    정 = _정규화(원, 오류)
    if not 정["매출구분"]:
        오류.append("구조.매출구분 이 비었습니다 — 매출 구분을 하나 이상 선언합니다")
    if 오류:
        return 오류, None
    구 = 구조(정)
    오류.extend(금지조합(가정, 구, 축))
    오류.extend(선언과값(가정, 구))
    오류.extend(못받는갈래(구, 지금받는))
    return 오류, 구


def 구조읽기(가정, 축=None, 지금받는=None):
    """검증을 지난 `구조`. 오류가 있으면 가정오류."""
    오류, 구 = 구조오류(가정, 축, 지금받는)
    if 오류:
        raise 가정오류("가정 JSON 오류 %d건\n" % len(오류) + "\n".join("  - " + x for x in 오류))
    구.지문 = 구조지문(가정, 구)
    return 구


