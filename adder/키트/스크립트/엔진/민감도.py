def 놓기값(가정, h, v, 시나리오="기준", R0=None):
    """1.1.2 — 손잡이를 표에 적는 값 v 로 놓은 가정(역산 `_놓기` 와 같은 셈). 가감 공간 손잡이(매출성장 · 목표마진)는 값으로 놓지 못한다(ValueError)."""
    h = 손잡이풀기(h, 가정)
    대상 = "%s" % h["대상"][0]
    if 대상 in ("매출성장", "목표마진"):
        raise ValueError("가감 공간 손잡이(%s)는 값으로 놓지 않는다" % 대상)
    R0 = R0 or 계산(가정, 시나리오)
    if 대상 in WACC대상:
        지금 = R0["WACC"][대상.split(".", 1)[1]]["WACC"]
        return 움직이기(가정, dict(h, 방식="가산"), v - 지금, 시나리오)
    if 대상 == "영구이익률가감":
        return 움직이기(가정, dict(h, 방식="가산"), v - R0["요약"]["영구기간영업이익률"], 시나리오)
    지금 = _n(적용값(가정, h, 시나리오, R0))
    if h.get("방식") == "값":
        return 움직이기(가정, h, v, 시나리오)
    if h.get("방식") == "배율" and 대상 not in ("영구ROIC",):
        return 움직이기(가정, dict(h, 방식="배율"), (v / 지금 - 1) if 지금 else 0.0, 시나리오)
    return 움직이기(가정, dict(h, 방식="가산"), v - 지금, 시나리오)


def 역산둘(가정, 목표주당, h1, v1, h2, 시나리오="기준"):
    """1.1.2 — 두 변수 동시 역산: 손잡이 h1 을 v1 에 놓고(그 범위 안의 값) 같은 가격이 되는 h2 의 값을 푼다 → `역산` 의 결과 사전(「놓은값」 을 더한다)."""
    try:
        a = 놓기값(가정, h1, v1, 시나리오)
    except (ValueError, 가정오류) as e:
        return {"결과": "계산 실패 — %s" % e, "까닭": "계산실패", "놓은값": v1}
    r = 역산(a, 목표주당, 시나리오, h2)
    if isinstance(r, dict):
        r = dict(r, 놓은값=v1)
    return r


def _바꿈(v, 방식, x):
    if 방식 == "값":
        return x
    if 방식 == "배율":
        return None if v is None else _n(v) * (1 + x)
    return None if v is None else _n(v) + x


