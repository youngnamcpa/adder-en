def g짝판(가정, 시나리오="기준", R0=None, 설=None):
    """1.1.3(B3) — 영구성장률과 ERP 출처의 짝. 성숙시장 ERP 가 내재 ERP(끝 성장 = 무위험이자율)이면 g 의 기본 상한은 영구기간 무위험이자율
    (부도 스프레드 차감 후 — 3번 Rf 의 영구 칸)이고, 영구 ROIC > 영구 WACC 인 회사(g 가 값을 움직인다)는 「g = 무위험 근처」(Rf − 근처폭) 판을
    민감도 표준 줄로 싣는다. → {"Rf", "g", "g짝", "근처폭", "영구WACC", "영구ROIC", "필요", "상한넘음", "주당", "기준주당", "변화", "까닭"}.
    값을 바꾸지 않는다 — 판은 사본으로 셈한다."""
    설 = 설 if 설 is not None else _영구짝설정()
    R0 = R0 or 계산(가정, 시나리오)
    요 = R0["요약"]
    rf = _n(((R0.get("WACC") or {}).get("영구기간") or {}).get("Rf"))
    w, roic, g = _n(요.get("영구기간WACC")), _n(요.get("영구ROIC")), _n(요.get("영구성장률"))
    폭 = float(설.get("근처폭") or 0.005)
    out = {"Rf": rf, "g": g, "영구WACC": w, "영구ROIC": roic, "근처폭": 폭, "기준주당": 요.get("주당가치"),
           "끝성장": 설.get("내재ERP끝성장") or "무위험이자율", "확인": 설.get("확인")}
    if not rf:
        out["까닭"] = "영구기간 무위험이자율이 없다(3번 Rf)"
        return out
    out["g짝"] = rf - 폭
    out["필요"] = bool(roic and w and roic > w + 1e-9)
    out["상한넘음"] = bool(g is not None and g > rf + 1e-12)
    out["무위험과의차"] = (rf - g) if g is not None else None
    if w is not None and out["g짝"] >= w:
        out["까닭"] = "무위험 근처 g(%.4f)가 영구 WACC(%.4f) 이상이다 — 판을 셈하지 않는다" % (out["g짝"], w)
        return out
    try:
        a = 놓기값(가정, 손잡이풀기("영구성장률", 가정), out["g짝"], 시나리오, R0)
        주 = 계산(a, 시나리오)["요약"]["주당가치"]
    except (가정오류, ValueError, ZeroDivisionError) as e:
        out["까닭"] = "판 셈 실패 — %s" % e
        return out
    out["주당"] = 주
    b = _n(요.get("주당가치"))
    out["변화"] = ((주 - b) / b) if (b and 주 is not None) else None
    return out


