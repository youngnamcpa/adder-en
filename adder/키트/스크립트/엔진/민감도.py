    측 = 0
    for _ in range(반복):
        if abs(hi - lo) <= 허용 * max(1.0, abs(lo), abs(hi)):
            break
        x = hi - fhi * (hi - lo) / (fhi - flo) if fhi != flo else (lo + hi) / 2
        if not (min(lo, hi) < x < max(lo, hi)):
            x = (lo + hi) / 2
        fx = f(x)
        if fx == 0:
            return x
        if (fx > 0) == (fhi > 0):
            hi, fhi = x, fx
            if 측 == -1:
                flo /= 2
            측 = -1
        else:
            lo, flo = x, fx
            if 측 == 1:
                fhi /= 2
            측 = 1
    return lo if abs(flo) < abs(fhi) else hi


