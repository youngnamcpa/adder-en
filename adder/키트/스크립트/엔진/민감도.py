    if 대상 == "영구이익률가감":
        R = R or 계산(가정, 시나리오)
        return R["요약"]["영구기간영업이익률"]
    if 대상 == "영구ROIC":                          # R1a(K6)
        R = R or 계산(가정, 시나리오)
