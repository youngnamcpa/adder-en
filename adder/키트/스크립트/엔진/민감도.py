def 등가곡선(가정, 목표주당, 시나리오="기준", 축=None, 함께=None, 값들=None):
    """K7 — 등가 곡선: 함께 손잡이를 값마다 두고 축(역산)을 푼다 → [{함께값, 값(내재값) · 결과, 내재영구이익률 …}].
    `역산.등가` {축, 함께, 값} 을 읽는다(인자로 주면 그것). 선언이 없으면 None."""
    d = (가정.get("역산") or {}).get("등가") or {}
    if 축 is None and not d:
        return None
    h축 = 손잡이풀기(축 or d.get("축") or (가정.get("역산") or {}).get("축") or "영구성장률", 가정)
    h함 = 손잡이풀기(함께 or d.get("함께") or "RONIC", 가정)
    h함 = dict(h함, 방식="값")
    if 값들 is None:
        값들 = d.get("값")
    if 값들 is None:
        w = 계산(가정, 시나리오)["요약"]["영구기간WACC"]
        값들 = [w + x for x in RONIC가감]
    줄 = []
    for v in 값들:
        한 = {"함께값": v}
        try:
            a = 움직이기(가정, h함, v, 시나리오)
            r = 역산(a, 목표주당, 시나리오, h축)
        except 가정오류:
            r = None
        if isinstance(r, dict) and r.get("값") is not None:
            한.update({k: r[k] for k in ("값", "가감", "내재영구이익률", "내재영구ROIC", "내재영구매출액", "내재영구영업이익") if k in r})
            비고 = 역산비고(h축, r["값"], 계산(a, 시나리오), r.get("적용값"))
            if 비고:
                한["비고"] = 비고
        else:
            한["결과"] = (r or {}).get("결과") or 해당없음
        줄.append(한)
    return {"축": h축["이름"], "함께": h함["이름"], "목표주당": 목표주당, "줄": 줄}


def _날(글):
    import datetime
    y, m, d = ("%s" % 글)[:10].split("-")
    return datetime.date(int(y), int(m), int(d))


def 굴림(가정, 날짜, 주당=None, 시나리오="기준", R0=None, 배당=None):
    """K7 — 기준일의 주당가치를 날짜로 굴린다: 주당 × (1 + Ke)^(일수 ÷ 365) − Σ 그사이 배당 × (1 + Ke)^((날짜 − 배당일) ÷ 365).
    Ke = 그 시나리오의 예측기간 자기자본비용(3번). 배당 = [{날짜, 주당}](없으면 `역산.배당`) — 기준일 뒤 · 날짜까지(배당락일).
    날짜가 기준일 앞이면(2026-10-26) 그날 뒤 · 기준일까지의 배당을 그날 값으로 할인해 더한다(배당차감이 음수 — 되굴림은 가격에서 그 배당을 뺀 뒤 키운다).
    → {날짜, 일수, Ke, 키움, 배당차감, 굴린주당}"""
    R0 = R0 or 계산(가정, 시나리오)
    기준일 = _날((가정.get("메타") or {}).get("평가기준일"))
    끝 = _날(날짜)
    ke = R0["WACC"]["예측기간"]["Ke"]
    주당 = R0["요약"]["주당가치"] if 주당 is None else 주당
    일수 = (끝 - 기준일).days
    키움 = (1 + ke) ** (일수 / 365.0)
    배당 = 배당 if 배당 is not None else ((가정.get("역산") or {}).get("배당") or [])
    차감 = 0.0
    for d in 배당:
        t = _날(d["날짜"])
        if 기준일 < t <= 끝:
            차감 += _n(d["주당"]) * (1 + ke) ** ((끝 - t).days / 365.0)
        elif 끝 < t <= 기준일:                           # 2026-10-26 — 기준일 앞 날짜(날짜 둘 판의 사이 주가): 그날 뒤 · 기준일까지의 배당은 그날 가격에 들어 있다
            차감 -= _n(d["주당"]) * (1 + ke) ** ((끝 - t).days / 365.0)
    return {"날짜": "%s" % 끝, "일수": 일수, "Ke": ke, "키움": 키움, "배당차감": 차감, "굴린주당": 주당 * 키움 - 차감}


def 되굴림(가정, 날짜, 가격, 시나리오="기준", R0=None, 배당=None):
    """K7 — 날짜의 가격을 기준일 주당가치의 눈금으로 되굴린다(굴림의 역): (가격 + 배당차감) ÷ 키움."""
    g = 굴림(가정, 날짜, 1.0, 시나리오, R0, 배당)
    return (가격 + g["배당차감"]) / g["키움"], g


def 날짜가격(가정, 시나리오="기준", R0=None):
    """K7 — `역산.가격` [{날짜, 종가, 근거}] 마다: 굴린 주당가치 · 가격 ÷ 굴린 값 · 되굴린 목표 · 그 목표의 역산(역산.축 — 선언했을 때) ·
    그 값이 뜻하는 영구기간 영업이익률. 선언이 없으면 []."""
    목록 = (가정.get("역산") or {}).get("가격") or []
    if not 목록:
        return []
    R0 = R0 or 계산(가정, 시나리오)
    낸 = []
    for d in 목록:
        g = 굴림(가정, d["날짜"], None, 시나리오, R0)
        목표, _g = 되굴림(가정, d["날짜"], _n(d["종가"]), 시나리오, R0)
        한 = dict(g, 종가=d["종가"], 근거=d.get("근거"), 비율=_n(d["종가"]) / g["굴린주당"] if g["굴린주당"] else None, 되굴린목표=목표)
        h = 역산축(가정)                          # S9-03 — 선언이 없으면 유형 기본 축(날짜 궤적 · 목표주가 역산이 수렴 회사만이 아니게)
        r = 역산(가정, 목표, 시나리오, h)
        if isinstance(r, dict) and r.get("값") is not None:
            한["역산"] = {k: r[k] for k in ("이름", "값", "가감", "내재영구이익률", "내재영구ROIC", "손잡이값") if k in r}
            비고 = 역산비고(h, r["값"], R0, r.get("적용값"))
            if 비고:
                한["역산"]["비고"] = 비고
        else:
            한["역산"] = {"결과": (r or {}).get("결과") or 해당없음, "까닭": (r or {}).get("까닭")}
        한["역산"]["고정"] = 고정목록(가정, h, 시나리오, R0, 날짜=d["날짜"])
        낸.append(한)
    return 낸


