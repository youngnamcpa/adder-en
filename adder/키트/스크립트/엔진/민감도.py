def 보조덧씌우기(가정, 보조):
    """보조 시나리오 하나 → (바탕 시나리오에 덧을 씌운 가정 사본, 바탕). 덧: 가정 {번호: {열: 값}} · 시점가정 {번호: 값} · 표 {번호: {칸: 값}}."""
    바탕 = 보조.get("바탕") or "기준"
    if 바탕 not in 시나리오목록:
        raise 가정오류("보조 시나리오 「%s」 의 바탕 「%s」 — 비관 · 기준 · 낙관 가운데 하나여야 합니다" % (보조.get("이름"), 바탕))
    a = copy.deepcopy(가정)
    a.pop("보조시나리오", None)
    덧 = 보조.get("덧") or {}
    from .읽개 import 축내기
    축 = 축내기(a)
    for 번호, 열값 in (덧.get("가정") or {}).items():
        번호 = "%s" % 번호
        모름 = [c for c in 열값 if c not in 축.ID]
        if 모름:
            raise 가정오류("보조 시나리오 「%s」 덧.가정.%s — 이 축에 없는 기간 ID %s" % (보조.get("이름"), 번호, " · ".join(모름)))
        벌 = a.setdefault("가정", {}).get(번호)
        if not isinstance(벌, dict):
            벌 = {}
        if 공통키 in 벌 and 바탕 not in 벌:
            벌 = {시: copy.deepcopy(벌[공통키]) for 시 in 시나리오목록}
        a["가정"][번호] = 벌
        한 = 벌.setdefault(바탕, {})
        for c, v in 열값.items():
            if v is None:
                한.pop(c, None)
            else:
                한[c] = v
    for 번호, 값 in (덧.get("시점가정") or {}).items():
        a.setdefault("시점가정", {})
        _시점바꾸기(a, "%s" % 번호, 바탕, lambda v, 값=값: 값)
    for 번호, 칸값 in (덧.get("표") or {}).items():
        번호 = "%s" % 번호
        표 = (a.setdefault("표", {})).get(번호)
        if not isinstance(표, dict):
            표 = {}
        if not (any(k in 표 for k in 시나리오목록) or 공통키 in 표):
            표 = {시: copy.deepcopy(표) for 시 in 시나리오목록}
        elif 공통키 in 표 and 바탕 not in 표:
            표 = {시: copy.deepcopy(표[공통키]) for 시 in 시나리오목록}
        표.setdefault(바탕, {}).update(칸값)
        a["표"][번호] = 표
    return a, 바탕


def 보조계산(가정, 이름):
    """보조 시나리오(이름)의 전 결과 — `계산(덧씌운 가정, 바탕)`."""
    for 보조 in (가정.get("보조시나리오") or []):
        if 보조.get("이름") == 이름:
            a, 바탕 = 보조덧씌우기(가정, 보조)
            return 계산(a, 바탕)
    raise 가정오류("보조 시나리오 「%s」 가 없습니다" % 이름)


def 보조시나리오(가정):
    """K4 — 가정 파일의 보조 시나리오마다 {이름, 바탕, 주당가치, 영업가치, 주주가치, 영구가치비중, 바탕주당가치, 차, 차율, 덧(번호 목록), 근거, 신호}.
    막힌 가정이면 「결과」에 까닭. 선언이 없으면 []."""
    낸 = []
    for 보조 in (가정.get("보조시나리오") or []):
        한 = {"이름": 보조.get("이름"), "바탕": 보조.get("바탕") or "기준", "근거": 보조.get("근거"), "신호": 보조.get("신호"),
             "덧": sorted({"%s.%s" % (블, 번) for 블 in ("가정", "시점가정", "표") for 번 in ((보조.get("덧") or {}).get(블) or {})})}
        try:
            a, 바탕 = 보조덧씌우기(가정, 보조)
            R = 계산(a, 바탕)
            R바탕 = 계산(가정, 바탕)
            q, qb = R["요약"], R바탕["요약"]
            한.update({"주당가치": q["주당가치"], "영업가치": q["영업가치"], "주주가치": q["주주가치"], "영구가치비중": q["영구가치비중"],
                      "예측기간FCFF현가합": q["예측기간FCFF현가합"], "영구가치현가": q["영구가치현가"],
                      "바탕주당가치": qb["주당가치"], "차": q["주당가치"] - qb["주당가치"],
                      "차율": (q["주당가치"] / qb["주당가치"] - 1) if qb["주당가치"] else None})
        except 가정오류 as e:
            한["결과"] = "%s" % e
        낸.append(한)
    return 낸


