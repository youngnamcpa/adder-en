def _축풀기(d, 가정):
    """격자 축 선언 {손잡이 | 이름 · 대상, 값 | 가감, 방식} → (손잡이, [x …])."""
    if "손잡이" in d:
        h = dict(손잡이풀기({"손잡이": d["손잡이"]}, 가정))
        if d.get("이름"):
            h["이름"] = d["이름"]
    else:
        h = {"이름": d["이름"], "대상": d["대상"]}
    if "열" in d:
        h["열"] = d["열"]
    if "값" in d:
        h["방식"] = "값"
        return h, list(d["값"])
    h["방식"] = d.get("방식", "가산")
    return h, list(d.get("가감") or [])


def 채택축(가정, 축, 시나리오="기준", R0=None):
    """1.1.2 — 선언 격자의 축(손잡이, [x …])에 채택값이 없으면 가장 가까운 눈금을 채택값으로 바꾼다(칸 수 그대로 — 격자에 채택값 축 필수).
    값 방식은 지금 적용값, 가산 · 배율은 0 이 채택값이다."""
    h, xs = 축
    xs = list(xs)
    if not xs:
        return 축
    if h.get("방식") == "값":
        try:
            지금 = _n(적용값(가정, h, 시나리오, R0))
        except Exception:                           # noqa: BLE001
            return 축
    else:
        지금 = 0.0
    if 지금 is None or any(isinstance(x, (int, float)) and abs(x - 지금) < 1e-9 * max(1.0, abs(지금)) for x in xs):
        return 축
    i = min(range(len(xs)), key=lambda k: abs(_n(xs[k]) - 지금) if isinstance(xs[k], (int, float)) else float("inf"))
    xs[i] = 지금
    return h, sorted(xs) if all(isinstance(x, (int, float)) for x in xs) else xs


def RONIC눈금(w, 적용):
    """표6 의 가로 눈금 — 영구기간 WACC + RONIC가감. 1.1.2 — 채택 RONIC 이 눈금에 없으면 가장 가까운 칸(둘째 칸 RONIC = WACC 는 남긴다)을
    채택값으로 바꾼다(격자에 채택값 축 필수 — 칸 수는 그대로라 워크북 자리가 그대로다)."""
    눈 = [w + d for d in RONIC가감]
    if isinstance(적용, (int, float)) and not any(abs(x - 적용) < 1e-9 for x in 눈):
        후보 = [i for i in range(len(눈)) if i != 1]
        i = min(후보, key=lambda k: abs(눈[k] - 적용))
        눈[i] = float(적용)
        눈 = sorted(눈)
    return 눈


def RONIC격자(가정, 시나리오="기준", R0=None):
    """K6 — RONIC(영구기간 ROIC) × 영구성장률 격자: 세로 = g + 성장가감, 가로 = RONIC = 영구기간 WACC + RONIC가감(값)."""
    R0 = R0 or 계산(가정, 시나리오)
    w = R0["요약"]["영구기간WACC"]
    h = dict(이름손잡이("RONIC", 가정), 방식="값")
    t = _격자(가정, 시나리오, (손잡이풀기("영구성장률", 가정), 성장가감), (h, RONIC눈금(w, R0["요약"].get("영구ROIC"))), R0)
    t["적용RONIC"] = R0["요약"]["영구ROIC"]
    t["영구기간WACC"] = w
    return t


