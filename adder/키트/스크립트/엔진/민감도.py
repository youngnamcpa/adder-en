def _짧은수(v):
    return ("%.4g" % v) if isinstance(v, float) else ("%s" % v)


def _역산결과(가정, h, 축이름, x, 지금, 목표주당, 시나리오, 고정=None, 놓기=None):
    낸 = {"축": 축이름, "이름": h["이름"], "값": x, "가감": x - 지금, "목표주당": 목표주당, "적용값": 지금, "까닭": None}
    if 고정 is not None:
        낸["고정"] = 고정
    R = None
    try:                                         # R1a(K7) — 그 값이 뜻하는 영구기간 영업이익률 · 영구 ROIC · 영구기간 매출액 · 영업이익
        if 놓기 is not None:
            a = 놓기(x)
        else:
            a = 움직이기(가정, h, x, 시나리오) if (h.get("방식") == "값" and "%s" % h["대상"][0] != "영구이익률가감") \
                else 움직이기(가정, dict(h, 방식="가산"), x - 지금, 시나리오)
        R = 계산(a, 시나리오)
        낸["내재영구이익률"] = R["요약"]["영구기간영업이익률"]
        낸["내재영구ROIC"] = R["요약"]["영구ROIC"]
        낸["내재영구매출액"] = R["2.DCF"]["41"]
        낸["내재영구영업이익"] = R["2.DCF"]["43"]
        낸["내재주당"] = R["요약"]["주당가치"]
        끝 = R["요약"].get("마지막예측열")
        매 = _n(R["4.Sales"]["54"].get(끝)) if 끝 else None
        if 매:
            낸["내재마지막해영업이익률"] = _n(R["6.SG&A"]["22"].get(끝)) / 매
        낸["내재매출CAGR"] = 매출CAGR(R)
    except Exception:                            # noqa: BLE001 — 덧 값이다(역산 값은 그대로 낸다)
        R = None
    대상 = "%s" % h["대상"][0]
    if 대상 in WACC대상:                          # 값 = 그 WACC(첫 대상의 구간). 두 구간을 함께 옮겼으면 다른 구간의 그때 WACC 도 적는다
        R = R or 계산(움직이기(가정, dict(h, 방식="가산"), x - 지금, 시나리오), 시나리오)
        낸["WACC"] = R["요약"]["예측기간WACC"]
        낸["영구기간WACC"] = R["요약"]["영구기간WACC"]
    if 대상 in ("매출성장", "목표마진"):           # S9-03 — 표에 적는 값은 결과(매출 CAGR · 영구기간 영업이익률). 가감(손잡이 값)은 「손잡이값」
        낸["손잡이값"] = x
        기준R = 계산(가정, 시나리오)
        if 대상 == "매출성장":
            낸["값"], 낸["적용값"] = 낸.get("내재매출CAGR"), 매출CAGR(기준R)
        else:                                       # 예측 끝 영업이익률(마지막 예측 열) — 영구이익기준 = 입력(213)이면 영구기간 열은 213 그대로라 끝 해로 읽는다
            낸["값"], 낸["적용값"] = 낸.get("내재마지막해영업이익률"), 마지막해마진(기준R)
        낸["가감"] = (낸["값"] - 낸["적용값"]) if (낸.get("값") is not None and 낸.get("적용값") is not None) else None
    return 낸


# 1.1.4(D) — 비현실 해의 상한(설정 없이 고정 — 뜻 범위 규칙과 같은 자리). 비율 손잡이(원가 줄 비율 · 몫 · 판매량 · 판매단가 증가율)는 절댓값 100% ·
#   그 밖의 선언 손잡이(물량 · 금액 · 배수)는 적용값의 10배. 넘으면 「상한 초과」 — 레터는 표 Ⅳ 에 값과 까닭을 싣고 역산 자 그림에는 그리지 않는다
비율손잡이 = tuple(str(x) for x in (80, 84, 88, 92, 112, 116, 120, 30, 38, 46, 54, 62, 70, 34, 42, 50, 58, 66)) + tuple(str(x) for x in range(711, 778))
상한배수 = 10.0


def 역산비고(h, v, R0, 적용=None):
    """W6c(S4) — 역산 값 v 가 뜻 범위 밖이면 그 까닭(글), 안이면 None. 1번 역산 줄의 값3 · 14번 Ⅳ 비고 · 레터가 그대로 쓴다.
      WACC                  무위험이자율(예측기간 3번 7)보다 낮으면 「무위험이자율 3.68%보다 낮음」
      영구기간 영업이익률    100% 를 넘으면 「100% 초과, 성립 불가」 · −100% 밑이면 「−100% 미만, 성립 불가」(목표마진 손잡이의 내재값도)
      영구성장률            −10% 밑이면 「−10% 미만(영구 축소)」 · **무위험이자율보다 높으면 「영구성장률 상한 초과 — 지금 현금흐름이 정상 상태가
                            아니다」**(S9-05 — 장기 명목 성장은 무위험이자율을 넘지 못한다 · g ≥ 영구기간 WACC 는 엔진이 막는다)
      판매단가 지수(6s6)     0 이하면 「0 이하, 성립 불가」
      매출 CAGR(매출성장)    −50% 밑이나 100% 위면 「성립 불가에 가깝다」"""
    대상 = "%s" % h["대상"][0]
    v = _n(v)
    rf = _n((R0["WACC"].get("예측기간") or {}).get("Rf"))
    if 대상 in WACC대상:
        return "무위험이자율 %.2f%%보다 낮음" % (rf * 100) if v < rf else None
    if 대상 in ("영구이익률가감", "213", "목표마진"):
        if v > 1.0:
            return "100% 초과, 성립 불가"
        return "−100% 미만, 성립 불가" if v < -1.0 else None
    if 대상 == "212":
        if v < -0.10:
            return "−10% 미만(영구 축소)"
        if rf and v > rf:
            return "영구성장률 상한(무위험이자율 %.2f%%) 초과 — 지금 현금흐름이 정상 상태가 아니다" % (rf * 100)
        return None
    if 대상 == "매출성장":
        return "연 −50%% 밑 · 100%% 위 — 성립 불가에 가깝다" if (v < -0.5 or v > 1.0) else None
    if len(대상) == 3 and 대상.startswith("6") and 대상.endswith("6"):
        return "0 이하, 성립 불가" if v <= 0 else None
    if 대상 == "비영업할인":
        return None
    if 대상 in 비율손잡이 and abs(v) > 1.0:
        return "절댓값 100% 초과 — 상한 초과(성립 불가에 가깝다)"
    적 = _n(적용)
    if 적 is not None and abs(적) > 1e-12 and abs(v) > 상한배수 * abs(적):
        return "적용값의 %d배 초과 — 상한 초과(성립 불가에 가깝다)" % int(상한배수)
