def 요약출력(전부):
    L = []
    L.append("%-6s %16s %16s %16s %8s" % ("시나리오", "주당가치", "주주가치", "영업가치", "TV비중"))
    for s in 시나리오목록:
        q = 전부[s]["요약"]
        L.append("%-6s %16.10f %16.2f %16.2f %7.1f%%"
                 % (s, q["주당가치"], q["주주가치"], q["영업가치"], q["영구가치비중"] * 100))
    L.append("단조(비관≤기준≤낙관): %s" % ("OK" if 전부["_대조"]["단조"] else "확인 필요"))
    # **유한책임 표기** — 음수 주당가치는 값이 아니라 신호다. 계산은 그대로 두고
    # (민감도·역산이 원값을 문다), 사람 눈에 닿는 이 줄에서만 0 하한과 잠김 깊이를 병기한다.
    잠긴 = [(s, 전부[s]["요약"]["주당가치"]) for s in 시나리오목록
          if _n(전부[s]["요약"]["주당가치"]) < 0]
    if 잠긴:
        L.append("유한책임 표기 — " + " · ".join(
            "%s 0원 (잠김 %s원)" % (s, "{:,.0f}".format(v)) for s, v in 잠긴)
            + "  ← 음수는 값이 아니라 신호: 창(T2)·구조(마진)·브리지(비영업)를 가르십시오")
    return "\n".join(L)
