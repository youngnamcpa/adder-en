            f후 = _평가안전(후)
            if f후 is None:                                    # 막힘 — 그 너머로 넓히지 않고 그 앞(lo 쪽)으로 반씩 당긴다
                막 = 후
                if abs(막 - lo) <= 1e-10 * max(1.0, abs(lo)):
                    break
                continue
            if flo * f후 <= 0:
                hi, fhi = 후, f후
                break
            lo, flo = 후, f후
            if 끝값 is not None and abs(후 - 끝값) <= 1e-15 * max(1.0, abs(끝값)):
                break
            if 막 is None:
                폭 *= 2
