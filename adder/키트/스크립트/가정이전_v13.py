def 검산(옛결과, 새가정):
    """옮긴 파일을 새 엔진에 돌려 주당가치를 옛 엔진의 값과 견준다 → [(시나리오, 옛, 새, 같은가)]."""
    새엔진 = importlib.import_module("엔진")
    줄 = []
    for 시 in 시나리오목록:
        옛 = 옛결과[시]["요약"]["주당가치"]
        새 = 새엔진.계산(copy.deepcopy(새가정), 시)["요약"]["주당가치"]
        줄.append((시, 옛, 새, abs(새 - 옛) <= 허용오차 * max(1.0, abs(옛))))
    return 줄


def _파일지문(경로):
    import hashlib
    h = hashlib.sha256()
    with open(경로, "rb") as f:
        for 덩이 in iter(lambda: f.read(1 << 20), b""):
            h.update(덩이)
    return h.hexdigest()


