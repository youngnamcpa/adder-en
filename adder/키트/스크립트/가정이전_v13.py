def _새근거(원본, 새):
    """원본의 옛 키에서 새로 세운 208 · 249 · 250 에 근거 네 칸(출처 · 기준일 · 산정 근거 · 비고)을 단다 — 근거가 이미 있으면 두지 않는다."""
    시점 = 새.get("시점가정") if isinstance(새.get("시점가정"), dict) else {}
    for 줄, (블록, 키), 무엇 in 새근거:
        옛 = 원본.get(블록) if isinstance(원본.get(블록), dict) else {}
        if 줄 not in 시점 or _빈칸(옛.get(키)):
            continue
        근거 = 새.get("근거") if isinstance(새.get("근거"), dict) else None
        if 근거 is None:
            근거 = 새["근거"] = {}
        if any(not _빈칸(x) for x in (근거.get(줄) or [])):
            continue
        근거[줄] = ["이전 도구 — 옛 판(v12)의 「%s.%s」에서 옮긴 값" % (블록, 키), None,
                   "%s — 옛 값 그대로다. 출처 · 산정 근거를 다시 적는다" % 무엇, None]


def 구조만이전(가정):
    """기간 부분만 옮긴 v13(구조가 없는 파일) → (구조를 가진 v13, 기록). 이미 구조가 있으면 이전불가."""
    if str(가정.get("스키마버전") or "") != 새버전:
        raise 이전불가("스키마버전이 「%s」 입니다 — 구조 부분만 옮기는 길은 기간 부분을 옮긴 「%s」 파일이 받습니다"
                     % (가정.get("스키마버전") or "없음", 새버전))
    if "구조" in 가정:
        raise 이전불가("이미 구조가 있는 v13 파일입니다 — 옮길 것이 없습니다")
    새, 덧 = 구조이전(가정)
    _새근거(가정, 새)
    기록 = dict(가정.get("이전") or {})
    기록["단계"] = "기간(W2) + 구조(W3b — 기간 부분만 옮긴 v13 에서 구조 부분을 옮겼다)"
    기록.update(덧)
    새["이전"] = 기록
    return 새, 기록


