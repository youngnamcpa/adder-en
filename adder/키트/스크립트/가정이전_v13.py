def _글값(이름, v, 기본):
    """스위치 같은 글 값 — 비면 기본값. 앞뒤에 빈칸이 있으면 멈춘다(다듬어 받지 않는다)."""
    if _빈칸(v):
        return 기본
    if _빈칸붙은글(v):
        raise 이전불가("%s 「%s」 — 글의 앞뒤에 빈칸이 있습니다. 옛 엔진은 글자가 꼭 같을 때만 그 갈래로 계산했습니다. "
                     "빈칸을 지우고 옛 엔진의 값과 같은지 본 뒤에 옮기십시오" % (이름, v))
    return v


def _값있나(벌):
    return not _전부영(벌)


def 구조이전(가정):
    """옛 키를 가진 기간 ID 의 꼴 가정 → (구조를 가진 v13 가정, 기록 덧붙임). 원본은 건드리지 않는다. 못 옮기면 이전불가.

    기록 덧붙임 = {"굳힌목록": […], "걷은키": […], "알림": […]}."""
    if not isinstance(가정, dict):
        raise 이전불가("가정이 객체가 아닙니다")
    살아있는 = 옛경로오류(가정)
    if 살아있는:
        raise 이전불가("옛 경로가 살아 있습니다 — 동결 엔진으로 굳힌 뒤에 옮깁니다:\n      - " + "\n      - ".join(살아있는))
    새 = copy.deepcopy(가정)
    굳힌, 걷은, 알림 = [], [], []
    메타 = 새.get("메타") if isinstance(새.get("메타"), dict) else {}
    S = 새.get("스위치") if isinstance(새.get("스위치"), dict) else {}
    L = 새.get("연장") if isinstance(새.get("연장"), dict) else {}
    A = 새.setdefault("가정", {}) if isinstance(새.get("가정", {}), dict) else {}
    시점 = 새.setdefault("시점가정", {}) if isinstance(새.get("시점가정", {}), dict) else {}
    원천 = 새.get("원천") if isinstance(새.get("원천"), dict) else {}
    기간 = 새.get("기간") if isinstance(새.get("기간"), dict) else {}
    try:
        축 = 기간축(새)
    except 기간축오류 as e:
        raise 이전불가("기간 축을 지을 수 없습니다 — %s" % e)
    예측영구ID = [축.ID[i] for i in 축.예측] + [축.ID[축.영구]]
    구 = {}

    # ── 스위치 — 워크북 칸에서 바꾸는 넷만 남는다
    새스위치 = {}
    if "적용시나리오" in S:
        새스위치["적용시나리오"] = S["적용시나리오"]
    새스위치["현금흐름발생시점"] = _글값("스위치.할인컨벤션", S.get("할인컨벤션"), "기중")
    if 새스위치["현금흐름발생시점"] not in ("기중", "기말"):
        raise 이전불가("스위치.할인컨벤션 「%s」 — 기중 · 기말 가운데 하나여야 합니다" % 새스위치["현금흐름발생시점"])
    새스위치["영구가치할인시점"] = "기말"            # 옛 식 — 영구가치를 최종 예측 열의 기말 현가계수로 할인했다
    if "리스부채포함" in S:
        새스위치["리스부채포함"] = S["리스부채포함"]
    for k, v in S.items():
        if k in 옛스위치키:
            continue
        if k in 옛경로키("스위치"):
            걷은.append("스위치.%s" % k)             # 값이 계산에 닿지 않는 옛 경로의 스위치(위의 판정을 지났다)
        else:
            새스위치[k] = v                          # 모르는 키 — 그대로 둔다(엔진이 경보로 알린다)
    if "최저한세한도율" in S:
        시점[한도율줄] = S["최저한세한도율"]

    # ── 매출 구분 — 실적이나 가정 값이 있는 구분, 이름을 준 구분을 선언한다
    이름표 = {블록: (메타.get(블록) if isinstance(메타.get(블록), dict) else {}) for 블록 in ("스트림이름", "물량이름", "단가이름")}
    구분들 = []
    for s, (원, 물, 단, _금) in enumerate(매출구분, start=1):
        열쇠 = 스트림열쇠[s]
        이름 = {블록: 이름표[블록].get(열쇠) for 블록 in 이름표}
        값있다 = _값있나(원천.get(원)) or _값있나(A.get(물)) or (단 is not None and _값있나(A.get(단)))
        if not 값있다 and all(_빈칸(x) for x in 이름.values()):
            continue
        구분 = {"번호": s}
        for 블록, 새키 in (("스트림이름", "이름"), ("물량이름", "판매량명칭"), ("단가이름", "판매단가명칭")):
            if not _빈칸(이름[블록]):
                구분[새키] = 이름[블록]
        구분["경로"] = "증가율"
        구분들.append(구분)
    if not 구분들:
        구분들.append({"번호": 1, "경로": "증가율"})
    구["매출구분"] = 구분들
    for 블록 in 이름표:
        남는 = {k: v for k, v in 이름표[블록].items() if k not in 스트림열쇠.values()}
        if 남는:
            알림.append("메타.%s 의 %s — 매출 구분의 열쇠가 아니라 옮기지 않았습니다" % (블록, " · ".join("%s" % k for k in 남는)))
        메타.pop(블록, None)

    # ── 원가 줄 — 옛 워크북의 원가 줄 일곱을 다 선언한다(옛 판은 값이 0 인 줄도 섰다 — 엔진 · 워크북의 줄이 그대로 남게. W5f).
    #    줄 4 · 5 · 7 의 옛 경로(물가형 · 비율형)는 `옛식 = 예` 로 옛 식을 그대로 쓴다(설계서 8-1 의 기준 금액 환산은 W7 로 미룬다).
    #    줄 5 의 비율형은 열마다 그 열의 비율이라 새 식(매출액비율)과 같다 — 옛식을 달지 않는다
    원가이름 = 메타.get("원가이름") if isinstance(메타.get("원가이름"), dict) else {}
    쓴열쇠 = set()
    줄들 = []
    for k in range(1, 8):
        이름 = next((원가이름[x] for x in 원가열쇠[k] if not _빈칸(원가이름.get(x))), None)
        쓴열쇠.update(원가열쇠[k])
        경로 = None
        if k in 원가경로스위치:
            경로 = _글값("스위치.%s" % 원가경로스위치[k], S.get(원가경로스위치[k]), "물가형")
            if 경로 not in 경로산식:
                raise 이전불가("스위치.%s 「%s」 — 물가형 · 비율형 가운데 하나여야 합니다(명목상한형은 옮기지 않습니다)"
                             % (원가경로스위치[k], 경로))
        줄 = {"번호": k}
        if 이름 is not None:
            줄["이름"] = 이름
        줄["시트"] = 5 if k <= 4 else 6
        줄["산식"] = 경로산식[경로] if 경로 is not None else "매출액비율"
        if k in 원가가격지수:
            줄["가격지수"] = 원가가격지수[k]
        if 경로 == "물가형" or (경로 == "비율형" and k != 5):
            줄["옛식"] = "예"
        줄들.append(줄)
    구["원가줄"] = 줄들
    남는 = [k for k in 원가이름 if k not in 쓴열쇠 and not ("%s" % k).startswith(("_", "("))]
    if 남는:
        알림.append("메타.원가이름 의 %s — 원가 줄의 열쇠가 아니라 옮기지 않았습니다" % " · ".join("%s" % k for k in 남는))
    메타.pop("원가이름", None)

    # ── 인건비 · 투자 · 법인세 · 영구가치 · 할인 — 옛 식이 곧 이 선언이다
    인건비시트 = _글값("스위치.인건비시트", S.get("인건비시트"), "사용")
    구["인건비"] = {"산정방식": "미분리" if 인건비시트 == "미사용" else "인원", "인원경로": "수준"}
    구["투자"] = {"유지규칙": "직접", "상각방식": "상각률", "무형상각": "상각률"}
    결손 = _글값("스위치.결손금처리", S.get("결손금처리"), "세율수렴")
    if 결손 not in 결손금처리새값:
        raise 이전불가("스위치.결손금처리 「%s」 — %s 가운데 하나여야 합니다" % (결손, " · ".join(결손금처리새값)))
    구["법인세"] = {"세액공제이월": "아니오", "무형공제": "예", "결손금처리": 결손금처리새값[결손]}
    구["영구가치"] = {"영구이익기준": "입력"}
    W = 새.get("WACC") if isinstance(새.get("WACC"), dict) else {}
    로드맵 = _글값("연장.WACC로드맵", L.get("WACC로드맵"), "미사용")
    구["할인"] = {"영구WACC": "예측과같음" if W.get("예측기간") == W.get("영구기간") else "따로",
               "연도별WACC": "사용" if 로드맵 == "사용" else "미사용"}

    # ── 한시적 현금흐름 — 구조에 선언, 금액은 가정 395 · 404 · 413, 예측기간 밖 잔여액은 표 399 · 408 · 417
    유한 = [x for x in (새.get("유한현금흐름") or []) if isinstance(x, dict)] if isinstance(새.get("유한현금흐름"), list) else []
    if len(유한) > 한시적최대:
        raise 이전불가("유한현금흐름이 %d개입니다 — 한시적 현금흐름은 셋까지 받습니다" % len(유한))
    물량줄구분 = {}
    for s, (_원, 물, 단, _금) in enumerate(매출구분, start=1):
        물량줄구분[물] = s
        if 단 is not None:
            물량줄구분[단] = s
    흐름들 = []
    근거 = 새.get("근거") if isinstance(새.get("근거"), dict) else None
    for k, f in enumerate(유한, start=1):
        b = 394 + (k - 1) * 9
        금액줄, 잔여줄 = str(b + 1), str(b + 5)
        병합 = ("%s" % (f.get("병합행") or "")).strip()
        if 병합 and 병합 not in 물량줄구분:
            raise 이전불가("유한현금흐름[%d].병합행 「%s」 — 매출 구분의 판매량 · 판매단가 가정 번호(%s)가 아닙니다"
                         % (k - 1, 병합, " · ".join(sorted(물량줄구분, key=int))))
        세후 = f.get("세후", True)
        흐름 = {"번호": k}
        if not _빈칸(f.get("이름")):
            흐름["이름"] = f.get("이름")
        흐름["손익반영"] = 물량줄구분[병합] if 병합 else "없음"
        흐름["세후"] = "아니오" if (세후 is False or str(세후) in ("아니오", "false", "False")) else "예"
        for 덧 in ("태그", "제약"):
            if not _빈칸(f.get(덧)):
                흐름[덧] = f.get(덧)
        흐름들.append(흐름)
        금액 = f.get("금액") if isinstance(f.get("금액"), dict) else {}
        A[금액줄] = {시: (금액.get(시) if isinstance(금액.get(시), dict) else {}) for 시 in 시나리오목록}
        잔여 = f.get("잔여") if isinstance(f.get("잔여"), dict) else {}
        if any(잔여.get(시) for 시 in 시나리오목록):
            새.setdefault("표", {})[잔여줄] = {
                시: dict(zip(잔여칸, (list(잔여.get(시) or []) + [None] * 3)[:3])) for 시 in 시나리오목록}
        if f.get("근거"):
            if 근거 is None:
                근거 = 새["근거"] = {}
            근거.setdefault(금액줄, list(f.get("근거")))
            근거.setdefault(잔여줄, list(f.get("근거")))
        모르는 = [x for x in f if x not in 옛유한키 and not ("%s" % x).startswith(("_", "("))]
        if 모르는:
            알림.append("유한현금흐름[%d] 의 %s — 옮길 자리가 없어 걷었습니다" % (k - 1, " · ".join(모르는)))
    if 흐름들:
        구["한시적현금흐름"] = 흐름들
    새.pop("유한현금흐름", None)

    # ── 연장 — 사유는 기간으로, 연도별 WACC 는 구조로, 연장 여부는 기간에서 나온다
    if not _빈칸(L.get("트리거")):
        기간["연장사유"] = L.get("트리거")
    if not _빈칸(L.get("근거자료")):
        if 근거 is None:
            근거 = 새["근거"] = {}
        넷 = (list(근거.get(연장사유줄) or []) + [None] * 4)[:4]
        넷[2] = L.get("근거자료") if _빈칸(넷[2]) else "%s / %s" % (넷[2], L.get("근거자료"))
        근거[연장사유줄] = 넷
    for 키, 줄 in (("연장전주당가치", 연장전줄), ("연장후주당가치", 연장후줄)):
        if not _빈칸(L.get(키)):
            시점[줄] = L.get(키)
    난연장 = "연장" if (축.상세추정연수 + 축.수렴연수) > 5 else "미연장"
    if not _빈칸(L.get("연장여부")) and L.get("연장여부") != 난연장:
        알림.append("연장.연장여부 「%s」 — 기간(상세 %d년 + 수렴 %d년)에서 나오는 값은 「%s」 입니다. 연장 여부는 이제 기간이 정합니다"
                  % (L.get("연장여부"), 축.상세추정연수, 축.수렴연수, 난연장))
    for k in L:
        if k in 옛연장키 or k == "둔화층시작열":
            continue
        걷은.append("연장.%s" % k)                   # 옛 경로의 줄(252 · 256 · 완공리드타임) — 값이 계산에 닿지 않는다
    새.pop("연장", None)

    # ── 수식덮기(D11) — 제안값 수식을 두지 않는다. 덮던 칸에는 가정 값이 그대로 들어가고, 빈칸은 옛 엔진이 쓰던 값을 적는다
    if "수식덮기" in 새:
        걷은.append("수식덮기")
        새.pop("수식덮기", None)
    한계세율 = (W.get("예측기간") or {}).get("한계세율") if isinstance(W.get("예측기간"), dict) else None
    for 번호, 채울 in (("190", 0.0), ("196", 한계세율)):
        벌 = A.get(번호)
        if not isinstance(벌, dict):
            벌 = A[번호] = {}
        for 시 in 시나리오목록:
            if not isinstance(벌.get(시), dict):
                벌[시] = {}
            for c in 예측영구ID:
                if _빈칸(벌[시].get(c)) and 채울 is not None:
                    벌[시][c] = 채울
                    굳힌.append({"번호": 번호, "시나리오": 시, "기간": c, "값": 채울, "규칙": 제안값줄[번호]})

    # ── 값이 계산에 닿지 않는 옛 경로의 키와 그 줄에 달린 글
    for k in 옛경로키("최상위"):
        if k in 새:
            걷은.append(k)
            새.pop(k)
    for k in 옛경로키("가정"):
        if k in A:
            걷은.append("가정.%s" % k)
            A.pop(k)
    for 블록 in ("근거", "방향선언", "행이름", "독자근거"):
        d = 새.get(블록)
        if isinstance(d, dict):
            for r in [r for r in d if 옛경로줄인가(r)]:
                걷은.append("%s.%s" % (블록, r))
                d.pop(r)
    사유 = 새.get("사유")
    if isinstance(사유, dict):
        for 자리 in [x for x in 사유 if x not in 사유자리 and not ("%s" % x).startswith(("_", "("))]:
            글 = 사유.pop(자리)
            걷은.append({"사유": 자리, "글": 글, "까닭": "워크북에 그 사유 칸이 없다(옛 배치의 자리)"})
    스위치사유 = 새.get("스위치사유")
    if isinstance(스위치사유, dict) and "인건비시트" in 스위치사유:
        스위치사유["인건비산정방식"] = 스위치사유.pop("인건비시트")

    새["스위치"] = 새스위치
    새["구조"] = 구
    새["스키마버전"] = 새버전
    return 새, {"굳힌목록": 굳힌, "걷은키": 걷은, "알림": 알림}


# ────────────────────────────────────────────────────────────── 1. 열

def 축읽기(가정):
    """옛 꼴의 `기간` 과 평가기준일 → (축, 대응, 옛길이).

    대응 = {옛 자리(0~14): 기간 ID}. 쓰지 않는 옛 열은 대응에 없다. 옮길 수 없으면 이전불가."""
    메타, 기간 = 가정.get("메타") or {}, 가정.get("기간") or {}
    if _빈칸(메타.get("평가기준일")):
        raise 이전불가("메타.평가기준일 이 없습니다")
    if not isinstance(기간.get("종료일"), list):
        raise 이전불가("기간.종료일 이 15칸 배열이 아닙니다 — 옛 꼴(v12)의 파일이 아닙니다")
    if 기간.get("영구기간길이", 1) not in (None, 1, 1.0):
        raise 이전불가("기간.영구기간길이 가 %s 입니다 — 새 판의 영구기간 열은 12개월 고정입니다" % 기간.get("영구기간길이"))
    기준 = 날짜(메타["평가기준일"])
    종 = _열다섯(기간["종료일"])
    if any(_빈칸(x) for x in 종[:옛실적수]):
        raise 이전불가("실적 열(D·E·F)의 종료일이 비었습니다: %s" % 종[:옛실적수])
    D끝, E끝, F끝 = (날짜(x) for x in 종[:옛실적수])
    if F끝 != 기준:
        raise 이전불가("마지막 실적 열(F)의 종료일 %s 이 평가기준일 %s 과 다릅니다 — 기준일 열에는 평가기준일의 값이 와야 합니다"
                     % (F끝, 기준))
    하루 = timedelta(days=1)
    F개월 = 개월수(E끝 + 하루, F끝)
    if F개월 > 12:
        raise 이전불가(
            "평가기준일 열(F)의 길이가 1년을 넘습니다(%s ~ %s, %s개월). 셋째 실적 열에 회계연도 금액을 넣고 "
            "종료일만 평가기준일로 둔 파일입니다 — 자동으로 옮기지 않습니다. 직전 회계연도 열과 평가기준일까지의 "
            "누계 열을 따로 세워 가정을 다시 조립하십시오(설계/5_기간열_결함.md 1절)" % (E끝 + 하루, F끝, F개월))
    기말평가 = (F개월 == 12)
    결산 = F끝 if 기말평가 else E끝
    if (결산 + 하루).day != 1:
        raise 이전불가("회계연도 말 %s 이 월말이 아닙니다" % 결산)
    쓰는 = [i for i in 옛예측자리 if not _빈칸(종[i])]
    if not 쓰는:
        raise 이전불가("예측 열(G~Q)의 종료일이 전부 비었습니다")
    if 쓰는 != list(range(3, 3 + len(쓰는))):
        raise 이전불가("예측 열 사이에 빈 열이 있습니다 — 쓰는 열: %s" % " · ".join(옛열이름[i] for i in 쓰는))
    연장 = 가정.get("연장") or {}
    둔화시작 = int(_n(연장.get("둔화층시작열", 7)) or 7)
    수렴 = max(0, len(쓰는) - (둔화시작 - 1))
    연간수 = len(쓰는) - (0 if 기말평가 else 1)
    try:
        축 = 기간축.만들기(기준.isoformat(), 결산월=결산.month, 실적연도수=3 if 기말평가 else 2,
                         상세추정연수=연간수 - 수렴, 수렴연수=수렴)
    except 기간축오류 as e:
        raise 이전불가("새 축을 지을 수 없습니다 — %s (쓰는 예측 열 %d개 · 둔화층시작열 %d)" % (e, len(쓰는), 둔화시작))
    대응 = {}
    for k, i in enumerate(축.실적):
        대응[k] = 축.ID[i]
    for k, i in enumerate(축.예측):
        대응[3 + k] = 축.ID[i]
    대응[옛영구자리] = 축.ID[축.영구]
    # 옛 종료일이 새 축의 종료일과 같아야 한다 — 다르면 열의 뜻이 다르다
    for 자리, ID in 대응.items():
        c = 축.열[축.위치(ID)]
        if c.종료일 is None:
            continue
        if 날짜(종[자리]) != c.종료일:
            raise 이전불가("%s열의 종료일 %s 이 회계연도 경계(%s 열 %s)와 다릅니다 — 결산월 %d월로 읽었습니다"
                         % (옛열이름[자리], 종[자리], ID, c.종료일, 축.결산월))
    return 축, 대응


# ────────────────────────────────────────────────────────────── 2. 값

def _옮기기(배열, 대응, 받는, 자리이름, 버린값):
    """15칸(원천은 3칸) 배열 → {기간 ID: 값}. 받는 = 값을 싣는 옛 자리들. 그 밖의 자리에 값이 있으면 버린값에 적는다."""
    v = _열다섯(배열)
    for i in range(옛열수):
        if i not in 받는 and not _빈칸(v[i]) and _n(v[i]) != 0:
            버린값.append({"자리": "%s[%s]" % (자리이름, 옛열이름[i]), "값": v[i],
                          "까닭": "쓰지 않는 열" if i not in 대응 else "그 열의 값은 읽지 않는다"})
    return {대응[i]: v[i] for i in 받는}


def 살피기(가정):
    """옮길 수 있는 파일인가 — 옛 엔진을 돌리기 전에 본다 → (축, 대응). 못 옮기면 까닭을 전부 담아 이전불가."""
    받은 = str(가정.get("스키마버전") or "")
    if 받은 != 원본버전:
        raise 이전불가("스키마버전이 「%s」 입니다 — 이 도구는 「%s」 를 「%s」 로 옮깁니다" % (받은 or "없음", 원본버전, 새버전))
    까닭, 축, 대응 = [], None, None
    try:
        축, 대응 = 축읽기(가정)
    except 이전불가 as e:
        까닭.append("%s" % e)
    살아있는 = 옛경로오류(가정)
    if 살아있는:
        까닭.append("옛 경로가 살아 있습니다 — 동결 엔진으로 굳힌 뒤에 옮깁니다:\n      - "
                  + "\n      - ".join(살아있는))
    if 까닭:
        raise 이전불가(까닭[0] if len(까닭) == 1 else "까닭 %d가지\n    · %s" % (len(까닭), "\n    · ".join(까닭)))
    return 축, 대응


def 이전(가정, 옛엔진=None, 옛결과=None):
    """옛 꼴 가정(사전) → (새 꼴 가정, 기록). 원본은 건드리지 않는다. 옮길 수 없으면 이전불가.

    옛엔진 = 동결 엔진 모듈(`보관/dcf엔진_v12.py`). 증가율 환산에 옛 엔진의 기간 금액이 필요하다."""
    축, 대응 = 살피기(가정)
    옛엔진 = 옛엔진 or 엔진불러오기(동결엔진경로, "dcf엔진_v12_이전용")
    옛결과 = 옛결과 or {시: 옛엔진.계산(copy.deepcopy(가정), 시) for 시 in 시나리오목록}
    길이 = 옛결과["기준"]["기간"]["길이"]
    쓰는예측 = [i for i in 옛예측자리 if i in 대응]
    실적자리 = [0, 1, 2]
    예측영구 = 쓰는예측 + [옛영구자리]
    새 = copy.deepcopy(가정)
    버린값, 환산 = [], []

    # ── 기간
    옛기간 = 가정.get("기간") or {}
    새["기간"] = {"결산월": 축.결산월, "실적연도수": 축.실적연도수,
                 "상세추정연수": 축.상세추정연수, "수렴연수": 축.수렴연수}
    옛라벨 = {대응[i]: x for i, x in enumerate(_열다섯(옛기간.get("라벨"))) if i in 대응 and not _빈칸(x)}

    # ── 원천 (실적 열)
    for r, v in (가정.get("원천") or {}).items():
        if isinstance(v, list):
            새["원천"][r] = _옮기기(v, 대응, 실적자리, "원천.%s" % r, 버린값)

    # ── 가정 · 연장의 번호 줄 (예측 열과 TV)
    def 줄옮기기(블록이름):
        for r, 벌 in (가정.get(블록이름) or {}).items():
            if not (str(r).isdigit() and isinstance(벌, dict)):
                continue
            for 시, v in 벌.items():
                if isinstance(v, list):
                    새[블록이름][r][시] = _옮기기(v, 대응, 예측영구, "%s.%s.%s" % (블록이름, r, 시), 버린값)
    줄옮기기("가정")
    줄옮기기("연장")
    if isinstance(새.get("연장"), dict):
        새["연장"].pop("둔화층시작열", None)          # → 기간.수렴연수

    # ── 한시적 현금흐름의 금액 (예측 열)
    for 번, f in enumerate(가정.get("유한현금흐름") or []):
        if not isinstance(f, dict):
            continue
        for 시, v in (f.get("금액") or {}).items():
            if isinstance(v, list):
                새["유한현금흐름"][번]["금액"][시] = _옮기기(v, 대응, 쓰는예측, "유한현금흐름[%d].금액.%s" % (번, 시), 버린값)

    # ── 증가율 환산 — 누계 열이 있을 때만(잔여 기간 열과 그 다음 열)
    if 축.잔여 is not None:
        G, H = 3, 4
        잔ID, 다음ID = 대응[G], 대응[H]
        원천 = 가정.get("원천") or {}
        for 시 in 시나리오목록:
            매출 = 옛결과[시]["4.Sales"]
            for 원, 물, 단, 금줄 in 매출구분:
                src = _열다섯(원천.get(원))
                FY, 누계 = _n(src[1]), _n(src[2])
                금G, 금H = _n(매출[금줄][G]), _n(매출[금줄][H])
                연간 = 누계 + 금G
                물벌, 단벌 = 새["가정"].get(물), (새["가정"].get(단) if 단 else None)
                if FY == 0:
                    if 연간 != 0 or 금H != 0:
                        raise 이전불가("원천 %s — 직전 회계연도 실적이 0 인데 누계 실적 · 예측 매출이 있습니다(%s). "
                                     "전년 대비 증가율로 적을 수 없습니다" % (원, 시))
                    continue
                if 연간 == 0:
                    raise 이전불가("원천 %s — 누계 실적 + 잔여 기간 매출이 0 입니다(%s). 다음 해의 전년 대비를 낼 수 없습니다" % (원, 시))
                if not isinstance(물벌, dict) or not isinstance(물벌.get(시), dict):
                    raise 이전불가("가정.%s.%s 이 없습니다 — 원천 %s 의 예측 매출이 있는데 판매량 증가율 줄이 없습니다" % (물, 시, 원))
                for ID, 자리, 결합 in ((잔ID, G, 연간 / FY), (다음ID, H, 금H / 연간)):
                    p = _n(단벌[시].get(ID)) if isinstance(단벌, dict) and isinstance(단벌.get(시), dict) else 0.0
                    if 1 + p == 0:
                        raise 이전불가("가정.%s.%s 의 %s 이 −100%% 입니다 — 판매량 증가율로 되풀 수 없습니다" % (단, 시, ID))
                    옛값 = 물벌[시].get(ID)
                    새값 = 결합 / (1 + p) - 1
                    물벌[시][ID] = 새값
                    환산.append({"번호": 물, "시나리오": 시, "기간": ID, "옛": 옛값, "새": 새값,
                               "규칙": ("전년 대비 — (누계 실적 + 잔여 기간 금액) ÷ 직전 회계연도 실적 ÷ (1 + 판매단가 증가율) − 1"
                                       if 자리 == G else
                                       "전년 대비 — 그 열의 금액 ÷ (누계 실적 + 잔여 기간 금액) ÷ (1 + 판매단가 증가율) − 1")})
            # 지수 · 물가 — 열 사이 거리를 지수로 쓰던 것을 연 단위로
            for r in 지수가정:
                벌 = 새["가정"].get(r)
                if not isinstance(벌, dict) or not isinstance(벌.get(시), dict):
                    continue
                for i in 쓰는예측[1:]:
                    승 = (_n(길이[i - 1]) + _n(길이[i])) / 2
                    옛값 = 벌[시].get(대응[i])
                    if 승 == 1 or _빈칸(옛값):
                        continue
                    if 1 + _n(옛값) < 0:
                        raise 이전불가("가정.%s.%s 의 %s 이 −100%% 아래입니다 — 환산할 수 없습니다" % (r, 시, 대응[i]))
                    새값 = (1 + _n(옛값)) ** 승 - 1
                    if 새값 == _n(옛값):
                        continue                              # 0% 는 그대로 0% 다
                    벌[시][대응[i]] = 새값
                    환산.append({"번호": r, "시나리오": 시, "기간": 대응[i], "옛": 옛값, "새": 새값,
                               "규칙": "연 단위 누적 — (1 + 옛 율)^%s − 1 (옛 식의 지수 = (앞 길이 + 이 길이) ÷ 2)" % ("%g" % 승)})

    새["스키마버전"] = 새버전
    기록 = {"원본버전": 원본버전,
           "단계": "기간(열을 기간 ID 로 · 증가율을 전년 대비로 — W2) + 구조(옛 스위치 · 연장 · 유한현금흐름 · 수식덮기를 구조와 새 자리로 — W3b)",
           "도구": "스크립트/가정이전_v13.py",
           "축": list(축.ID), "옛열": {옛열이름[i]: ID for i, ID in sorted(대응.items())},
           "옛라벨": 옛라벨, "환산목록": 환산, "버린값": 버린값}
    # ── 구조 부분 — 옛 스위치 · 연장 · 유한현금흐름 · 메타의 이름 · 수식덮기를 구조와 새 자리로
    새, 덧 = 구조이전(새)
    _새근거(가정, 새)
    기록.update(덧)
    새["이전"] = 기록
    return 새, 기록


