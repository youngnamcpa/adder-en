def 단위배(메타):
    """`메타.금액단위` 를 곱수로(백만원 → 1e6). 모델 금액은 이 단위로 적혀 있다."""
    글 = ("%s" % ((메타 or {}).get("금액단위") or "")).strip()
    for 말, 곱 in (("십억", 1e9), ("백만", 1e6), ("억", 1e8), ("천", 1e3), ("만", 1e4)):
        if 글.startswith(말):
            return 곱
    return 1.0


def 통화(메타):
    return ("%s" % ((메타 or {}).get("표시통화") or "KRW")).upper()


def 통화말(메타):
    t = 통화(메타)
    return _통화말.get(t, t)


def _음(글, v):
    return ("−" + 글) if v < 0 else 글


def 금액글(x, 메타):
    """모델 금액(금액 단위) → 읽는 단위. 원은 조 · 억, 그 밖의 통화는 억 · 만."""
    v = _n(x)
    if v is None:
        return "—"
    v = v * 단위배(메타)
    a = abs(v)
    if 통화(메타) == "KRW":
        if a >= 1e12:
            글 = "%s조 원" % "{:,.2f}".format(a / 1e12)
        elif a >= 1e10:
            글 = "%s억 원" % "{:,.0f}".format(a / 1e8)
        elif a >= 1e9:
            글 = "%s억 원" % "{:,.1f}".format(a / 1e8)
        elif a >= 1e8:
            글 = "%s억 원" % "{:,.2f}".format(a / 1e8)
        elif a >= 1e4:
            글 = "%s만 원" % "{:,.0f}".format(a / 1e4)
        else:
            글 = "%s원" % "{:,.0f}".format(a)
    else:
        말 = 통화말(메타)
        if a >= 1e10:
            글 = "%s억 %s" % ("{:,.0f}".format(a / 1e8), 말)
        elif a >= 1e8:
            글 = "%s억 %s" % ("{:,.1f}".format(a / 1e8), 말)
        elif a >= 1e4:
            글 = "%s만 %s" % ("{:,.0f}".format(a / 1e4), 말)
        else:
            글 = "%s%s" % ("{:,.0f}".format(a), 말)
    return _음(글, v if abs(v) >= 0.5 else 0.0)


def 주당글(x, 메타):
    v = _n(x)
    if v is None:
        return "—"
    단위 = ("%s" % ((메타 or {}).get("주당단위") or "")).strip() or 통화말(메타)
    if 단위 in ("원", "엔"):
        return _음("{:,.0f}{}".format(abs(v), 단위), v if abs(v) >= 0.5 else 0.0)
    if 단위.upper() in _통화말:
        단위 = _통화말[단위.upper()]
    return _음("{:,.2f}{}".format(abs(v), 단위), v if abs(v) >= 0.005 else 0.0)


def _유효(a, 자리):
    """a 를 유효숫자 자리 개로 반올림(0 이면 0)."""
    if not a:
        return 0.0
    k = 자리 - 1 - int(math.floor(math.log10(abs(a))))
    return round(a, k)


def 어림주당글(x, 메타):
    """독자 층의 주당가치(R1b · L16) — 원 · 엔: 10만 이상은 만 단위(「130만 원」), 1만~10만은 0.1만 단위(「3.3만 원」), 그 아래는
    유효숫자 둘(「2,500원」). 그 밖의 통화는 유효숫자 셋(「30.4달러」). 깊이 층(본편)은 원 단위 「주당」 꼴을 쓴다."""
