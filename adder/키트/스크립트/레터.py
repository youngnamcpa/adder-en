    for n, 줄 in enumerate(글.split("\n"), 1):
        t = 줄.strip()
        if t.startswith("```"):
            코드 = not 코드
            continue
        if 코드 or not t:
            continue
        for 패, 이름 in 번호식이름:
            m = re.search(패, t)
