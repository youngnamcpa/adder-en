def 가격성립찾기(경로, 지정=None):
    """회차 폴더의 가격 성립 입력 — 없으면 None."""
    p = 지정 or (os.path.join(회차폴더(경로), 가격성립파일) if 경로 else None)
    if not p or not os.path.isfile(p):
        if 지정:
            raise 레터오류("가격 성립 입력 파일이 없습니다: %s" % 지정)
        return None
    try:
        d = _읽기(p)
    except Exception as e:                                   # noqa: BLE001
        raise 레터오류("가격 성립 입력 파일을 못 읽었습니다(%s): %s" % (e, p))
    if not isinstance(d, dict):
        raise 레터오류("가격 성립 입력 파일의 최상위가 객체가 아닙니다: %s" % p)
    for 칸 in ("증설", "조합"):
        if 칸 in d and not isinstance(d[칸], list):
            raise 레터오류("가격 성립 입력 「%s」 는 목록으로 적습니다" % 칸)
        for i, x in enumerate(d.get(칸) or []):
            if not isinstance(x, dict) or not ("%s" % (x.get("이름") or "")).strip():
                raise 레터오류("가격 성립 입력 「%s[%d]」 에 이름이 없습니다" % (칸, i))
    return d


def _자리풀기(a, 자리):
    """「가정.678」 · 「구조.매출구분[번호=1].라인」 → (부모 객체, 마지막 열쇠). 중간 사전은 만든다."""
    부 = [x for x in re.split(r"\.(?![^\[]*\])", 자리) if x]
    if not 부:
        raise 레터오류("덧씌우기 자리가 비었습니다")
    cur = a
    for i, 조각 in enumerate(부):
        끝 = i == len(부) - 1
        m = re.match(r"^([^\[]+)\[([^=\]]+)=([^\]]+)\]$", 조각)
        if m:
            목록 = cur.get(m.group(1)) if isinstance(cur, dict) else None
            if not isinstance(목록, list):
                raise 레터오류("덧씌우기 자리 「%s」 — %s 가 목록이 아닙니다" % (자리, m.group(1)))
            고른 = [x for x in 목록 if isinstance(x, dict) and ("%s" % x.get(m.group(2))) == m.group(3)]
            if len(고른) != 1 or 끝:
                raise 레터오류("덧씌우기 자리 「%s」 — %s 로 고른 원소가 하나가 아니거나 자리가 원소에서 끝납니다" % (자리, 조각))
            cur = 고른[0]
            continue
        if not isinstance(cur, dict):
            raise 레터오류("덧씌우기 자리 「%s」 — %s 앞이 사전이 아닙니다" % (자리, 조각))
        if 끝:
            return cur, 조각
        cur = cur.setdefault(조각, {})
    raise 레터오류("덧씌우기 자리를 못 풀었습니다: %s" % 자리)


def 덧씌우기(가정, 고침들):
    """가정 JSON 에 고침을 얹은 사본 — 스키마 검증 오류가 있으면 레터오류(입력의 꼴 — rc 2)."""
    a = copy.deepcopy(가정)
    for x in 고침들 or []:
        if not isinstance(x, dict) or not x.get("자리") or not (("값" in x) ^ ("더하기" in x)):
            raise 레터오류("덧씌우기 고침은 {\"자리\", \"값\"} 이나 {\"자리\", \"더하기\"} 로 적습니다: %s" % json.dumps(x, ensure_ascii=False)[:120])
        부모, 열쇠 = _자리풀기(a, "%s" % x["자리"])
        if "더하기" in x:
            목록 = 부모.setdefault(열쇠, [])
            if not isinstance(목록, list):
                raise 레터오류("덧씌우기 「더하기」 자리가 목록이 아닙니다: %s" % x["자리"])
            목록.append(copy.deepcopy(x["더하기"]))
        else:
            부모[열쇠] = copy.deepcopy(x["값"])
    if 고침들:
        오류, _경보, _구, _축 = _스키마.검증전부(a)
        if 오류:
            raise 레터오류("덧씌운 가정이 스키마 검증에 걸립니다 — %s" % " · ".join(오류[:3]))
    return a


