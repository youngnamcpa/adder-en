    if 끝 == "%":
        return 받침없음
    if 끝 in _숫자받침:
        if 끝 in "178" and ("%s" % 받침있음).startswith("으로"):     # ㄹ 받침 + 으로 → 로(레터1부._조 와 같은 규칙)
            return 받침없음
        return 받침있음 if _숫자받침[끝] else 받침없음
    if 끝.isalpha() and 끝.upper() in "ABCDEFGHIJKLMNOPQRSTUVWXYZ":
        표받침 = 용어.받침(글)                                  # 용어표의 영어 용어 — 읽는 소리의 받침(L2)
        if 표받침 == "미정":                                   # 읽는 소리가 정해지지 않은 말(WACC) — 「값」 을 넣어 조사가 바로 붙지 않게
            return " 값" + ("%s" % 받침있음)
        if 표받침 is not None:
            return 용어.조사고르기(표받침, "%s" % 받침있음, "%s" % 받침없음)
        단받침 = 용어.영단어받침(글)                             # 1.1.10 — 소문자가 섞인 영문 낱말은 읽는 소리로(iPhone은)
        if 단받침 is not None:
            return 용어.조사고르기(단받침, "%s" % 받침있음, "%s" % 받침없음)
