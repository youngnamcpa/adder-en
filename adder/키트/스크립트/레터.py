def 열이름(속성, 열, 영구열=None):
    """기간 ID → 표의 열 이름(R1b · L4). 연간은 「2027(추정)」 · 「2025(실적)」, 반기는 「2026 하반기(추정)」, 영구기간은 「2032년~」."""
    속 = 속성.get(열, {}) if isinstance(속성, dict) else {}
    년 = 속.get("회계연도")
    if not 년:
        return ("%s" % (속.get("표기") or 열))
    if 열 == 영구열 or 속.get("종류") == "영구":
        return "%d년~" % int(년)
    말 = "실적" if 속.get("구분") == "실적" else "추정"
    개월 = 속.get("개월") or 12
    if 개월 == 12:
        return "%d(%s)" % (int(년), 말)
    시작 = "%s" % (속.get("시작일") or "")
    월 = int(시작[5:7]) if re.match(r"^\d{4}-\d{2}", 시작) else None
    if 개월 == 6 and 월 in (1, 7):
        return "%d %s(%s)" % (int(년), "상반기" if 월 == 1 else "하반기", 말)
    return "%d %s개월(%s)" % (int(년), 개월글(개월), 말)


def 개월글(개월):
    """개월 → 글 — 정수면 「3」, 아니면 소수 한 자리(달로 안 떨어지는 기간 · 월중 기준일). 5.8 을 「5개월」 로 내리지 않고,
    12 − 8.9 = 3.0999999999999996 같은 부동소수 꼬리를 글에 내지 않는다(1.1.9)."""
    try:
        개 = round(float(개월), 1)
    except (TypeError, ValueError):
        return "%s" % 개월
    return ("%d" % 개) if 개 == int(개) else ("%.1f" % 개)


def 열이름바꾸기(글, 속성, 영구열=None):
    """표 머리줄의 기간 ID(「2H26E」 · 「FY2027E」 · 「TV」 따위)를 열 이름으로 — 머리줄(구분선 바로 앞 줄)만 고친다."""
    아이디 = sorted((k for k in (속성 or {}) if k), key=len, reverse=True)
    if not 아이디:
        return 글
    패 = re.compile(r"(?<![\w가-힣])(%s)(?![\w가-힣])" % "|".join(re.escape(k) for k in 아이디))
    줄 = 글.split("\n")
    for i in range(len(줄) - 1):
        if 줄[i].lstrip().startswith("|") and re.match(r"^\s*\|[\s\-:|]+\|\s*$", 줄[i + 1]):
            줄[i] = 패.sub(lambda m: 열이름(속성, m.group(1), 영구열), 줄[i])
    return "\n".join(줄)


def _해시(가정):
    """워크북마감 의 가정 해시와 같은 셈(정렬한 키 · 공백 없는 JSON 의 sha256)."""
    깨끗 = {k: v for k, v in 가정.items() if not ("%s" % k).startswith("_경로")}
    return hashlib.sha256(json.dumps(깨끗, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")).hexdigest()


def 모델파일확인(엑셀, 마감):
    """평가 모델 파일(--엑셀)이 워크북 마감 기록의 마감본인가 → (같음, 말, 파일 해시).
    같음 = True(마감본과 바이트까지 같다) · False(다르다 — 말에 까닭) · None(파일이 없거나 마감 기록에 파일 해시가 없어 볼 거리가 없다)."""
    if not 엑셀 or not os.path.isfile(엑셀):
        return None, "평가 모델 파일을 주지 않았다", None
    with open(엑셀, "rb") as f:
        h = hashlib.sha256(f.read()).hexdigest()
    기록 = ((마감.get("워크북") or {}).get("파일해시")) if isinstance(마감, dict) else None
    if not 기록:
        return None, "워크북 마감 기록에 마감본의 파일 해시가 없다", h
    if h == 기록:
        return True, "평가 모델 파일 = 마감본(파일 해시 %s)" % h[:12], h
    return False, "평가 모델 파일 %s 이 워크북 마감 기록의 마감본과 다르다(파일 해시 %s · 마감본 %s)" % (
        os.path.basename(엑셀), h[:12], 기록[:12]), h


