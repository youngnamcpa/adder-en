def 반대바꿈(x):
    """반대 논거 한 줄 → [{"손잡이", "x"}] — {"바꿈": [{"가정": 번호 또는 손잡이 이름, "방식": 값 | 가산 | 배율, "값": x}]} (하나면 바꿈 없이 가정 · 방식 · 값)."""
    바 = x.get("바꿈") if isinstance(x.get("바꿈"), list) else [x]
    낸 = []
    for b in 바:
        if not isinstance(b, dict) or b.get("값") is None or b.get("가정") is None:
            raise 레터오류("반대 논거의 바꿈에 가정 · 값이 없습니다 — %s" % (json.dumps(b, ensure_ascii=False)[:80],))
        이 = ("%s" % b["가정"]).strip()
        방 = b.get("방식") or "가산"
        if 이.isdigit() or 이.startswith("WACC."):
            h = {"이름": 이, "대상": [이], "방식": 방}
        else:
            h = dict(_민감도.손잡이풀기(이), 방식=방)
        if b.get("열") is not None:                           # 1.1.7 — 바꿈의 열 지정(그 열들만 — 엔진 손잡이 「열」 · 열별 가정에만 닿는다)
            if not isinstance(b["열"], list) or not b["열"] or not all(isinstance(c, str) and c.strip() for c in b["열"]):
                raise 레터오류("반대 논거 바꿈의 「열」 은 기간 ID 목록이다(예: [\"FY2027E\", \"FY2028E\"]) — %s" % (json.dumps(b, ensure_ascii=False)[:80],))
            h["열"] = [c.strip() for c in b["열"]]
        낸.append({"손잡이": h, "x": float(b["값"])})
    return 낸


