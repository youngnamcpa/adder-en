    d = (오늘 - datetime.date(int(m.group(1)), int(m.group(2)), int(m.group(3)))).days
    if d > 너그러움:
        return ["메타.작성일 %s 이 오늘보다 %d일 이르다 — 지난 회차 날짜가 남았을 수 있다(레터의 「레터 작성」 날짜 · 회차를 시작할 때 오늘로)" % (t, d)]
