def _반올림글(x, 자리):
    """소수 자리 반올림 글 — 사사오입(5.25 → 「5.3」). 「%.1f」 는 짝수 쪽으로 반올림해 5.25 를 「5.2」 로 찍었다(회차 20261023 MO 순단가 5.25%).
    부동소수 잔차(0.0525 × 100 = 5.249999…)는 자리 + 6 에서 먼저 지운다."""
    import decimal                                           # noqa: PLC0415
    d = decimal.Decimal(repr(round(float(x), 자리 + 6))).quantize(decimal.Decimal(1).scaleb(-자리), rounding=decimal.ROUND_HALF_UP)
    return "{:.{}f}".format(d, 자리)


