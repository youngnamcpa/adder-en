def _강조오류(줄):
    자리 = [i for i in range(len(줄) - 1) if 줄[i:i + 2] == "**"]
    난것 = []
    for i in range(0, len(자리) - 1, 2):
        여, 닫 = 자리[i], 자리[i + 1]
        if 줄[여 + 2:여 + 3].isspace():
            난것.append("여는 ** 뒤 공백")
        if 줄[닫 - 1:닫].isspace():
            난것.append("닫는 ** 앞 공백")
    return 난것


