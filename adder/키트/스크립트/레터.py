def _능력필요(원, s, 목표):
    """매출 구분 s 의 모든 라인 생산능력(기간 평균 · 기말)을 모든 예측 열에서 같은 비율로 늘려(설비투자는 그대로) 주당가치 = 목표 가
    되는 최종 예측 연도 말 생산능력. 이미 목표 이상이거나 64배로도 못 닿으면 None."""
    가정 = 원["가정"]
    구분 = next((x for x in (가정.get("구조") or {}).get("매출구분") or [] if x.get("번호") == s), None)
    if not 구분 or 구분.get("판매량산정") != "능력" or 목표 is None:
        return None
    대상 = ["%d" % (668 + 2 * j["번호"]) for j in 구분.get("라인") or []] + ["%d" % (669 + 2 * j["번호"]) for j in 구분.get("라인") or []]
    대상 = [x for x in 대상 if x in (가정.get("가정") or {})]
    if not 대상:
        return None
    h = {"이름": "생산능력", "대상": 대상, "방식": "배율"}

    def f(x):
        return _주당(_민감도.움직이기(가정, h, x, "기준")) - 목표
    lo, hi = 0.0, 1.0
    flo = f(lo)
    if flo >= 0:
        return None
    fhi = f(hi)
    while fhi < 0 and hi < 64:
        lo, flo, hi = hi, fhi, hi * 2
        fhi = f(hi)
    if fhi < 0:
        return None
    for _ in range(100):
        mid = (lo + hi) / 2
        fm = f(mid)
        if fm < 0:
            lo = mid
        else:
            hi = mid
        if hi - lo < 1e-12:
            break
    R = 원["R"]["기준"]
    끝 = R["기간"]["자리"]["예측.끝"]
    return _n(R["4.Sales"]["1%d9" % s][끝]) * (1 + (lo + hi) / 2)


def 능력투자입력(원, s):
    """회차 입력 「능력투자」 에서 매출 구분 s 의 단가 줄 — {"구분": 이름 또는 번호, "단가": 생산능력 1단위당 투자액(가정의 금액 단위), "근거"}."""
    구분들 = (원["가정"].get("구조") or {}).get("매출구분") or []
    이름 = next((("%s" % (x.get("이름") or "")).strip() for x in 구분들 if x.get("번호") == s), "")
    for x in ((원.get("가성") or {}).get("능력투자") or []):
        if not isinstance(x, dict) or _n(x.get("단가")) is None or _n(x.get("단가")) <= 0:
            continue
        k = ("%s" % x.get("구분", "")).strip()
        if k == 이름 or k == "%d" % s:
            return x
    return None


def _능력투자가정(원, s, K):
    """매출 구분 s 에 생산능력 K(최종 예측 연도 말 — 평가기준일부터 고르게 늘린다)를 새 라인으로 더하고, 늘어난 만큼 그 기간에
    설비투자(단가 × 늘어난 생산능력)를 새 프로젝트로 넣은 가정. 프로젝트 속성은 유지 투자의 것(상각개시 · 공제대상 · 환율적용),
    자산군은 유지 기준 자산군. 라인(1~15) · 프로젝트(1~6) 번호가 모자라면 None."""
    입 = 능력투자입력(원, s)
    if 입 is None:
        return None
    a = copy.deepcopy(원["가정"])
    구 = a["구조"]
    구분 = next((x for x in 구.get("매출구분") or [] if x.get("번호") == s), None)
    쓴 = {j["번호"] for x in 구.get("매출구분") or [] for j in x.get("라인") or []}
    j = next((n for n in range(1, 16) if n not in 쓴), None)
    투 = 구.setdefault("투자", {})
    쓴p = {q["번호"] for q in 투.get("프로젝트") or []}
    q = next((n for n in range(1, 7) if n not in 쓴p), None)
    if 구분 is None or j is None or q is None:
        return None
    구분.setdefault("라인", []).append({"번호": j, "이름": "추가 생산능력"})
    속 = 투.get("유지속성") or {}
    투.setdefault("프로젝트", []).append({"번호": q, "이름": "추가 생산능력 설비", "상각개시": 속.get("상각개시", "기말"), "리드타임": 0,
                                    "공제대상": 속.get("공제대상", "예"), "환율적용": 속.get("환율적용", "예")})
    g = 투.get("유지기준자산군") or 1
    a.setdefault("표", {})["%d" % (870 + q)] = dict({"비중%d" % x["번호"]: (1.0 if x["번호"] == g else 0.0) for x in 투.get("자산군") or []},
                                                  리드타임=0)
    P = 원["R"]["기준"]["기간"]
    열 = list(P["묶음"]["예측"])
    끝 = _n(P["속성"][열[-1]]["기말"])
    단가 = _n(입["단가"])
    평, 말, 돈, 앞 = {}, {P["자리"]["기준일"]: 0.0}, {}, 0.0
    for c in 열:
        b = _n(P["속성"][c]["기말"])
        평[c] = K * (앞 + b) / 2 / 끝
        말[c] = K * b / 끝
        돈[c] = 단가 * K * (b - 앞) / 끝
        앞 = b
    a["가정"]["%d" % (668 + 2 * j)] = {"공통": 평}
    a["가정"]["%d" % (669 + 2 * j)] = {"공통": 말}
    a["가정"]["%d" % (860 + q)] = {"공통": 돈}
    return a


def _능력투자셈(원, s):
    """→ {"K": 이 가격에 닿는 추가 생산능력 또는 None, "끝기준": 채택 최종 예측 연도 말 생산능력, "한계": 1단위당 주당가치 변화} 또는 None."""
    캐 = 원.setdefault("_능력투자", {})
    if s in 캐:
        return 캐[s]
    R = 원["R"]["기준"]
    끝열 = R["기간"]["자리"]["예측.끝"]
    끝기준 = _n(((R["4.Sales"].get("1%d9" % s)) or {}).get(끝열))
    목표 = _가성종가(원)
    a0 = _능력투자가정(원, s, 0.0)
    if a0 is None or not 끝기준 or 목표 is None:
        캐[s] = None
        return None
    주0 = _주당(a0)
    K1 = 0.1 * 끝기준
    한계 = (_주당(_능력투자가정(원, s, K1)) - 주0) / K1
    낸 = {"K": None, "끝기준": 끝기준, "한계": 한계}
    if 한계 > 0:
        lo, hi = 0.0, 끝기준
        fhi = _주당(_능력투자가정(원, s, hi)) - 목표
        while fhi < 0 and hi < 64 * 끝기준:
            lo, hi = hi, hi * 2
            fhi = _주당(_능력투자가정(원, s, hi)) - 목표
        if fhi >= 0:
            for _ in range(100):
                mid = (lo + hi) / 2
                if _주당(_능력투자가정(원, s, mid)) < 목표:
                    lo = mid
                else:
                    hi = mid
