def 마감찾기(경로, 지정=None):
    """워크북 마감 기록(`워크북마감.py --출력 X.txt` 가 곁에 낸 X.json). 지정 > 회차 폴더 > 회차 _raw."""
    후보 = [지정] if 지정 else []
    곳 = 회차폴더(경로)
    if 곳 and not 지정:
        후보 += sorted(glob.glob(os.path.join(곳, "*마감*.json")) + glob.glob(os.path.join(곳, "_raw", "*마감*.json")),
                     key=lambda p: -os.path.getmtime(p))
    for p in 후보:
        try:
            d = _읽기(p)
        except Exception:                                    # noqa: BLE001
            continue
        if isinstance(d, dict) and "판정" in d and "가정" in d:
            d["_파일"] = p
            return d
    return None


