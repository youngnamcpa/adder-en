def 식값(식, 원):
    """[연산, 피연산자…] — 피연산자는 키(글) · 수 · 식(목록)."""
    연산, 들 = 식[0], 식[1:]

    def 값(x):
        if isinstance(x, list):
            return 식값(x, 원)
        if isinstance(x, str):
            return _n(키풀기(x, 원))
        return _n(x)
    vs = [값(x) for x in 들]
    if 연산 == "합":
        return None if any(v is None for v in vs) else sum(vs)
    if any(v is None for v in vs):
        return None
    if 연산 == "÷":
        return None if not vs[1] else vs[0] / vs[1]
    if 연산 == "×":
        p = 1.0
        for v in vs:
            p *= v
        return p
    if 연산 == "−":
        return vs[0] - vs[1]
    if 연산 == "괴리":                      # a ÷ b − 1
        return None if not vs[1] else vs[0] / vs[1] - 1
    if 연산 == "음":
        return -vs[0]
    if 연산 == "절대":                     # 레터 v27 6단계 B — 주당가치 폭(괴리의 절대값) · 실적 범위(최대 · 최소)를 표의 칸이 식 키로 부른다
        return abs(vs[0])
    if 연산 == "최대":
        return max(vs)
    if 연산 == "최소":
        return min(vs)
    if 연산 == "CAGR":                     # [끝, 시작, 연수] → (끝 ÷ 시작)^(1 ÷ 연수) − 1 · 연수를 빼면 두 키의 회계연도 차(FY2031E − FY2025A = 6)
        n = vs[2] if len(vs) > 2 else _연수(들[0], 들[1])   # 「매출 추정 절은 스트림마다 CAGR 로 수렴 수준」 — 저자 글이 장부 키로 쓴다
        if not n or n <= 0 or vs[0] <= 0 or vs[1] <= 0:
            return None
        return (vs[0] / vs[1]) ** (1.0 / n) - 1
    raise ValueError("모르는 연산: %s" % 연산)


def _연수(끝키, 시작키):
    """두 장부 키의 마지막 칸이 회계연도 열(FY2031E · FY2025A)이면 그 차 — 아니면 None(반기 열은 연수를 적어 준다)."""
    m1 = re.search(r":FY(\d{4})[AE]$", 끝키) if isinstance(끝키, str) else None
    m2 = re.search(r":FY(\d{4})[AE]$", 시작키) if isinstance(시작키, str) else None
    return (int(m1.group(1)) - int(m2.group(1))) if (m1 and m2) else None


