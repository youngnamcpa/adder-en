def 구조있나(가정):
    return isinstance(가정, dict) and isinstance(가정.get("구조"), dict)


def 옛꼴가정(가정, 실적넘침="오류"):
    """스키마 v13 의 가정 → 15칸 배열 · 옛 키의 꼴. 값은 그대로다(증가율은 전년 대비 그대로). 원본은 건드리지 않는다.

    구조가 있으면 먼저 옛 키로 되돌린다(`옛구조꼴`). `기간` 에는 새 키 넷을 그대로 두고 옛 키(라벨 · 종료일 · 구분 ·
    영구기간길이)를 더한다. `새꼴가정()` 이 되돌린다."""
    if isinstance(가정, dict) and (표식 in 가정 or 옛판인가(가정)):
        return copy.deepcopy(가정)                  # 이미 15칸 배열 꼴이다(옛 판 파일은 값의 뜻도 옛 것 그대로)
    if 구조있나(가정):
        가정 = 옛구조꼴(가정)
    축 = _축(가정)
    자리 = 옛자리(축, 실적넘침)
    g = copy.deepcopy(가정)
    라벨, 종료일, 구분 = [None] * 옛열수, [None] * 옛열수, [None] * 옛열수
    for c, i in 자리.items():
        열 = 축.열[축.위치(c)]
        라벨[i] = 열.표기
        종료일[i] = 열.종료일.isoformat() if 열.종료일 else None
        구분[i] = "영구" if 열.구분 == "영구기간" else 열.구분
    g["기간"] = dict(g["기간"], 라벨=라벨, 종료일=종료일, 구분=구분, 영구기간길이=1)
    for r, v in (가정.get("원천") or {}).items():
        if isinstance(v, dict) and all(k in 축.ID for k in v):
            g["원천"][r] = _펴기(v, 자리, len(실적열))
    for 블록 in ("가정", "연장"):
        for r, 벌 in _번호줄들(가정, 블록):
            for 시, v in 벌.items():
                if isinstance(v, dict):
                    g[블록][r][시] = _펴기(v, 자리)
    for 번, f in enumerate(가정.get("유한현금흐름") or []):
        if isinstance(f, dict):
            for 시, v in (f.get("금액") or {}).items():
                if isinstance(v, dict):
                    g["유한현금흐름"][번]["금액"][시] = _펴기(v, 자리)
    g[표식] = {"축": list(축.ID), "자리": 자리, "종료일": list(종료일)}
    return g


def 새판인가(가정):
    """기간 ID 로 적힌 가정(스키마버전 = 엔진의 것 — v13)이고 아직 15칸 배열로 펴지 않은 것인가."""
    return (isinstance(가정, dict) and 표식 not in 가정
            and str(가정.get("스키마버전") or "") == str(getattr(_엔진, "스키마버전", "") or "\0"))


def 위치꼴(가정, 실적넘침="오류"):
    """**열을 위치로 읽는 소비자가 가정 파일을 읽은 바로 뒤에 부른다**(W2 통합) — 기간 ID 로 적힌 가정(v13)이면 15칸 배열 꼴로
    펴서(`옛꼴가정`) 돌려주고, 그 밖(옛 판 v12 · 이미 편 것 · 스키마버전이 없는 조각이나 더 옛 판)은 받은 그대로 돌려준다.

    값의 뜻은 바뀌지 않는다(v13 의 증가율은 전년 대비 그대로다). 옛 꼴에 담기지 않는 축(실적 열 넷 이상 · 예측 열 열둘 이상)은 다리오류다."""
    return 옛꼴가정(가정, 실적넘침) if 새판인가(가정) else 가정


def _구조세우기(g):
    """옛 키를 가진 기간 ID 의 꼴 → 구조를 가진 v13 (이전 도구의 `구조이전`). 못 옮기면 가정오류."""
    이전도구 = _이전도구()
    try:
        return 이전도구.구조이전(g)[0]
    except 이전도구.이전불가 as e:
        raise 가정오류("가정 JSON 오류 — 옛 키의 가정을 구조(v13)로 옮기지 못했습니다: %s" % e)


def 새꼴가정(가정):
    """옛꼴가정 → 스키마 v13 의 가정(기간 ID · 구조). 옛 판(v12) 파일이면 이전 도구로 옮긴다. 이미 새 꼴이면 그대로 돌려준다.

    기간 부분만 옮긴 v13(구조가 없는 파일)도 받아 구조를 세운다."""
    if 옛판인가(가정):
        return _옮긴(가정)
    if not (isinstance(가정, dict) and 표식 in 가정):
        if isinstance(가정, dict) and not 구조있나(가정) and str(가정.get("스키마버전") or "") == str(getattr(_엔진, "스키마버전", "") or "\0"):
            return _구조세우기(가정)
        return 가정
    g = copy.deepcopy(가정)
    옛 = g.pop(표식)
    자리 = 옛["자리"]
    기간 = dict(g.get("기간") or {})
    받은종료일 = list(기간.get("종료일") or [])
    for k in ("라벨", "종료일", "구분", "영구기간길이"):
        기간.pop(k, None)
    g["기간"] = 기간
    축 = _축(g)
    if list(축.ID) != list(옛["축"]) or 받은종료일 != list(옛["종료일"]):
        raise 다리오류("옛꼴가정의 열이 바뀌었습니다 — 다리로는 열을 바꿀 수 없습니다. 기간.상세추정연수 · 수렴연수 · "
                    "메타.평가기준일 을 고친 새 꼴 가정으로 다시 부르십시오")

    def 접기(배열, 받는):
        배열 = list(배열) + [None] * 옛열수
        return {c: 배열[자리[c]] for c in 받는 if c in 자리}

    실적ID = [축.ID[i] for i in 축.실적]
    예측ID = [축.ID[i] for i in 축.예측]
    for r, v in (g.get("원천") or {}).items():
        if isinstance(v, list):
            g["원천"][r] = 접기(v, 실적ID)
    for 블록 in ("가정", "연장"):
        for r, 벌 in _번호줄들(g, 블록):
            for 시, v in 벌.items():
                if isinstance(v, list):
                    벌[시] = 접기(v, 예측ID + [축.ID[축.영구]])
    for f in g.get("유한현금흐름") or []:
        if isinstance(f, dict):
            for 시, v in (f.get("금액") or {}).items():
                if isinstance(v, list):
                    f["금액"][시] = 접기(v, 예측ID)
    return _구조세우기(g)            # 옛 키(스위치 · 연장 · 유한현금흐름)를 구조로 — 소비자가 옛 키를 고쳤으면 그대로 먹는다


