def 기간옛꼴(기간결과, 실적넘침="오류"):
    """엔진 결과의 「기간」(기간축.사전() + 발생시점 · 적용할인기간) → 옛 `기간계산()` 의 사전."""
    자리 = 옛자리(기간결과, 실적넘침)
    속 = 기간결과["속성"]
    종료일, 길이 = [None] * 옛열수, [None] * 옛열수
    t말, t중, t적용 = ["n/a"] * 옛열수, ["n/a"] * 옛열수, ["n/a"] * 옛열수
    for i in 예측열:
        길이[i] = 0                                      # 쓰지 않는 예측 자리 — 옛 판의 「길이 0」
    적용 = 기간결과.get("적용할인기간") or {}
    for c, i in 자리.items():
        종료일[i] = 속[c]["종료일"]
        길이[i] = 속[c]["년"]
        if 속[c]["기말"] is not None:
            t말[i], t중[i] = 속[c]["기말"], 속[c]["기중"]
            t적용[i] = 적용.get(c, 속[c]["기중"])
    D28 = len(기간결과["묶음"]["예측"])
    return {"종료일": 종료일, "길이": 길이, "t말": t말, "t중": t중, "t적용": t적용,
            "D28": D28, "E28": 1 if D28 else 0,
            "마지막예측": 2 + D28 if D28 else None, "첫예측": 3 if D28 else None}


def 옛꼴(결과, 부호="옛", 실적넘침="오류"):
    """`dcf엔진.계산()` 의 결과(줄 = {기간 ID: 값}) → 옛 꼴(줄 = 15칸 배열). 원본은 건드리지 않는다."""
    if 부호 not in ("옛", "새"):
        raise 다리오류("부호 는 「옛」 또는 「새」 입니다: %r" % (부호,))
    기간결과 = 결과["기간"]
    자리 = 옛자리(기간결과, 실적넘침)
    축ID = 기간결과["열"]
    글자 = lambda c: None if c is None else (열이름[자리[c]] if c in 자리 else c)
    out = {}
    for k, v in 결과.items():
        if k == "기간":
            out[k] = 기간옛꼴(기간결과, 실적넘침)
        elif k in 시트키:
            차감 = _엔진.차감줄.get(k, ()) if 부호 == "옛" else ()
            시트 = {}
            if k == "10.Tax" and isinstance(v.get("34"), dict) and isinstance(v.get("10"), dict):
                # 옛 정의 — 과세표준은 전 열에 선다(예측 열 밖은 10행 그대로). 새 엔진은 워크북의 34행처럼 예측 열에만 싣는다(W3c)
                v = dict(v, **{"34": {c: (v["10"].get(c) if y is None else y) for c, y in v["34"].items()}})
            for 줄, x in v.items():
                if _기간줄인가(x, 축ID):
                    x = _펴기(x, 자리)
                    if 줄 in 차감:
                        x = [None if y is None else -y for y in x]
                elif 줄 in 차감 and isinstance(x, (int, float)) and not isinstance(x, bool):
                    x = -x
                if (k, 줄) in 옛결과키:                 # 번호 키 → 옛 이름(옛 결과에 없던 키는 뺀다)
                    줄 = 옛결과키[(k, 줄)]
                    if 줄 is None:
                        continue
                시트[줄] = x
            out[k] = 시트
        else:
            out[k] = copy.deepcopy(v)
    요약 = out.get("요약")
    if isinstance(요약, dict):
        for 새키, 옛키 in 옛요약키.items():
            if 새키 in 요약:
                v = 요약.pop(새키)
                if 옛키 is not None:
                    요약[옛키] = v
    if isinstance(요약, dict) and "마지막예측열" in 요약:
        요약["마지막예측열"] = 글자(요약["마지막예측열"])
    부수 = out.get("부수")
    if isinstance(부수, dict):
        비중 = 부수.get("영구가치비중")
        if isinstance(비중, dict) and isinstance(비중.get("FCFF음수열"), list):
            비중["FCFF음수열"] = [글자(c) for c in 비중["FCFF음수열"]]
        for 줄 in 부수.get("연장대조표") or []:
            줄["열"] = 글자(줄.get("열"))
        소진 = 부수.get("결손금소진")
        if isinstance(소진, dict) and 소진.get("결손금처리") == "결손금금액":       # 옛 이름 「결손금행」
            소진["결손금처리"] = 옛결손금처리["결손금금액"]
            if isinstance(소진.get("메모"), str):
                소진["메모"] = 소진["메모"].replace("「결손금금액」", "「결손금행」")
        if isinstance(소진, dict):
            for 키 in ("소진열", "세율수렴열"):
                if 키 in 소진:
                    소진[키] = 글자(소진[키])
            for 줄 in 소진.get("표") or []:
                줄["열"] = 글자(줄.get("열"))
    return out


