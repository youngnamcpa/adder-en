def _번호줄들(가정, 블록):
    """그 블록에서 {시나리오: {기간 ID: 값}} 꼴인 번호 줄 — (번호, 벌)."""
    for r, 벌 in (가정.get(블록) or {}).items():
        if str(r).isdigit() and isinstance(벌, dict):
            yield r, 벌


