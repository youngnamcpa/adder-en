def _세벌(벌):
    """`{"공통": 값}` → `{비관, 기준, 낙관}` 세 벌(옛 꼴에는 공통이 없다). 그 밖은 그대로."""
    if isinstance(벌, dict) and "공통" in 벌 and not any(시 in 벌 for 시 in 시나리오목록):
        return {시: copy.deepcopy(벌["공통"]) for 시 in 시나리오목록}
    return 벌


