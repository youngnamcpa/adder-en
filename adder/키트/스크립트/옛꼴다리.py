# ────────────────────────────────────────────────────────────── 자리

def 옛자리(축, 실적넘침="오류"):
    """{기간 ID: 옛 15칸 배열의 자리}. `축` 은 기간축 또는 엔진 결과의 「기간」 사전."""
    if isinstance(축, dict):
        실적, 예측, 영구 = list(축["묶음"]["실적"]), list(축["묶음"]["예측"]), 축["자리"]["영구"]
    else:
        실적, 예측, 영구 = [축.ID[i] for i in 축.실적], [축.ID[i] for i in 축.예측], 축.ID[축.영구]
    if len(실적) > len(실적열):
        if 실적넘침 != "앞버림":
            raise 다리오류("실적 열이 %d개입니다(%s) — 옛 꼴은 셋까지 담습니다. 실적넘침=\"앞버림\" 을 주면 "
                        "가장 오래된 열을 버립니다" % (len(실적), " · ".join(실적)))
        실적 = 실적[-len(실적열):]
    if len(예측) > len(예측열):
        raise 다리오류("예측 열이 %d개입니다 — 옛 꼴은 %d개까지 담습니다" % (len(예측), len(예측열)))
    자리 = {}
    for k, c in enumerate(실적):
        자리[c] = len(실적열) - len(실적) + k
    for k, c in enumerate(예측):
        자리[c] = 예측열[0] + k
    자리[영구] = 영구열
    return 자리


def _펴기(사전, 자리, 길이=옛열수):
    v = [None] * 길이
    for c, x in (사전 or {}).items():
        if c in 자리 and 자리[c] < 길이:
            v[자리[c]] = x
    return v


def _기간줄인가(v, 축ID):
    return isinstance(v, dict) and len(v) > 0 and all(k in 축ID for k in v)


