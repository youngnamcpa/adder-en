def 기본글꼴(wb):
    """통합 문서의 기본 글꼴(표준 스타일)을 맑은 고딕 10pt 로 바꾼다. 열 폭 단위가 이 글꼴을 따른다.

    Normal 스타일의 글꼴만 바꾸면 스타일 없는 칸은 Calibri 11pt 로 남는다 — 통합 문서의 첫 글꼴(wb._fonts)을 바꾼다."""
    기본 = Font(name=글꼴이름, size=글꼴크기, family=2)
    wb._fonts = IndexedList([기본])
    wb._named_styles["Normal"].font = 기본
    wb._named_styles["Normal"].bind(wb)


def 스타일등록(wb):
    있는 = set(wb.named_styles)
    for s in 스타일목록():
        if s.name not in 있는:
            wb.add_named_style(s)


