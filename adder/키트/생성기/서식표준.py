    # 긴 글도 세로 가운데다 — 초안은 「왼쪽·위」였으나, 줄이 높아지면 같은 줄의 행 이름 · 값(세로 가운데)과 글의 첫 줄이 어긋난다
    긴글 = Alignment(horizontal="left", vertical="center", wrap_text=True)
    상자 = Border(left=_옅은, right=_옅은, top=_옅은, bottom=_옅은)
    S = []

    def 더하기(name, font, fill=None, border=None, alignment=None, number_format="General"):
        s = NamedStyle(name=name, font=font, number_format=number_format)
        if fill is not None:
            s.fill = fill
        if border is not None:
            s.border = border
        if alignment is not None:
            s.alignment = alignment
        S.append(s)

    # 글
    더하기("글_제목", _글꼴(size=제목크기, b=True), alignment=왼)
    더하기("글_부제", _글꼴(color=색["회색글"]), alignment=왼)
    더하기("글_구획", _글꼴(b=True), fill=_바탕(색["구획바탕"]), alignment=왼)
    더하기("글_소구획", _글꼴(b=True), border=Border(bottom=_옅은), alignment=왼)
    더하기("글_행이름", _글꼴(), alignment=왼, number_format="@")
    # 값 열에 놓인 둘째 이름(한 줄에 「이름 · 값 · 둘째 이름 · 값」을 나란히 둔 줄) — 값 열의 폭 안에서 줄바꿈한다
    더하기("글_곁이름", _글꼴(), alignment=긴글, number_format="@")
    더하기("글_단위", _글꼴(color=색["회색글"]), alignment=가운데, number_format="@")
    더하기("글_번호", _글꼴(color=색["회색글"]), alignment=가운데, number_format="@")
    더하기("글_출처", _글꼴(color=색["회색글"]), alignment=긴글, number_format="@")
    더하기("글_주석", _글꼴(color=색["회색글"]), alignment=왼, number_format="@")
    # 머리
