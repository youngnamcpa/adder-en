def 판정규칙(첫칸):
    """판정 칸의 조건부 서식 규칙 둘 — Error 빨강 · Review 주황. 수식은 범위 첫 칸을 기준으로 적는다(같은 시트의 칸만 읽는다).

    옛 판정 글(「확인 필요 — …」「신호 — …」)도 같은 색으로 알아본다. OK · N/A 는 물들이지 않는다."""
    규칙 = []
    for 표시 in ("Error", "Review"):
        글색, 바탕 = 점검색[표시]
        식 = "OR(%s)" % ",".join('LEFT(%s&"",%d)="%s"' % (첫칸, len(머리), 머리) for 머리 in 판정머리[표시])
        규칙.append(FormulaRule(formula=[식], font=Font(color=글색, b=True), fill=_바탕(바탕)))
    return 규칙


