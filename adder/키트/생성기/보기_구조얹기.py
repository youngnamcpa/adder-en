def 얹기(폴더):
    """정본의 사본(폴더)에 보기 줄을 얹는다."""
    if os.path.isdir(폴더):
        shutil.rmtree(폴더)
    shutil.copytree(os.path.join(생성기, "줄명세"), 폴더)
    책곳 = os.path.join(폴더, "책.json")
    with io.open(책곳, encoding="utf-8") as f:
        책 = json.load(f, object_pairs_hook=OrderedDict)
    # 정본의 되풀이 변수는 그대로 두고 보기의 것을 더한다(맞물림 2 — 바꿔 끼우면 묶음이 정본에 더한 변수 u · r … 를 읽는 줄이
    # 「되풀이 변수를 모른다」로 멈췄다). 같은 글자를 다른 뜻으로 쓰면 멈춘다
    되 = OrderedDict(책.get("되풀이") or {})
    for 글자, 뜻 in 되풀이.items():
        if 되.get(글자, 뜻) != 뜻:
            raise 배치오류([{"종류": "되풀이", "시트": None, "자리": 글자, "설명": "보기의 되풀이 변수 「%s」(%s)를 정본이 다른 뜻(%s)으로 쓴다" % (글자, 뜻, 되[글자])}])
        되[글자] = 뜻
    책["되풀이"], 책["구조기본"] = 되, 구조기본
    with io.open(책곳, "w", encoding="utf-8", newline="\n") as f:
        json.dump(줄무늬._차례(책, 줄무늬.책열쇠), f, ensure_ascii=False, indent=1)
        f.write("\n")
    for 시트 in ("S12", "S04"):
        경로 = os.path.join(폴더, 시트 + ".jsonl")
        머리, 줄들 = 줄무늬.시트읽기(경로)
        새 = []
        for 줄 in 줄들:
            새.append(줄)
        # 맞물림 2 — 정본에 이미 같은 ID 의 줄이 있으면(W5a 가 이 보기를 본떠 4번 · 12번의 수준 경로 줄과 표 T1 을, W5b 가 12번 86p 를
        # 올렸다) 보기의 줄은 얹지 않는다 — 정본의 줄로 같은 짓기(번호 열 · 세 줄 접기 · 표 구획 · 구조가 고른 줄)를 본다. 표도 없을 때만 더한다
        있는 = {줄.get("id") for 줄 in 새}
        if 시트 == "S12":
            표 = OrderedDict(머리.get("표") or {})
            if "T1" in 표:                    # 정본의 표 T1(W5a)이 있으면 보기의 표머리 · 빈줄도 얹지 않는다(표 구획에 머리 줄이 둘 서지 않게)
                있는 |= {"S12R698", "S12R699"}
            표.setdefault("T1", T1)
            머리["표"] = 표
            끝of = {}
            for i, 줄 in enumerate(새):
                끝of[줄.파일] = i
            for 파일, 덧 in (("S12_투자.jsonl", 투자줄), ("S12_매출.jsonl", 매출줄)):      # 뒤 조각부터 끼운다(앞 자리가 밀리지 않게)
                자리 = 끝of[파일] + 1
                for 한 in [x for x in 덧 if x["id"] not in 있는]:
                    낸 = 줄무늬.날줄(한)
                    낸.파일 = 파일
                    새.insert(자리, 낸)
                    자리 += 1
        else:
            새 += [줄무늬.날줄(한) for 한 in 계산줄 if 한["id"] not in 있는]
        줄무늬.시트쓰기(경로, 머리, 새)
    명 = 줄무늬.읽기(폴더, 옛서식=False, 덧파일=배치_납품.새시트파일)
    적었나, 바뀐, 구조오류 = 범위지문.승인(명, 위치범위=True)
    return 적었나, 바뀐, 구조오류


