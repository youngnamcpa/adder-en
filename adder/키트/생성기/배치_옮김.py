    줄, 구획, 지금 = 명["행"], [], None
    for r in 줄:
        if r.get("종류") == "구획머리":
            if 지금:
                구획.append(지금)
            지금 = [r["id"]] if (r.get("이름") or "").strip().startswith("검증") else None
        elif 지금 is not None:
            지금.append(r["id"])
    if 지금:
        구획.append(지금)
    점검 = {r["id"] for r in 줄 if r.get("종류") == "점검"}
    for 한 in 구획:                              # 구획의 끝 = 마지막 점검 줄(그 아래의 보조 계산 줄·빈 줄은 두고 간다)
        while 한 and 한[-1] not in 점검:
            한.pop()
    return [한 for 한 in 구획 if 한]


