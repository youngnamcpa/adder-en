def 시트열표(sid, 열수, 쓸표=None):
    """시트의 열 등록부를 만든다. → (열 목록 [{id, 옛, 종류}], 표). 표가 없는 시트는 옛 열 글자가 열 ID 다."""
    표 = (시트표 if 쓸표 is None else 쓸표).get(sid)
    열 = []
    for n in range(1, 열수 + 1):
        글 = 열글자(n)
        if 표 is None:
            열.append({"id": 글, "옛": 글, "종류": "기타"})
        elif n <= len(표["열"]):
            열.append({"id": 표["열"][n - 1][0], "옛": 글, "종류": 표["열"][n - 1][1]})
        else:
            열.append({"id": "열" + 글, "옛": 글, "종류": "기타"})
    return 열, (표 or _표([]))


