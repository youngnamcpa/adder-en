def 서식풀이(책):
    """서식 조합 번호 → {채움, 굵게, 글자색, 크기, 숫자} (줄 종류를 가늠하는 재료)."""
    표, 풀이 = 책["서식표"], []

    def 색(글):
        m = re.search(r'fgColor rgb="FF([0-9A-Fa-f]{6})"', 글)
        return m.group(1).upper() if m else None

    for f, p, b, a, pr, nf, qp in 책["서식조합"]:
        글꼴 = 표["글꼴"][f]
        m색 = re.search(r'<color rgb="FF([0-9A-Fa-f]{6})"', 글꼴)
        m크 = re.search(r'<sz val="([0-9.]+)"', 글꼴)
        풀이.append({"채움": 색(표["채움"][p]), "굵게": '<b val="1"' in 글꼴,
                   "글자색": m색.group(1).upper() if m색 else None,
                   "크기": float(m크.group(1)) if m크 else None, "숫자": 표["숫자서식"][nf]})
    return 풀이


def 서식이름(숫자서식):
    """옛 숫자 서식 글 → 서식표준의 서식 이름(가까운 것)."""
    f = 숫자서식 or "General"
    if f == "General":
        return "일반"
    if f == "@":
        return "글"
    if "yy" in f:
        return "날짜"
    if '"x"' in f:
        return "배수"
    if '"p"' in f:
        return "포인트"
    if "%" in f:
        return "비율2" if f.startswith("0.00%") else "비율"
    if f.startswith("#,##0.0"):
        return "금액1"
    if f.startswith("#,##0"):
        return "금액"
    if f.startswith("0.0000"):
        return "계수"
    if f.startswith("0.000"):
        return "베타"
    if f.startswith("0.00"):
        return "연수"
    if f.startswith("0.0"):
        return "일수"
    if f == "0":
        return "개월"
    return "일반"


